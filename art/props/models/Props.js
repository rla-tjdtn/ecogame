const { T, Rx, Ry, Rz, roundRect, circle2, arc2 } = require('../lib/model.js');

// 바닥에 눕힌 판(xz 평면 다각형 → y0 에서 위로 h). poly 점 = [x, z]
const flat = (m, poly, y0, h, o = {}) => m.with(Rx(-Math.PI / 2), () => m.extrude(poly.map(([x, z]) => [x, -z]), h, { z0: y0, ...o }));
// 옆에서 본 판(zy 평면 다각형 → x 를 가운데로 두께 t). poly 점 = [z, y]
const side = (m, poly, x, t, o = {}) => m.with(T(x, 0, 0).mul(Ry(-Math.PI / 2)), () => m.extrude(poly, t, { z0: -t / 2, ...o }));
// 앞에서 본 판(xy 평면 다각형 → z 를 가운데로 두께 t). poly 점 = [x, y]
const front = (m, poly, z, t, o = {}) => m.extrude(poly, t, { z0: z - t / 2, ...o });
const rect = (x0, y0, x1, y1) => [[x0, y0], [x1, y0], [x1, y1], [x0, y1]];
const rod = (m, a, b) => m.cyl(a, b, 0.06, { line: true });
// 상자(골판지) + 위 테이프 한 줄
function carton(m, x, y0, z, sx, h, sz, yaw = 0) {
  m.with(T(x, y0, z).mul(Ry(yaw)), () => {
    m.slab(0, 0, 0, sx, h, sz);
    m.line([[0, h + 0.01, -sz / 2], [0, h + 0.01, sz / 2]]);
  });
}

