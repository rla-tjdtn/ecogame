// 챕터 6 폐호텔 소품 메시. 좌표 = PropMesh.dress 에 넘긴 소품 좌표계(스터드, y 위, -z = 소품이 보는 쪽).
const { T, Rx, Ry, Rz, S, roundRect, circle2, arc2 } = require('../lib/model.js');
const L1 = { line: true };                 // 가는 막대 = 선 한 줄
const RING = { caps: false, silhouette: false, rings: [0.5] }; // 원 한 줄(바퀴·손잡이 고리)

// 사각형 홈(면 위 장식 선): 가운데 (cx, cy), 크기 w×h, z 에 붙임(xy 평면)
function rectXY(m, cx, cy, w, h, z) { m.line([[cx - w / 2, cy - h / 2, z], [cx + w / 2, cy - h / 2, z], [cx + w / 2, cy + h / 2, z], [cx - w / 2, cy + h / 2, z]], { closed: true }); }
// 바퀴(옆에서 원 한 줄 + 축 막대): 가운데 c, 반지름 r, 굴대 x 방향
function caster(m, x, z, r = 0.25) {
  m.cyl([x - 0.07, r, z], [x + 0.07, r, z], r, RING);
  m.cyl([x, r, z], [x, r + 0.35, z], 0.05, L1);
}

// ── 프런트 데스크(칸 한 토막, x -4..4, -z = 손님 쪽) ──
function frontDesk(m, endL, endR, bell) {
  const L = 8;
  const x0 = endL ? -3.6 : -4, x1 = endR ? 3.6 : 4, w = x1 - x0, xc = (x0 + x1) / 2;
  // 앞 판 + 걸레받이(발판 띠) + 높은 접수대(앞으로 튀어나온 상판)
  m.box([xc, 2.0, -0.9], [w, 4.0, 0.5], { lines: 'X' });
  m.box([xc, 0.2, -1.25], [w, 0.4, 0.2], { lines: 'X' });
  m.box([0, 4.1, -0.9], [L, 0.2, 1.3], { lines: 'X', bevel: 0.05 });
  // 앞 판의 세로 판 홈(칸마다 둘) + 가로 띠 홈
  for (const cx of [-2, 2]) rectXY(m, cx, 2.2, 3.3, 2.8, -1.16);
  // 직원 작업대 + 서랍장(작업대 아래 오른쪽) + 무릎 공간 뒤 칸막이
  m.box([0, 2.8, 0.45], [L, 0.2, 2.1], { lines: 'X' });
  m.box([2.6, 1.35, 0.5], [1.6, 2.7, 1.8], { lines: 'Y' });
  for (const y of [0.9, 1.8]) m.line([[1.8, y, -0.41], [3.4, y, -0.41]].map(([x, yy]) => [x, yy, 1.41]));
  // (서랍 손잡이)
  for (const y of [0.45, 1.35, 2.25]) m.line([[2.35, y, 1.42], [2.85, y, 1.42]]);
  // 모니터 + 받침 + 자판
  m.with(T(0.6, 2.9, 0.6).mul(Ry(0.25)), () => {
    m.box([0, 1.0, 0], [1.6, 1.0, 0.1], { lines: 'XY' });
    m.box([0, 0.03, 0], [0.6, 0.06, 0.45], { lines: 'none' });
    m.cyl([0, 0.06, 0.02], [0, 0.5, 0.02], 0.06, L1);
    m.box([0.1, 0.03, -0.75], [1.2, 0.06, 0.4], { lines: 'X' });
  });
  if (bell) { m.lathe([[0.25, 0], [0.24, 0.12], [0.12, 0.26], [0, 0.29]], { at: [-1.5, 4.2, -1.1], seg: 10, crease: 80 }); m.cyl([-1.5, 4.49, -1.1], [-1.5, 4.6, -1.1], 0.03, L1); }
  // 줄 끝 옆판(두툼한 판, 앞 모서리 둥근 윤곽)
  for (const [on, s] of [[endL, -1], [endR, 1]]) if (on) {
    m.with(T(s * 3.8, 0, -0.2).mul(Ry(Math.PI / 2)), () => m.extrude([[1.3, 0], [1.3, 4.2], [-1.3, 4.2], [-1.3, 0]], 0.4, { caps: true, sides: true }));
  }
}

// ── 호텔 침대 하나(머리판 +z 벽, 가운데 x, 폭 w) ──
function hotelBed(m, x, w) {
  const z0 = -2.75, z1 = 3.65;
  // 받침(바닥에서 조금 뜬 침대 밑판) + 매트리스 + 흘러내린 이불
  m.box([x, 0.5, 0.45], [w - 0.3, 0.8, 6.2], { lines: 'XZ' });
  m.box([x, 1.3, 0.45], [w - 0.1, 0.8, 6.3], { bevel: 0.12, lines: 'none' });
  // 이불: 위 덮개 + 발치·옆으로 흘러내린 자락
  m.cushion([x, 1.62, -0.15], [w, 0.36, 5.2], 0.14, { lines: 'top' });
  m.line([[x - w / 2 - 0.01, 0.9, z0 + 0.05], [x - w / 2 - 0.01, 1.4, z0 + 0.05]]);
  // 발치 러너(가로 띠) + 접힌 이불 끝
  m.line([[x - w / 2, 1.81, -1.9], [x + w / 2, 1.81, -1.9]]);
  m.line([[x - w / 2, 1.81, 2.2], [x + w / 2, 1.81, 2.2]]);
  // 베개(폭 넓으면 둘)
  const n = w > 4 ? 2 : 1, pw = (w - 0.6) / n;
  for (let k = 0; k < n; k++) m.cushion([x - (w - 0.6) / 2 + pw * (k + 0.5), 1.98, 2.9], [pw - 0.15, 0.42, 1.0], 0.18, { lines: 'top' });
  // 머리판: 위가 둥근 천 씌운 판 + 단추 홈 가로 선 둘
  m.with(T(x, 0, 3.8), () => {
    m.extrude(roundRect(w + 0.2, 3.4, 0.35, 2).map(([a, b]) => [a, b + 2.4]), 0.3, { caps: 'front', z0: -0.15 });
    m.line([[-w / 2 + 0.2, 3.1, -0.16], [w / 2 - 0.2, 3.1, -0.16]]);
  });
}
