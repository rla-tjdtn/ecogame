// xy 평면 사각 윤곽(z 고정)
const rectXY = (m, x0, y0, x1, y1, z) => m.line([[x0, y0, z], [x1, y0, z], [x1, y1, z], [x0, y1, z]], { closed: true });

// 해골: 머리통 공 + 눈구멍 둘(짧은 선) + 턱 아래 선. out = 바라보는 쪽 부호(+1: +z, -1: -z)
function skull(m, x, y, z, r, out) {
  m.sphere([x, y, z], r);
  const f = z + out * r * 1.0;
  for (const s of [-1, 1]) m.line([[x + s * r * 0.55, y + r * 0.05, f], [x + s * r * 0.12, y - r * 0.12, f]]);
}

// 엇갈린 뼈 두 개(X) — 끝마다 두 갈래 관절 머리. 면 z 위 가운데 (cx, cy), 반폭 w, 반높이 h
function crossBones(m, cx, cy, w, h, z) {
  for (const s of [-1, 1]) {
    const a = [cx - w, cy - s * h, z], b = [cx + w, cy + s * h, z];
    m.line([a, b]);
    for (const [p, d] of [[a, -1], [b, 1]]) {
      const L = Math.hypot(w, h), ux = d * w / L, uy = d * s * h / L, k = 0.17;
      m.line([[p[0] + (ux - uy) * k, p[1] + (uy + ux) * k, z], [p[0], p[1], z], [p[0] + (ux + uy) * k, p[1] + (uy - ux) * k, z]]);
    }
  }
}

// 불규칙한 바위(7각 기둥, 위아래 윤곽 + 옆 꺾임). w,h = 반지름 비율, d = 두께
function rock(m, xf, w, h, d, seed) {
  const pts = [];
  for (let i = 0; i < 7; i++) { const a = i / 7 * Math.PI * 2 + seed; const k = 0.78 + 0.22 * Math.sin(seed * 3 + i * 2.3); pts.push([Math.cos(a) * w * k, Math.sin(a) * h * k]); }
  m.with(xf, () => m.extrude(pts, d, { crease: 20 }));
}

