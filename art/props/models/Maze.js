// (dir = -1: -z 쪽에서 읽는 글 → x 를 뒤집는다)
function text(m, str, cx, cy, z, hgt, track = 1, dir = 1) {
  const adv = c => (ADV[c] ?? 0.85) * hgt * track;
  let w = 0; for (const c of str) w += adv(c);
  let x = cx - w / 2;
  for (const c of str) { for (const st of FONT[c] || []) m.line(st.map(([u, v]) => [dir * (x + u * hgt), cy + (v - 0.5) * hgt, z])); x += adv(c); }
}

