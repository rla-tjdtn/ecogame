function conveyorRun(m, legs) {
  const L = 16 * legs - 0.4, n = 2 * legs;
  m.mirrorX(() => {
    m.box([1.7, 3.0, 0], [0.2, 0.6, L], { lines: 'none' });
    m.line([[1.8, 3.3, -L / 2], [1.8, 3.3, L / 2]]);
    m.line([[1.8, 2.7, -L / 2], [1.8, 2.7, L / 2]]);
  });
  m.box([0, 3.05, 0], [3.2, 0.15, L], { lines: 'none' }); // 벨트
  for (const s of [-1, 1]) m.cyl([-1.6, 3.0, s * (L / 2 - 0.25)], [1.6, 3.0, s * (L / 2 - 0.25)], 0.25, { caps: false });
  for (let k = 0; k <= legs; k++) {
    const t = -L / 2 + 0.4 + (L - 0.8) * k / legs;
    m.mirrorX(() => { m.box([1.5, 1.35, t], [0.25, 2.7, 0.25], { lines: 'none' }); m.line([[1.62, 0, t], [1.62, 2.7, t]]); });
    m.line([[-1.5, 0.7, t], [1.5, 0.7, t]]);
  }
  // 구동부(가운데 아래 모터 상자)
  m.box([0, 2.25, 0], [1.6, 0.9, 1.6], { lines: 'Y' });
  m.cyl([0.8, 2.2, 0], [1.5, 2.2, 0], 0.35, { caps: false });
  for (let k = 0; k < n; k += 3) {
    const h = rnd(k, 3, legs);
    m.with(T(0, 3.13, -L / 2 + (k + 0.3 + h * 0.4) * 8).mul(Ry((h - 0.5) * 0.5)), () => m.box([0, 0.75, 0], [2.0, 1.5, 2.2]));
  }
}

