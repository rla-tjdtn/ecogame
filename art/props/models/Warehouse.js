const { T, Rx, Ry, Rz, S, arc2 } = require('../lib/model.js');

const WHEEL = { caps: false, silhouette: false, rings: [1] }; // 바퀴: 바깥 면 원 한 줄
const ROD = { line: true };                                    // 가는 막대 = 선 한 줄
const rnd = (a, b, c) => { const s = Math.sin(a * 12.9898 + b * 78.233 + c * 37.719) * 43758.5453; return s - Math.floor(s); };

// 옆모습(z, y) 다각형을 x0..x1 폭으로 밀어낸 몸(차체·포크·좌석)
function side(m, zy, x0, x1, o = {}) {
  m.with(Ry(Math.PI / 2), () => m.extrude(zy.map(([z, y]) => [-z, y]), x1 - x0, { z0: x0, ...o }));
}
// 닫힌 사각 선(가로 a 축, 세로 b 축) — 판 위 표시·창
const rectXY = (m, x0, x1, y0, y1, z) => m.line([[x0, y0, z], [x1, y0, z], [x1, y1, z], [x0, y1, z]], { closed: true });

// ── 팔레트 랙(선택식, 등을 맞댄 두 줄이면 줄마다 앞·뒤 기둥) ──
// b = 기둥 칸 수(칸 길이 16 기준, 빌더가 실제 길이에 맞춰 Z 로 늘인다), deep = 1(한 줄) | 2(등 맞댄 두 줄)
function rack(m, b, deep) {
  const L = 16 * b - 0.6, D = 8 * deep - 2.4, H = 10.2, xo = D / 2 - 0.15;
  const rows = deep === 1 ? [[-xo, xo]] : [[-xo, -xo + 5.3], [xo - 5.3, xo]];
  const ts = []; for (let k = 0; k <= b; k++) ts.push(-L / 2 + 0.15 + (L - 0.3) * k / b);
  const aisle = (x) => deep === 1 || Math.abs(x) > xo - 0.01; // 통로 쪽 면
  for (const [x0, x1] of rows) {
    const cx = (x0 + x1) / 2;
    for (const t of ts) {
      // 세움틀: 앞·뒤 기둥(선 한 줄씩) + 지그재그 가새
      for (const x of [x0, x1]) {
        const sx = x > cx ? 1 : -1;
        m.box([x, H / 2, t], [0.3, H, 0.3], { lines: 'none' });
        m.line([[x + sx * 0.15, 0, t], [x + sx * 0.15, H, t]]);
      }
      const a = x0 + 0.15, c = x1 - 0.15;
      m.line([[a, 0.5, t], [c, 3.6, t], [a, 6.8, t], [c, 9.9, t], [a, 9.9, t]]);
    }
    // 보(3.6, 7.0): 통로 쪽은 위·아래 두 줄, 안쪽(맞댄 쪽)은 위 한 줄
    for (const y of [3.6, 7.0]) for (const x of [x0, x1]) {
      const sx = x > cx ? 1 : -1, xf = x + sx * 0.135;
      m.box([x, y, 0], [0.27, 0.4, L], { lines: 'none' });
      m.line([[xf, y + 0.2, -L / 2], [xf, y + 0.2, L / 2]]);
      if (aisle(x)) m.line([[xf, y - 0.2, -L / 2], [xf, y - 0.2, L / 2]]);
    }
  }
  // 짐(팔레트 위 상자 더미): 칸마다 정해진 무늬로 비거나 찬다. 바닥 짐은 바닥에 바로
  const n = 2 * b;
  for (let k = 0; k < n; k++) for (const [ri, [x0, x1]] of rows.entries()) {
    const cx = (x0 + x1) / 2;
    [[0.0, 0.42], [3.8, 0.3], [7.2, 0.2]].forEach(([y, p], li) => {
      const h = rnd(k, li, ri + deep * 3 + b * 7);
      if (h > p * (deep === 1 ? 1.9 : 1.15)) return;
      const z = -L / 2 + (k + 0.5) * 8 + (h - p / 2) * 0.8, tall = 1.6 + rnd(k, li, 9) * 0.6;
      m.with(T(cx, y, z).mul(Ry((rnd(k, li, 5) - 0.5) * 0.12)), () => {
        m.box([0, 0.22, 0], [4.6, 0.44, 6.2], { lines: 'none' });   // 팔레트(보 위 검은 띠)
        m.box([0, 0.44 + tall / 2, 0], [4.3, tall, 5.8]);            // 상자 더미
      });
    });
  }
}

// ── 박스 흐름 선반(피킹): 판이 앞(+x)으로 기운 3단, 판 위에 미끄러져 내려온 상자들 ──
function flow(m, b, deep) {
  const L = 16 * b - 0.6, D = 8 * deep - 3.0, H = 7.2, xo = D / 2 - 0.15, tilt = 0.6;
  const ts = []; for (let k = 0; k <= b; k++) ts.push(-L / 2 + 0.15 + (L - 0.3) * k / b);
  for (const t of ts) for (const x of [-xo, 0, xo]) {
    m.box([x, H / 2, t], [0.3, H, 0.3], { lines: 'none' });
    m.line([[x + (x < 0 ? -0.15 : 0.15), 0, t], [x + (x < 0 ? -0.15 : 0.15), H, t]]);
  }
  const ang = Math.atan2(tilt, 2 * xo);
  for (const y of [1.2, 3.4, 5.6]) {
    // 앞 보(낮은 쪽, 집는 면) 위·아래 두 줄 / 뒤 보(높은 쪽) 한 줄 / 기운 판(몸만) / 칸 끝 기운 옆테
    m.box([xo, y, 0], [0.27, 0.4, L], { lines: 'none' });
    m.line([[xo + 0.135, y + 0.2, -L / 2], [xo + 0.135, y + 0.2, L / 2]]);
    m.line([[xo + 0.135, y - 0.2, -L / 2], [xo + 0.135, y - 0.2, L / 2]]);
    m.box([-xo, y + tilt, 0], [0.27, 0.4, L], { lines: 'none' });
    m.line([[-xo - 0.135, y + tilt + 0.2, -L / 2], [-xo - 0.135, y + tilt + 0.2, L / 2]]);
    m.with(T(0, y + tilt / 2 + 0.15, 0).mul(Rz(-ang)), () => m.box([0, 0, 0], [2 * xo, 0.1, L], { lines: 'none' }));
    for (const t of ts) m.line([[-xo, y + tilt + 0.25, t], [xo, y + 0.25, t]]);
  }
  // 상자: 칸·단마다 0~2개, 앞(낮은 쪽)부터 줄지어
  const n = 2 * b;
  for (let k = 0; k < n; k++) [1.2, 3.4, 5.6].forEach((y, li) => {
    const h = rnd(k, li, 41 + b);
    const cnt = h < 0.15 ? 0 : h < 0.45 ? 1 : h < 0.8 ? 2 : 3;
    for (let q = 0; q < cnt; q++) {
      const x = xo - 1.5 - q * 2.6, yb = y + 0.2 + tilt * (xo - x) / (2 * xo) + 0.1;
      const z = -L / 2 + (k + 0.5) * 8 + (rnd(k, li, q) - 0.5) * 2.4;
      m.with(T(x, yb, z).mul(Rz(-ang)).mul(Ry((rnd(q, k, li) - 0.5) * 0.15)), () => m.box([0, 0.7, 0], [2.4, 1.4, 2.6]));
    }
  });
}

