function stanchion(two, belt) {
  return (m) => {
    // 원점 = 칸 가운데(세계 축), 기둥 x -3.5(+ 다음 칸이 기둥이 아니면 3.5)
    const post = (x) => {
      m.cyl([x, 0, 0], [x, 0.08, 0], 0.6, WHEEL); m.cone([x, 0.08, 0], [x, 0.3, 0], 0.55, 0.14, { lines: 'none' }); // 받침
      m.cyl([x, 0.3, 0], [x, 2.98, 0], 0.12, { caps: false }); m.cyl([x, 2.98, 0], [x, 3.3, 0], 0.2, { rings: [0] }); // 기둥 + 띠 감개 머리
    };
    post(-3.5);
    if (two) post(3.5);
    if (belt === 'Belt') {
      m.line([[-3.32, 3.05, 0], [3.32, 3.05, 0]]); m.line([[-3.32, 2.82, 0], [3.32, 2.82, 0]]);
      m.box([0, 2.93, 0], [6.6, 0.23, 0.04], { lines: 'none', solid: false });
    } else if (belt === 'Sag') {
      // 한쪽이 풀려 바닥까지 늘어진 띠
      const pts = []; for (let i = 0; i <= 8; i++) { const t = i / 8; pts.push([-3.32 + t * 5.2, 3.0 - 2.7 * Math.sin(t * PI / 2) ** 1.4, 0]); }
      pts.push([2.6, 0.05, -0.4]);
      m.line(pts); m.line(pts.map(([x, y, z]) => [x + 0.12, y - 0.2, z]).slice(0, 8));
    }
  };
}

