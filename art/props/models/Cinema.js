// ── 극장 의자 한 줄(가운데 원점, 바닥 y 0, -z = 스크린) ──
// xs = 의자 가운데 x 목록, w = 의자 폭, arms = 팔걸이 기둥 x, fold = 접혀 올라간 의자 번호
function seatRow(m, xs, w, arms, fold = []) {
  xs.forEach((cx, k) => {
    if (fold.includes(k)) pad(m, [cx, 1.75, 0.42], [w - 0.4, 1.6, 0.4], 0.12, { lines: 'X' }); // 접힌 앉는 판
    else pad(m, [cx, 1.45, -0.2], [w - 0.4, 0.45, 1.8], 0.14, { lines: 'X' });
    m.with(T(cx, 1.6, 0.72).mul(Rx(0.18)), () => {
      plate(m, roundRect(w - 0.3, 2.55, 0.5, 1).map(([x, y]) => [x, y + 1.275]), 0, 0.5); // 등받이(뒤 윤곽)
      m.line([[-(w - 0.9) / 2, 0.55, -0.02], [(w - 0.9) / 2, 0.55, -0.02]]); // 등받이 아래 이음매
    });
  });
  // 팔걸이 기둥(옆판 + 팔걸이): 옆에서 본 윤곽 한 줄
  const prof = [[-0.45, 0], [0.95, 0], [0.95, 2.1], [0.75, 2.35], [-0.95, 2.35], [-1.05, 2.2], [-0.95, 2.06], [-0.45, 1.85]].map(([z, y]) => [-z, y]);
  for (const x of arms) m.with(T(x, 0, 0).mul(Ry(PI / 2)), () => plate(m, prof, -0.11, 0.22));
}

