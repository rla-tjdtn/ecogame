// 글자 줄: c = 가운데, h = 글자 높이, face = -1 이면 -z 쪽에서 읽힌다(그쪽에서 보면 +x 가 왼쪽)
function text(m, str, c, h, face = -1) {
  const w = 0.6 * h, gap = 0.28 * h, total = str.length * w + (str.length - 1) * gap;
  const dir = face < 0 ? -1 : 1;
  let x = -total / 2;
  for (const ch of str) {
    for (const stroke of GLYPH[ch] || []) m.line(stroke.map(([u, v]) => [c[0] + dir * (x + u * h), c[1] - h / 2 + v * h, c[2]]));
    x += w + gap;
  }
}
// 축 방향 판(두께 d)을 윤곽 한 줄로: xy 다각형을 z0..z0+d 로
const plate = (m, poly, z0, d, caps = 'front') => m.extrude(poly, d, { z0, caps });
