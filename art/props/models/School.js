function trophyCase(m, h) {
  const z = 2.9, zf = z - 1.0, zb = z + 1.0;
  // 아래 나무장(문 둘) + 위 유리장 틀(옆판·윗판·뒤판) — 앞 유리는 몸 없이 문틀 선만
  m.box([0, 0.9, z], [6.6, 1.8, 2.0], { lines: 'all' });
  m.line([[0, 0.1, zf - 0.01], [0, 1.7, zf - 0.01]]);
  m.box([0, h - 0.25, z], [6.6, 0.5, 2.0], { lines: 'XZ' });
  m.mirrorX(() => m.box([3.22, h / 2, z], [0.16, h - 2.3, 2.0], { lines: 'none' }));
  m.mirrorX(() => m.line([[3.3, 1.8, zf], [3.3, h - 0.5, zf]]));
  m.box([0, h / 2, zb - 0.05], [6.4, h - 2.3, 0.1], { lines: 'none' });
  // 미닫이 유리문 틀(가운데 겹침)
  m.line([[-0.05, 1.8, zf], [-0.05, h - 0.5, zf]]);
  m.line([[0.12, 1.8, zf + 0.12], [0.12, h - 0.5, zf + 0.12]]);
  // 유리 선반 둘(앞 가장자리 선만)
  const ys = [1.8 + (h - 2.3) / 3, 1.8 + (h - 2.3) * 2 / 3];
  for (const yy of ys) { m.box([0, yy, z], [6.28, 0.06, 1.8], { lines: 'none', solid: false }); m.line([[-3.14, yy, zf + 0.2], [3.14, yy, zf + 0.2]]); }
  // 트로피: 컵 둘 + 방패 액자 하나
  const cup = (x, y0, s) => {
    m.box([x, y0 + 0.15 * s, z], [0.6 * s, 0.3 * s, 0.6 * s], { lines: 'XZ' });
    m.lathe([[0.1 * s, 0.2 * s], [0.1 * s, 0.7 * s], [0.42 * s, 1.0 * s], [0.42 * s, 1.35 * s]].map(([r, yy]) => [r, y0 + yy]), { at: [x, 0, z], seg: 12, crease: 50 });
    m.mirrorX(() => m.tube([[x + 0.4 * s, y0 + 1.3 * s, z], [x + 0.62 * s, y0 + 1.22 * s, z], [x + 0.36 * s, y0 + 1.02 * s, z]], 0.03, ROD));
  };
  cup(-1.7, 1.8, 1.1);
  cup(1.4, ys[0], 0.9);
  m.with(T(-0.6, ys[1] + 0.55, z + 0.5).mul(Rx(-0.15)), () => m.extrude([[-0.45, 0.5], [0.45, 0.5], [0.45, -0.1], [0, -0.5], [-0.45, -0.1]], 0.08, { caps: 'back' }));
}

