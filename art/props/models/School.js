// ── 나무(겨울, 잎 없음) ──
function tree(m, top) {
  const fy = top * 0.6, fork = [0.3, fy, 0.2];
  m.cone([0, 0, 0], fork, 0.75, 0.45, { caps: false });
  // 뿌리 퍼짐
  m.cone([0, 0, 0], [0, 0.7, 0], 1.05, 0.72, { caps: false, silhouette: false, lines: 'none' });
  const br = [[0.35, 3.0], [1.95, 2.8], [3.3, 3.1], [4.7, 2.9]];
  const hs = [0.75, 0.35, 0.95, 0.55];
  br.forEach(([a, R], k) => {
    const tip = [fork[0] + Math.cos(a) * R, fork[1] + top * 0.33 + hs[k], fork[2] + Math.sin(a) * R];
    m.cone(fork, tip, 0.32, 0.08, { caps: false });
    // 잔가지 둘(끝에서 갈라진다)
    const mid = [fork[0] + (tip[0] - fork[0]) * 0.6, fork[1] + (tip[1] - fork[1]) * 0.6, fork[2] + (tip[2] - fork[2]) * 0.6];
    const sa = a + 0.7;
    m.line([mid, [mid[0] + Math.cos(sa) * 1.2, Math.min(top - 0.1, mid[1] + 1.1), mid[2] + Math.sin(sa) * 1.2]]);
    m.line([tip, [tip[0] + Math.cos(a - 0.5) * 0.7, Math.min(top - 0.05, tip[1] + 0.5), tip[2] + Math.sin(a - 0.5) * 0.7]]);
  });
  // 가운데 위로 뻗는 가지
  m.cone(fork, [0.1, top - 0.2, 0.5], 0.22, 0.06, { caps: false });
  // 나무 둘레 보호틀(쇠 격자 덮개: 바깥 네모 + 안쪽 둥근 구멍)
  m.box([0, 0.3, 0], [4.4, 0.6, 4.4], { lines: 'top', solid: false });
  m.line([[-2.2, 0.6, -2.2], [-2.2, 0, -2.2]]); m.line([[2.2, 0.6, 2.2], [2.2, 0, 2.2]]);
  m.line([[2.2, 0.6, -2.2], [2.2, 0, -2.2]]); m.line([[-2.2, 0.6, 2.2], [-2.2, 0, 2.2]]);
  m.cyl([0, 0.6, 0], [0, 0.61, 0], 1.25, { caps: false, rings: [1], silhouette: false, lines: 'all', capMesh: false });
}

// ── 농구대 ──
function hoop(m, y) {
  // 벽 안전 매트(세로 판 셋)
  m.box([0, 2.6, 3.4], [7.6, 5.2, 1.0], { lines: 'all', bevel: 0.08 });
  for (const x of [-1.27, 1.27]) m.line([[x, 0.05, 2.895], [x, 5.15, 2.895]]);
  // 지지대(벽 → 백보드 위) + 아래 버팀
  m.mirrorX(() => {
    m.cyl([1.6, y + 0.6, 3.95], [1.6, y + 0.6, 1.75], 0.12, { caps: false });
    m.cyl([1.6, y - 1.6, 3.95], [1.6, y + 0.4, 1.75], 0.08, ROD);
  });
  // 백보드: 둥근 모서리 판(윤곽 한 줄) + 슈팅 네모
  m.with(T(0, y, 0), () => m.extrude(roundRect(6.4, 4.0, 0.25, 2), 0.25, { z0: 1.475, caps: 'back' }));
  rectLine(m, -1.1, y - 1.3, 1.1, y + 0.3, 1.46);
  // 림 + 그물(아래로 좁아지는 줄)
  const ry = y - 1.4, rz = 0.2;
  m.box([0, ry, 1.2], [0.5, 0.18, 0.5], { lines: 'none' });
  m.cyl([0, ry - 0.04, rz], [0, ry + 0.04, rz], 1.1, { caps: false, rings: [0.5], silhouette: false, capMesh: false });
  const n = 8;
  for (let k = 0; k < n; k++) {
    const a = k / n * Math.PI * 2, b = a + Math.PI / n * 1.6;
    m.line([[Math.cos(a) * 1.1, ry, rz + Math.sin(a) * 1.1], [Math.cos(b) * 0.7, ry - 1.4, rz + Math.sin(b) * 0.7]]);
  }
  m.cyl([0, ry - 1.41, rz], [0, ry - 1.39, rz], 0.7, { caps: false, rings: [0.5], silhouette: false, capMesh: false, seg: 8 });
}

// ── 체육관 단상 한 칸 ──
function gymStage(m, H) {
  const L = 8;
  m.box([0, 1.7, 0], [L, 3.4, L], { lines: 'XZ' });
  m.mirrorX(() => m.line([[4, 0, 4], [4, 3.4, 4]]));
  // 앞판: 위 몰딩 + 판 나눔 + 걸레받이
  m.box([0, 3.28, 4.06], [L, 0.24, 0.12], { lines: 'X' });
  for (const x of [-2, 2]) m.line([[x, 0.35, 4.01], [x, 3.16, 4.01]]);
  m.line([[-4, 0.35, 4.01], [4, 0.35, 4.01]]);
  // 뒤쪽 막: 주름(지그재그) 커튼 — 위 막대 + 아래 단 지그재그 + 앞으로 나온 주름 세로선
  const y0 = 3.4, y1 = H - 1.2, zc = -3.5, n = 10, w = L / n;
  const zz = (k) => zc + (k % 2 ? 0.22 : -0.22);
  const poly = []; for (let k = 0; k <= n; k++) poly.push([-L / 2 + k * w, zz(k)]);
  const back = poly.map(([x, z]) => [x, z - 0.06]).reverse();
  m.with(T(0, y0 + 0.02, 0).mul(Rx(-Math.PI / 2)), () => m.extrude([...poly, ...back].map(([x, z]) => [x, -z]), y1 - y0 - 0.04, { z0: 0, lines: 'none' }));
  m.line(poly.map(([x, z]) => [x, y0 + 0.05, z]));
  m.line(poly.map(([x, z]) => [x, y1, z]));
  for (let k = 1; k < n; k += 2) m.line([[poly[k][0], y0 + 0.05, poly[k][1]], [poly[k][0], y1, poly[k][1]]]);
  m.box([0, y1 + 0.12, zc], [L, 0.24, 0.3], { lines: 'X' }); // 커튼 레일 덮개
}

