// 챕터 7 폐교(한국 학교) 소품 메시. 좌표 = PropMesh.dress 에 넘긴 소품 좌표계(스터드, y 위, -z = 소품이 보는 쪽).
// 벽 소품(againstWall): +z = 벽 쪽, 벽면 z = 4(타일 8 의 반), -z = 방 안쪽.
const { T, Rx, Ry, Rz, roundRect } = require('../lib/model.js');
const ROD = { line: true };            // 가는 쇠파이프 = 한 줄
const rect = (x0, y0, x1, y1, z) => [[x0, y0, z], [x1, y0, z], [x1, y1, z], [x0, y1, z]];
// x = 가로, y = 세로 평면의 사각형 선(z 고정)
const rectLine = (m, x0, y0, x1, y1, z) => m.line(rect(x0, y0, x1, y1, z), { closed: true });

// ── 학생 책상 + 의자 ──
// 책상: 나무 상판 + 상판 밑 책 넣는 칸(쇠판) + 쇠파이프 다리 틀(옆 H자). 원점 = 칸 가운데, 책상은 z -0.8, 의자는 z 1.2(뒤)
function desk(m) {
  m.box([0, 2.6, -0.8], [2.8, 0.18, 1.9], { lines: 'XZ' });
  // 책 칸: 바닥판 + 앞(교탁 쪽) 막음판 + 옆판 — 학생 쪽(+z)이 열렸다
  m.box([0, 2.2, -0.85], [2.3, 0.06, 1.45], { lines: 'none' });
  m.box([0, 2.36, -1.55], [2.3, 0.38, 0.05], { lines: 'none' });
  m.line([[-1.15, 2.2, -0.13], [1.15, 2.2, -0.13], [1.15, 2.51, -0.13]]);
  m.line([[-1.15, 2.2, -0.13], [-1.15, 2.51, -0.13]]);
  m.mirrorX(() => {
    // 다리 둘 + 아래 발 막대 + 가운데 가로대(옆에서 H)
    m.cyl([1.22, 0, -1.5], [1.22, 2.51, -1.5], 0.05, ROD);
    m.cyl([1.22, 0, -0.1], [1.22, 2.51, -0.1], 0.05, ROD);
    m.cyl([1.22, 0.06, -1.6], [1.22, 0.06, 0.0], 0.05, ROD);
    m.cyl([1.22, 0.9, -1.5], [1.22, 0.9, -0.1], 0.04, ROD);
  });
}
// 의자: 합판 앉는 판 + 굽은 등판 + 쇠파이프 다리(뒷다리가 등판까지 올라간다). 원점 = 의자 바닥 가운데, 등판 +z
function chair(m) {
  m.box([0, 1.6, 0], [1.5, 0.15, 1.4], { lines: 'XZ' });
  m.with(T(0, 2.82, 0.72).mul(Rx(-0.08)), () => m.extrude(roundRect(1.5, 0.75, 0.14, 1), 0.1, { caps: 'back' }));
  m.mirrorX(() => {
    m.cyl([0.68, 0, -0.62], [0.68, 1.53, -0.62], 0.05, ROD);
    m.cyl([0.68, 0, 0.66], [0.68, 3.15, 0.76], 0.05, ROD);
    m.cyl([0.68, 0.45, -0.62], [0.68, 0.45, 0.67], 0.04, ROD);
  });
}

// ── 사각 테두리 판(칠판·게시판·거울): 바깥 윤곽 한 줄(방 쪽 면) + 안쪽 선 ──
function framedPanel(m, cx, cy, w, h, zFace, depth, inset) {
  m.with(T(cx, cy, 0), () => m.extrude(roundRect(w, h, 0, 1), depth, { z0: zFace, caps: 'back' }));
  if (inset) rectLine(m, cx - w / 2 + inset, cy - h / 2 + inset, cx + w / 2 - inset, cy + h / 2 - inset, zFace - 0.01);
}

