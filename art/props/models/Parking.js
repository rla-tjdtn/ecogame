const { T, Rx, Ry, Rz, roundRect, circle2, arc2 } = require('../lib/model.js');

const WHEEL = { caps: false, silhouette: false, rings: [0.5] }; // 바퀴: 원 한 줄
const SIDE = Ry(-Math.PI / 2); // 옆 모습(u = z, v = y) 다각형을 x 방향으로 밀어낸다(extrude 깊이 = 폭)

// 바퀴 아치가 파인 차체 옆 모습: pts 위쪽 윤곽(앞 → 뒤), 아래는 바퀴 둘(uf, ur) 자리 아치
function bodyProfile(top, uf, ur, wy, ar, sill) {
  const out = top.slice();
  const back = top[top.length - 1], front = top[0];
  const a = Math.asin(Math.max(-1, Math.min(1, (sill - wy) / ar)));
  out.push([back[0] - 0.15, sill]);
  for (const p of arc2(ur, wy, ar, a, Math.PI - a, 5)) out.push(p);
  for (const p of arc2(uf, wy, ar, a, Math.PI - a, 5)) out.push(p);
  out.push([front[0] + 0.15, sill]);
  return out;
}
// 타이어: 검은 몸(선 없음) + 바깥 면 원 한 줄(8각)
function wheel(m, x, y, z, r, w) {
  const s = Math.sign(x);
  m.cyl([x - s * w, y, z], [x, y, z], r, { lines: 'none' });
  m.line(circle2(r * 0.97, 8).map(([a, b]) => [x + s * 0.02, y + b, z + a]), { closed: true });
}

// 천장 안내 표지(EXIT + 화살표): 판 가운데 높이 y, 천장 top. 앞면 = -z, 앞에서 볼 때 오른쪽 = -x
function hangSign(m, y, top) {
  m.box([0, y, 0], [6.4, 1.8, 0.3], { bevel: 0.05 });
  m.line(roundRect(6.0, 1.45, 0.08, 1).map(([a, b]) => [a, y + b, -0.16]), { closed: true });
  for (const x of [-2.4, 2.4]) m.cyl([x, y + 0.9, 0], [x, top, 0], 0.07, { line: true });
  // 글자(막대 그림) + 화살표 — 앞면(-z)·뒷면(+z) 둘 다(글자는 양쪽에서 바로 읽히게, 화살표는 같은 방향)
  const h = 0.9, w = h * 0.62, gap = h * 0.3;
  const L = { E: [[0, 0, 0, 1], [0, 1, 1, 1], [0, 0.5, 0.8, 0.5], [0, 0, 1, 0]], X: [[0, 0, 1, 1], [0, 1, 1, 0]], I: [[0.5, 0, 0.5, 1]], T: [[0, 1, 1, 1], [0.5, 0, 0.5, 1]] };
  for (const d of [1, -1]) { // d = 앞에서 본 왼쪽이 +x 면 1
    const z = -0.17 * d;
    let x0 = 0.9 + d * (4 * w + 3 * gap) / 2;
    for (const ch of 'EXIT') {
      for (const [u0, v0, u1, v1] of L[ch]) m.line([[x0 - d * u0 * w, y - h / 2 + v0 * h, z], [x0 - d * u1 * w, y - h / 2 + v1 * h, z]]);
      x0 -= d * (w + gap);
    }
    m.line([[-1.5, y - 0.12], [-2.25, y - 0.12], [-2.25, y - 0.42], [-2.85, y], [-2.25, y + 0.42], [-2.25, y + 0.12], [-1.5, y + 0.12]].map(([x, yy]) => [x, yy, z]), { closed: true });
  }
}

