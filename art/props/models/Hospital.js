const { T, Rx, Ry, Rz, roundRect, circle2, arc2 } = require('../lib/model.js');
const WHEEL = { caps: false, silhouette: false, rings: [0.5] }; // 바퀴: 원 한 줄
const PI = Math.PI;

// 바닥에 눕힌 2D 윤곽(x, z) 을 y0 에서 위로 h 만큼 세운 기둥(윤곽 = 위 테두리)
function vext(m, polyXZ, y0, h, o = {}) { m.with(Rx(-PI / 2), () => m.extrude(polyXZ.map(([x, z]) => [x, -z]), h, { z0: y0, ...o })); }
// YZ 면 윤곽(z, y) 을 x0 에서 +x 로 d 만큼 밀어낸 판
function xext(m, polyZY, x0, d, o = {}) { m.with(Ry(PI / 2), () => m.extrude(polyZY.map(([z, y]) => [-z, y]), d, { z0: x0, ...o })); }
// 작은 바퀴(포크 + 원 한 줄): 바닥 위 (x, z), 반지름 r, 바퀴 축 = x
function caster(m, x, z, r, top) {
  m.cyl([x - 0.06, r, z], [x + 0.06, r, z], r, WHEEL);
  m.line([[x, r, z], [x, top, z - r * 0.4]]);
}
// 사각 윤곽 선(면 위): 가운데 c, 축 두 개 u·v 의 반폭 a·b
function rect(m, c, u, v, a, b) {
  const p = (s, t) => [c[0] + u[0] * a * s + v[0] * b * t, c[1] + u[1] * a * s + v[1] * b * t, c[2] + u[2] * a * s + v[2] * b * t];
  m.line([p(-1, -1), p(1, -1), p(1, 1), p(-1, 1)], { closed: true });
}

