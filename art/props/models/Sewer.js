// (z, y) 옆모습 다각형을 x0..x1 로 밀어낸 몸통
function extX(m, polyZY, x0, x1, o = {}) {
  m.with(T(x1, 0, 0).mul(Ry(-Math.PI / 2)), () => m.extrude(polyZY, x1 - x0, { z0: 0, ...o }));
}
// 원 한 줄(몸 없는 선): 가운데 c, 축 'x'|'y'|'z', 반지름 r, n 조각
function ring(m, c, axis, r, n = 12) {
  const pts = circle2(r, n).map(([u, v]) => axis === 'x' ? [c[0], c[1] + u, c[2] + v] : axis === 'y' ? [c[0] + u, c[1], c[2] + v] : [c[0] + u, c[1] + v, c[2]]);
  m.line(pts, { closed: true });
}
function rectXY(m, x0, y0, x1, y1, z) { m.line([[x0, y0, z], [x1, y0, z], [x1, y1, z], [x0, y1, z]], { closed: true }); }

