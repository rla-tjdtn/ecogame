// 수로 아치 갈비(벽돌 아치 띠): 반폭 half, 발치 6.5, 높이 rise(천장 14 → 6.9), 띠 두께 0.6, 깊이 0.8 + 발치 받침돌 + 쐐기돌
function archRib(m, half) {
  const spring = 6.5, rise = 6.9, t = 0.3;
  const arcLen = Math.PI * Math.sqrt(((half + t) ** 2 + (rise + t) ** 2) / 2);
  const n = Math.max(10, Math.ceil(arcLen / 2.4));
  const outer = [], inner = [];
  for (let k = 0; k <= n; k++) {
    const a = Math.PI * k / n;
    outer.push([(half + t) * Math.cos(a), spring + (rise + t) * Math.sin(a)]);
    inner.push([(half - t) * Math.cos(a), spring + (rise - t) * Math.sin(a)]);
  }
  m.extrude([...outer, ...inner.reverse()], 0.8, { crease: 20 });
  // 벽돌 이음(앞뒤 면 방사 줄 몇 개)
  for (const a of [0.22, 0.5, 0.78].map(f => f * Math.PI).concat([(1 - 0.22) * Math.PI, (1 - 0.5) * Math.PI].slice(0, 0))) {
    for (const z of [-0.41, 0.41]) m.line([[(half - t) * Math.cos(a), spring + (rise - t) * Math.sin(a), z], [(half + t) * Math.cos(a), spring + (rise + t) * Math.sin(a), z]]);
  }
  // 쐐기돌(꼭대기) + 발치 받침돌 둘
  m.box([0, spring + rise, 0], [0.7, 0.95, 1.0]);
  m.mirrorX(() => m.box([half - 0.2, spring - 0.25, 0], [0.9, 0.5, 1.1]));
}

