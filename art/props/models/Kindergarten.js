// 벽 소품(againstWall): +z = 벽, -z = 방 안쪽. 길게 이어지는 소품(runAxis): z = 이어지는 방향.
const { T, Rx, Ry, Rz, S, roundRect, circle2, arc2 } = require('../lib/model.js');

const ROD = { line: true };
const rod = (m, a, b) => m.cyl(a, b, 0.06, ROD);
const rect = (w, h, cx = 0, cy = 0) => [[cx - w / 2, cy - h / 2], [cx + w / 2, cy - h / 2], [cx + w / 2, cy + h / 2], [cx - w / 2, cy + h / 2]];
const shift = (poly, dx, dy) => poly.map(([x, y]) => [x + dx, y + dy]);
// (z, y) 평면 다각형을 x 방향으로 밀어낸다(x0 부터 depth). caps 'back' = x0 쪽, 'front' = x0+depth 쪽
const extX = (m, polyZY, x0, depth, o = {}) => m.with(Ry(Math.PI / 2), () => m.extrude(polyZY.map(([z, y]) => [-z, y]), depth, { ...o, z0: x0 }));
// (x, z) 평면 다각형을 y 방향으로(y0 부터 h). caps 'back' = 아래, 'front' = 위
const extY = (m, polyXZ, y0, h, o = {}) => m.with(Rx(-Math.PI / 2), () => m.extrude(polyXZ.map(([x, z]) => [x, -z]), h, { ...o, z0: y0 }));
// 앞(-z)을 보는 판: (x, y) 다각형, 앞면 z = zf, 두께 d(뒤로)
const panel = (m, polyXY, zf, d, o = {}) => m.extrude(polyXY, d, { caps: 'back', ...o, z0: zf });

