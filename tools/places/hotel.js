// 챕터 6 호텔: 1층 직원 구역(북) → 1층 서비스 복도 / 2층 객실층(가운데, 나란한 두 길) → 1층 연회·식당 구역(남) → 프런트 로비(남동, 출구).
//   node tools/places/hotel.js [--dry]
// 가로 띠 셋을 갈지자로 지난다. 띠마다 갈래가 셋(복도 둘 + 방을 잇는 샛문 줄)이라 한 곳이 막혀도 돌아간다.
//   북쪽 띠(y1~10): 직원 복도 · 직원 방 줄(샛문으로 이어짐) · 사무 복도 — 서쪽 휴게실(시작)에서 동쪽으로.
//   가운데 띠(y12~29): 1층 서비스 복도(y12~13) 와 2층 객실층(y15~29: 객실 줄, 복도 A, 코어, 복도 B) 이 나란히 서쪽으로.
//     계단 셋: 동쪽 중앙 계단(직원 동쪽 복도 → 2층), 가운데 직원 계단(서비스 복도 ↔ 2층), 서쪽 비상계단(2층 → 남쪽 띠).
//   남쪽 띠(y32~41): 연회 복도 · 연회장─주방─레스토랑─라운지 바(샛문 줄) · 남쪽 복도 — 서쪽에서 동쪽 프런트 로비로.
const { Grid, report, writeStage } = require("./lib");

const g = new Grid(47, 43);
g.markUpper(4, 15, 42, 29);

// ══ 북쪽 띠: 직원 복도(y1~2), 직원 방 줄(y4~7), 사무 복도(y9~10), 동쪽 직원 복도(x44~45, y1~25) ══
g.fill(1, 1, 43, 2).fill(1, 9, 43, 10).fill(44, 1, 45, 25);
// 직원 휴게실(시작): 직원 복도·사무 복도·락커실로 문 셋
g.fill(1, 4, 5, 7).set(4, 3, "D").set(3, 8, "D").set(6, 6, "D");
g.put("S", [[1, 4], [2, 4], [1, 5], [2, 5]]).set(3, 6, "T").set(5, 4, "Z").set(1, 7, "L");
// 락커실
g.fill(7, 4, 11, 7).set(9, 3, "D").set(12, 5, "D");
g.put("L", [[8, 4], [10, 4], [9, 7]]).put("k", [[11, 4], [7, 7]]).set(11, 7, "Z");
// 세탁실(세탁기 줄)
g.fill(13, 4, 19, 7).set(16, 8, "D").set(20, 6, "D");
g.put("m", [[14, 4], [15, 4], [17, 4], [18, 4]]).set(13, 7, "Z").set(19, 7, "L").put("c", [[13, 4]]);
// 린넨실(선반 k)
g.fill(21, 4, 25, 7).set(23, 3, "D").set(26, 5, "D");
g.put("k", [[21, 4], [22, 4], [24, 7], [25, 7]]).set(25, 4, "Z").set(21, 7, "L");
// 직원 식당(식탁)
g.fill(27, 4, 34, 7).set(30, 8, "D").set(35, 6, "D").set(32, 3, "D");
g.put("T", [[28, 7], [33, 7]]).set(34, 4, "Z").set(27, 4, "L");
// 기계실(보일러 m)
g.fill(36, 4, 42, 7).set(39, 3, "D").set(41, 8, "D");
g.put("m", [[36, 4], [37, 4], [42, 5], [42, 6]]).set(36, 7, "Z").set(42, 7, "L").set(39, 7, "c");
// 사무 복도 · 직원 복도 소품
g.put("c", [[20, 1], [33, 10]]).put("k", [[12, 1], [26, 10]]);
g.set(45, 12, "c").set(44, 18, "k");
// 사무 복도 동쪽 끝 → 서비스 복도로 내려가는 문
g.set(40, 11, "D");

// ══ 가운데 띠 1층: 서비스 복도(y12~13) → 서쪽 직원 복도(x1~2, y12~41) ══
g.fill(1, 12, 42, 13).fill(1, 12, 2, 41);
g.put("c", [[30, 12], [12, 13]]).put("k", [[36, 13], [1, 20]]);
// 가운데 직원 계단: 서비스 복도 → 2층 직원 계단실
g.stairs(22, 14, 0, 1);

// ══ 가운데 띠 2층 객실층(x4~42, y15~29) ══
// 북쪽 객실 줄(y16~19, 문 y20), 복도 A(y21~22), 코어(y24~26), 복도 B(y28~29), 양 끝 이음 복도(x4~5, x40~41)
g.fill(4, 21, 41, 22).fill(4, 28, 41, 29).fill(4, 21, 5, 29).fill(40, 21, 41, 29);
const guest = (x0, n) => {
	g.fill(x0, 16, x0 + 3, 19).set(x0 + 1, 20, "D");
	g.set(x0 + 2, 16, "R").set(x0, 16, "Z").set(x0 + 3, 19, "L");
	if (n % 2) g.set(x0 + 2, 18, "c");
};
[4, 9, 14, 25, 30, 35].forEach(guest);
g.fill(19, 16, 23, 19).set(21, 20, "D").put("c", [[19, 16], [19, 17]]).set(23, 19, "Z"); // 직원 계단실(가운데 계단 2층 쪽)
g.fill(39, 16, 41, 19).set(40, 20, "D").put("k", [[39, 16], [41, 16]]).set(41, 19, "L"); // 청소 창고(막다른 방)
// 코어
g.fill(6, 24, 10, 26).set(8, 23, "D").put("k", [[6, 24], [7, 24], [10, 24]]).set(6, 26, "Z"); // 린넨실
g.fill(12, 24, 15, 26).set(13, 27, "D").put("m", [[15, 24]]).set(12, 24, "L"); // 제빙·자판기실
g.fill(17, 24, 23, 26).set(18, 23, "D").set(22, 23, "D").set(18, 27, "D").set(22, 27, "D"); // 엘리베이터 홀(두 복도 잇기)
g.put("m", [[17, 25], [23, 25]]);
g.fill(25, 24, 30, 26).set(27, 23, "D").set(29, 27, "D").put("k", [[25, 24], [30, 24]]).set(25, 26, "Z").set(30, 26, "c"); // 하우스키핑
g.fill(32, 24, 35, 26).set(33, 27, "D").set(35, 24, "R").set(32, 24, "Z").set(35, 26, "L"); // 객실(복도 B 쪽)
g.fill(37, 24, 38, 26).set(38, 23, "D").set(37, 24, "k").set(37, 26, "Z"); // 린넨 창고
g.put("c", [[12, 22], [30, 21], [20, 29], [34, 28]]);
// 동쪽 중앙 계단(1층 동쪽 직원 복도 ↔ 동쪽 이음 복도), 서쪽 비상계단(복도 B 서쪽 → 남쪽 띠 연회 복도)
g.stairs(43, 25, -1, 0);
g.stairs(6, 31, 0, -1);

// ══ 남쪽 띠: 연회 복도(y32~33), 연회·식당 방 줄(y35~38), 남쪽 복도(y40~41), 프런트 로비(x35~44, y31~41) ══
g.fill(1, 32, 34, 33).fill(1, 40, 34, 41);
// 연회장(기둥·원탁)
g.fill(4, 35, 14, 38).set(3, 36, "D").set(8, 34, "D").set(11, 39, "D").set(15, 37, "D");
g.put("O", [[7, 36], [11, 36]]).put("T", [[5, 38], [9, 38], [13, 35]]).set(4, 35, "Z").set(14, 38, "L");
// 연회 주방(조리대 T·화구 m)
g.fill(16, 35, 21, 38).set(19, 34, "D").set(22, 36, "D").set(17, 39, "D");
g.put("m", [[16, 35], [17, 35]]).put("T", [[19, 37], [20, 37]]).set(21, 35, "Z").set(16, 38, "L");
// 레스토랑
g.fill(23, 35, 28, 38).set(25, 34, "D").set(29, 37, "D").set(27, 39, "D");
g.put("T", [[24, 37], [27, 36]]).set(28, 35, "Z").set(23, 38, "L");
// 라운지 바(로비로 문)
g.fill(30, 35, 33, 38).set(34, 36, "D").set(31, 39, "D");
g.put("k", [[30, 35], [31, 35]]).set(33, 38, "Z").set(30, 38, "L");
g.put("c", [[10, 33], [24, 40], [2, 38]]);
// 프런트 로비: 데스크 k 줄, 기둥, 엘리베이터, 동쪽 벽 가운데 정문
g.fill(35, 31, 44, 41);
g.set(45, 36, "E");
g.put("k", [[38, 32], [39, 32], [40, 32], [41, 32]]).put("O", [[38, 36], [41, 36], [38, 39], [41, 39]]).put("m", [[44, 31], [44, 32]]);
g.set(35, 31, "Z").set(44, 41, "L").set(35, 41, "c");

const opts = { blocked: ["R"] };
const r = report("호텔", g, opts);
if (process.argv.includes("--print")) console.log(g.rows().join("\n"));
if (!process.argv.includes("--dry")) {
	// (writeStage 는 주석 달린 UpperRects 줄을 못 지우므로 먼저 지운다)
	const sf = require("path").join(__dirname, "..", "..", "src", "server", "Stages", "Stage6.luau");
	const fs = require("fs");
	fs.writeFileSync(sf, fs.readFileSync(sf, "utf8").replace(/\r\n/g, "\n").replace(/\tUpperRects = \{[^\n]*\n/g, ""));
}
if (!process.argv.includes("--dry"))
	writeStage("Stage6.luau", g, [
		"STAGE 6 — 호텔 (47x43칸, tools/places/hotel.js 로 생성)",
		"실제 호텔 구조를 가로 띠 셋으로 갈지자로 지난다(2층 = UpperRects, 계단 1·2 로 오르내림). 띠마다 갈래가 셋이라 막힌 곳은 돌아간다.",
		"북쪽 띠(1층 직원 구역): 직원 복도 · 사무 복도 사이에 휴게실(시작)·락커실·세탁실·린넨실·직원 식당·기계실이 샛문으로 이어진다.",
		"가운데 띠: 1층 서비스 복도와 2층 객실층이 나란히 서쪽으로 간다. 2층 = 북쪽 객실 줄(침대 R·서랍장 Z·옷장 L), 복도 A·B 가",
		"코어(린넨실·제빙실·엘리베이터 홀·하우스키핑)를 둘러싸는 레이스트랙. 계단 셋: 동쪽 중앙 계단, 가운데 직원 계단(서비스 복도 ↔ 2층),",
		"서쪽 비상계단(2층 → 남쪽 띠). 1층만으로도(서비스 복도 → 서쪽 직원 복도), 2층으로도 남쪽 띠에 닿는다.",
		"남쪽 띠(1층 연회·식당): 연회 복도 · 남쪽 복도 사이에 연회장(기둥·원탁)─연회 주방─레스토랑─라운지 바가 샛문으로 이어져 프런트 로비(정문 출구)로.",
		`출구까지 최단 약 ${r.exit}칸.`,
	]);
