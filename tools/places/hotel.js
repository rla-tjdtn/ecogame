// 챕터 6 호텔: 1층 = 직원 구역(북) · 주방·연회장 뒤쪽 서비스 구역(가운데) · 식당·라운지 바·프런트 로비(남, 출구),
//             2층 = 객실층(1층과 같은 크기로 겹쳐 쌓음): 코어(엘리베이터 홀·린넨실·하우스키핑·서비스 계단)를 둘러싼 객실 복도 고리.
//   node tools/places/hotel.js [--dry] [--print]
// 큰 흐름(갈지자 세 띠): 북서쪽 직원 휴게실(시작) → 직원 구역을 동쪽으로 → 서비스 복도·주방/연회장 줄·연회 준비 복도를 서쪽으로
//   → 서쪽 직원 통로로 내려가 → 공용 복도·식당 줄·남쪽 복도를 동쪽으로 → 프런트 로비 정문(출구).
//   2층 객실층은 가운데 띠를 대신하는 셋째 길: 동쪽 주 계단·가운데 서비스 계단으로 올라 서쪽 비상계단으로 내려온다.
// 소품 글자(Stage6 Props 줄): R 침대, Z 객실 서랍장, L 옷장/벽장, T 책상·사무 테이블, k 캐비닛, c 상자, m 설비, O 기둥,
//   호텔 전용(ChapterProps/Hotel.luau): F 프런트 데스크, G 짐 카트, w 소파, q 바 카운터, U 원형 테이블(의자),
//   K 업소용 화구(후드), P 스테인리스 조리대, W 업소용 세탁기, j 린넨 선반, l 직원 사물함 줄, h 하우스키핑 카트,
//   V 제빙기·자판기, e 엘리베이터 문
const { Grid, report, writeStage } = require("./lib");

const g = new Grid(47, 43);
const up = g.floor2(); // 2층 객실층(1층 위에 같은 크기). 프런트 로비 위는 2층까지 트인 높은 천장(벽)

// ════════════════════════ 1층 ════════════════════════
// ══ 북쪽 띠: 직원 복도(y1~2), 직원 방 줄(y4~7), 사무 복도(y9~10), 동쪽 직원 통로(x44~45, y1~24) ══
g.fill(1, 1, 43, 2).fill(1, 9, 43, 10).fill(44, 1, 45, 24);
// 직원 휴게실(시작): 직원 복도·사무 복도·락커실로 문 셋
g.fill(1, 4, 5, 7).set(4, 3, "D").set(3, 8, "D");
g.put("S", [[1, 4], [2, 4], [1, 5], [2, 5]]).set(4, 6, "T").set(5, 4, "Z").set(1, 7, "L");
// 직원 락커실: 사물함 줄(l) + 숨는 사물함(L)
g.fill(7, 4, 11, 7).set(9, 3, "D").set(12, 5, "D");
g.put("l", [[8, 4], [10, 4], [11, 4]]).put("L", [[9, 7]]);
// 세탁실: 업소용 세탁기 줄(W), 린넨 카트(h)
g.fill(13, 4, 19, 7).set(16, 8, "D").set(20, 6, "D");
g.put("W", [[14, 4], [15, 4], [17, 4], [18, 4]]).set(13, 7, "Z").set(19, 7, "L").set(19, 4, "h");
// 린넨 보관실(린넨 선반 j)
g.fill(21, 4, 25, 7).set(23, 3, "D"); // (세탁실 샛문 + 직원 복도 문)
g.put("j", [[21, 4], [22, 4], [24, 7], [25, 7]]).set(25, 4, "Z").set(21, 7, "L");
// 직원 식당(식탁 U)
g.fill(27, 4, 34, 7).set(30, 8, "D").set(35, 6, "D");
g.put("U", [[29, 5], [33, 6]]).set(34, 4, "Z").set(27, 4, "L");
// 기계실(보일러·공조기 m)
g.fill(36, 4, 42, 7).set(39, 3, "D"); // (직원 복도 문 + 직원 식당 샛문)
g.put("m", [[36, 4], [37, 4], [42, 5], [42, 6]]).set(36, 7, "Z").set(42, 7, "L");
// 직원 복도·사무 복도 소품(아주 조금)
g.put("c", [[20, 1], [33, 10]]).set(12, 1, "h");
g.set(45, 12, "c");
// 사무 복도 동쪽 끝 → 서비스 복도로 내려가는 문
g.set(34, 11, "D");

// ══ 가운데 띠(1층 서비스 구역): 서비스 복도(y12~14, 세 칸 폭), 주방·냉장실·서비스 계단·연회장 줄(y16~25), 연회 준비 복도(y27~28),
//    서쪽 직원 통로(x1~2, y12~41) ══
g.fill(1, 12, 42, 14).fill(1, 12, 2, 41).fill(1, 27, 40, 28);
// 메인 주방: 화구 줄(K, 북쪽 벽 후드 아래)·가운데 조리대 섬(P), 서비스 복도로 문 하나(가운데쯤 — 긴 복도에서 앞뒤로 몰렸을 때 빠질 곳), 연회 준비 복도로 문 하나
g.fill(4, 16, 17, 25).set(14, 15, "D").set(10, 26, "D");
g.put("K", [[9, 16], [10, 16], [11, 16], [12, 16]]).put("P", [[8, 19], [9, 19], [12, 19], [13, 19], [8, 22], [9, 22], [12, 22], [13, 22]]);
g.set(4, 20, "Z").set(17, 17, "Z").set(4, 25, "L").set(17, 25, "c");
// 냉장실(선반 j) → 세척실(식기 카트): 위아래로 이어진다
g.fill(19, 16, 24, 19).set(21, 15, "D").set(22, 20, "D");
g.put("j", [[19, 16], [19, 17], [24, 16], [24, 17]]).set(24, 19, "Z");
g.fill(19, 21, 24, 25).set(22, 26, "D");
g.put("P", [[24, 22], [24, 23]]).set(19, 25, "L").set(19, 21, "c");
// 연회장(그랜드 볼룸): 기둥 넷, 원형 테이블(U), 동쪽 무대(k 줄)
g.fill(28, 16, 40, 25).set(31, 15, "D").set(38, 26, "D");
g.put("O", [[31, 18], [37, 18], [31, 22], [37, 22]]).put("U", [[34, 17], [34, 23], [29, 20]]).put("k", [[40, 18], [40, 19], [40, 21], [40, 22]]);
g.set(28, 16, "Z").set(40, 25, "Z").set(40, 16, "L");
// 동쪽 주 계단(동쪽 직원 통로 → 2층 동쪽 복도)
g.stairs(43, 20, -1, 0);
// 연회 준비 복도 소품
g.put("c", [[25, 28], [40, 27]]).set(13, 27, "h").set(1, 20, "k");
// 배식 통로: 연회 준비 복도 ↔ 공용 복도(레스토랑 앞). 서쪽 직원 통로·비상계단이 막혔을 때의 셋째 내려가는 길
g.fill(10, 29, 10, 31).set(10, 30, "D");
// 서쪽 비상계단(2층 → 1층 공용 복도)
g.stairs(6, 31, 0, -1);

// ══ 남쪽 띠(1층 공용 구역): 공용 복도(y32~33), 식당 줄(y35~38), 남쪽 복도(y40~41), 프런트 로비(x35~44, y31~41) ══
g.fill(1, 32, 34, 33).fill(1, 40, 34, 41);
// 올데이 다이닝(레스토랑): 기둥 둘, 원형 테이블
g.fill(4, 35, 14, 38).set(8, 34, "D").set(11, 39, "D").set(15, 37, "D");
g.put("O", [[7, 36], [11, 36]]).put("U", [[5, 38], [9, 38], [13, 35]]).set(4, 35, "Z").set(14, 38, "L");
// 룸서비스 팬트리(작은 주방)
g.fill(16, 35, 21, 38).set(19, 34, "D").set(22, 36, "D");
g.put("K", [[16, 35], [17, 35]]).put("P", [[19, 37], [20, 37]]).set(21, 35, "Z").set(16, 38, "L");
// 라운지 바: 바 카운터(q) + 소파(w)
g.fill(23, 35, 28, 38).set(27, 34, "D").set(29, 37, "D");
g.put("q", [[24, 35], [25, 35], [26, 35]]).put("w", [[26, 38], [25, 37]]).set(28, 35, "Z").set(23, 38, "L");
// 짐 보관실·컨시어지(로비로 문)
g.fill(30, 35, 33, 38).set(34, 36, "D").set(31, 39, "D");
g.put("G", [[30, 35]]).put("k", [[31, 35]]).set(33, 38, "Z").set(30, 38, "L");
g.put("c", [[10, 33], [24, 40], [2, 38]]);
// 프런트 로비: 프런트 데스크(F 줄), 기둥, 로비 소파, 짐 카트, 엘리베이터(e), 동쪽 벽 가운데 정문
g.fill(35, 31, 44, 41);
g.set(45, 36, "E");
g.put("F", [[38, 32], [39, 32], [40, 32], [41, 32]]).put("O", [[38, 36], [41, 36], [38, 39], [41, 39]]).put("e", [[44, 31], [44, 32]]);
g.put("w", [[39, 41], [40, 41]]).set(43, 38, "G");
g.set(35, 31, "Z").set(44, 41, "L");

// ════════════════════════ 2층 객실층 ════════════════════════
// 고리: 북쪽 객실 복도(y10~11) · 서쪽 복도(x3~4) · 남쪽 객실 복도(y26~27) · 동쪽 복도(x40~41)가 코어를 둘러싼다.
up.fill(3, 10, 41, 11).fill(3, 10, 4, 27).fill(3, 26, 41, 27).fill(40, 10, 41, 27);
// 객실: x0..x0+4, 침대(R)는 머리를 안쪽 벽에, 서랍장(Z)·옷장(L)
// 북쪽 객실 줄(y2~8, 문 y9). 객실은 문 하나뿐이라 서랍장(열쇠 상자) 없이 옷장만 — 진짜 호텔처럼 쉬어 숨는 막다른 방
const north = [3, 9, 15, 21, 27, 33];
north.forEach((x0, n) => {
	up.fill(x0, 2, x0 + 4, 8).set(x0 + 2, 9, "D");
	up.set(x0 + 2, 2, "R");
	const left = n % 2 === 0;
	up.set(left ? x0 + 4 : x0, 8, "L");
});
// 북동쪽 끝: 린넨실(문 하나 — 상자 없이 선반·카트만)
up.fill(39, 2, 43, 8).set(41, 9, "D").put("j", [[39, 2], [43, 2], [43, 3]]).set(39, 8, "h").set(43, 8, "L");
// 코어 북쪽 줄(y13~18, 북쪽 복도로 문)·남쪽 줄(y20~24, 남쪽 복도로 문)
up.fill(6, 13, 12, 18).set(5, 16, "D").set(13, 15, "D"); // 층 린넨실: 서쪽 복도로 문, 하우스키핑 사무실로 샛문
up.put("j", [[6, 13], [7, 13], [11, 13], [12, 13]]).set(6, 18, "Z").set(12, 18, "h");
up.fill(14, 13, 18, 18).set(16, 12, "D"); // 하우스키핑 사무실
up.put("T", [[16, 15]]).set(18, 18, "L"); // (문 하나뿐인 방: 상자 없음)
up.fill(20, 13, 24, 24).set(22, 12, "D").set(22, 25, "D"); // 엘리베이터 홀(두 복도를 잇는다)
up.put("e", [[20, 15], [20, 17], [24, 20], [24, 22]]).set(22, 19, "w").set(24, 16, "Z"); // (홀 벽 콘솔 서랍장)
up.fill(26, 13, 31, 18).set(29, 12, "D"); // 서비스 계단실(가운데 계단 2층 쪽)
up.put("h", [[31, 13]]).set(31, 18, "c");
up.fill(33, 13, 38, 18).set(35, 12, "D").set(35, 19, "D"); // 제빙기·자판기실(남쪽 창고로 이어진다)
up.put("V", [[33, 13], [34, 13]]).set(38, 16, "Z");
up.fill(33, 20, 38, 24).set(36, 25, "D"); // 청소 창고
up.put("j", [[33, 24], [34, 24]]).set(38, 20, "L");
up.fill(6, 20, 12, 24).set(9, 25, "D").set(13, 22, "D"); // 코어 쪽 객실 둘(커넥팅)
up.fill(14, 20, 18, 24).set(16, 25, "D");
up.put("R", [[9, 20], [16, 20]]).set(6, 22, "Z").set(18, 22, "Z").set(12, 24, "L").set(14, 24, "L");
up.fill(26, 20, 31, 24).set(28, 25, "D"); // 객실(문 하나: 옷장만)
up.put("R", [[28, 20]]).set(31, 24, "L");
// 남쪽 객실 줄(스위트: 거실 y29~33 + 침실 y35~40, 사이 문): 막다른 방이라 옷장만
up.set(6, 28, "."); // (서쪽 비상계단 2층 쪽 계단참 통로)
const south = [9, 15, 21, 27];
south.forEach((x0, n) => {
	up.fill(x0, 29, x0 + 4, 33).set(x0 + 2, 28, "D").fill(x0, 35, x0 + 4, 40).set(x0 + 2, 34, "D");
	up.put("w", [[x0, 30]]).set(x0 + 2, 40, "R");
	const left = n % 2 === 0;
	up.set(left ? x0 + 4 : x0, 29, "L");
});
up.put("c", [[30, 10], [20, 27]]);
// 가운데 서비스 계단(1층 서비스 복도 → 2층 서비스 계단실). 2층 방을 판 뒤에 놓아야 계단 구멍(o)이 남는다
g.stairs(26, 15, 0, 1);

const opts = { walkable: ["k"], id: 6 };
const r = report("호텔", g, opts);
if (process.argv.includes("--print")) for (const [name, gr] of [["1층", g], ["2층", up]]) console.log(name + "\n" + gr.rows().map((row, i) => String(i).padStart(2) + " " + row).join("\n"));
// 스테이지 파일의 소품 줄과 호텔 전용 소품 모듈 require 줄도 생성기가 맞춘다.
// 임시 폴더에 완성본을 만든 뒤 한 번에 옮긴다(Rojo 가 반쯤 쓴 파일을 읽지 않게)
const fs = require("fs");
const path = require("path");
const sf = path.join(__dirname, "..", "..", "src", "server", "Stages", "Stage6.luau");
const PROPS_LINE =
	"\tProps = { R = Props.Bed, T = Props.Desk, k = Props.Cabinet, F = CP.FrontDesk, G = CP.LuggageCart, w = CP.Sofa, q = CP.BarCounter, U = CP.RoundTable, K = CP.Range, P = CP.PrepTable, W = CP.Washer, j = CP.LinenShelf, l = CP.StaffLockers, h = CP.HousekeepingCart, V = CP.IceMachine, e = CP.Elevator },";
const WALK_LINE = "\tWalkable = { k = true }, -- (캐비닛은 벽에 붙어 칸 반이 빈다: 지나갈 수 있다. 나머지 소품은 막힌 칸)";
function patchProps() {
	let s = fs.readFileSync(sf, "utf8");
	const crlf = s.includes("\r\n");
	s = s.replace(/\r\n/g, "\n");
	if (!s.includes("ChapterProps.Hotel")) s = s.replace(/(local Props = require\(script\.Parent\.Parent\.Props\)\n)/, "$1local CP = require(script.Parent.Parent.ChapterProps.Hotel)\n");
	s = s.replace(/\tProps = \{[^\n]*\n/, PROPS_LINE + "\n").replace(/\tWalkable = \{[^\n]*\n/, WALK_LINE + "\n");
	return crlf ? s.replace(/\n/g, "\r\n") : s;
}
if (!process.argv.includes("--dry")) {
	const tmp = path.join(fs.mkdtempSync(path.join(require("os").tmpdir(), "stage6-")), "Stage6.luau");
	fs.writeFileSync(tmp, patchProps());
	const outDir = process.env.STAGE_OUT_DIR;
	delete process.env.STAGE_OUT_DIR;
	writeStage(path.relative(path.dirname(sf), tmp), g, [
		"STAGE 6 — 호텔 (47x43칸, 2층 건물, tools/places/hotel.js 로 생성)",
		"1층(뒤쪽 서비스 → 공용): 북쪽 직원 구역(휴게실=시작·락커실·세탁실·린넨 보관실·직원 식당·기계실, 직원 복도·사무 복도 사이 샛문),",
		"가운데 서비스 구역(서비스 복도 · 메인 주방─냉장실/세척실─서비스 계단─그랜드 볼룸 · 연회 준비 복도),",
		"남쪽 공용 구역(공용 복도 · 레스토랑─룸서비스 팬트리─라운지 바─짐 보관실 · 남쪽 복도) → 프런트 로비 정문(출구).",
		"2층(Rows2) 객실층: 객실 복도 고리가 코어(엘리베이터 홀·층 린넨실·하우스키핑·제빙기실·청소 창고)를 둘러싼다.",
		"북쪽 객실 줄, 남쪽 스위트 줄(거실+침실), 코어 쪽 커넥팅 룸 한 쌍. 계단 셋: 동쪽 주 계단, 가운데 서비스 계단, 서쪽 비상계단.",
		"가운데 띠 → 남쪽 띠로 내려가는 길 셋: 서쪽 직원 통로, 배식 통로(연회 준비 복도 ↔ 레스토랑 앞), 서쪽 비상계단(2층).",
		`출구까지 최단 약 ${r.exit}칸.`,
	]);
	fs.copyFileSync(tmp, outDir ? path.join(outDir, "Stage6.luau") : sf);
}
