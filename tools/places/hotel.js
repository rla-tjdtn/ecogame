		"서쪽 1층: 직원 휴게실(시작)·락커실·세탁실(세탁기 줄)·린넨실─창고·주방─연회장(기둥·원탁), 직원 복도.",
		"2층 객실층: 가운데 코어(린넨실·제빙실·엘리베이터 홀·하우스키핑)를 두 객실 복도가 둘러싸는 레이스트랙, 바깥쪽으로 작은 객실이 빽빽이",
		"(침대 R·서랍장 Z·옷장 L). 동쪽 1층: 중앙 계단 홀·라운지 바·비즈니스 센터·짐 보관실·프런트 로비(데스크·기둥, 정문 출구).",
		"살짝 뒤틀린 곳: 복도마다 무너진 천장·쓰러진 카트로 막힌 칸(세탁실·라운지를 가로지르거나 커넥팅 룸 샛문으로 돌아감),",
