// 챕터 2 물류 창고: 선반 보관동·지게차 주 통로·냉동 창고·하역장·컨테이너 야적장·사무동, 2층 메자닌 사무실·캣워크.
//   node tools/places/warehouse.js [--dry] [--print]
// 큰 흐름(S자 세 띠, 띠마다 두세 갈래):
//   위 띠(y1~19): 북동쪽 경비실(시작) → 냉동 창고 / 주 통로 / 위 보관동 / 2층 메자닌 중 골라 서쪽으로
//   가운데 띠(y21~28): 아래 보관동 다섯 개를 위·아래 샛문 두 줄로 동쪽으로
//   아래 띠(y30~41): 사무동 복도 / 사무실 → 충전실 / 부품 창고 → 하역장 → 컨테이너 야적장 출구(남서쪽)
const { Grid, report, writeStage } = require("./lib");

const g = new Grid(47, 43);
const up = g.floor2(); // 2층(1층 위에 같은 크기로 겹쳐 쌓는다): 북쪽 메자닌 사무실·캣워크, 나머지는 높은 천장(벽)

// 보관동: x0..x1, y0..y1 에 가로 선반 줄(H)을 rows 에, 선반은 양 끝 한 칸씩 비워 통로를 남긴다
function bay(x0, y0, x1, y1, rows, { gapL = 1, gapR = 1, breaks = [], on = g } = {}) {
	on.fill(x0, y0, x1, y1);
	for (const y of rows) for (let x = x0 + gapL; x <= x1 - gapR; x++) if (!breaks.includes(x)) on.set(x, y, "H");
}

// ══ 2층 메자닌 (x1~29, y1~6): 방(y1~4) + 캣워크(y6) ══ 계단 세 곳(A·B·C 보관동 북쪽 벽에서 올라온다)
up.fill(1, 6, 29, 6);
up.fill(1, 1, 7, 4).set(4, 5, "D"); // 2층 관리 사무실
up.put("T", [[2, 2], [6, 2]]).set(1, 4, "Z").set(7, 1, "L");
up.fill(9, 1, 14, 4).set(11, 5, "D").set(8, 3, "D"); // 회의실(관리 사무실과 안쪽 문)
up.put("T", [[11, 2], [12, 2]]).set(14, 4, "Z");
up.fill(16, 1, 20, 4).set(18, 5, "D"); // 서류 창고
up.put("c", [[16, 1], [17, 1], [20, 4], [20, 1]]);
up.fill(22, 1, 29, 4).set(23, 5, "D").set(28, 5, "D"); // 2층 휴게실(문 2개)
up.put("T", [[25, 2]]).set(29, 1, "L").set(22, 1, "Z");
// ══ 메자닌 아래 1층 (y1~5): 포장실(냉장실 쪽 문) → 안쪽 검수실(막다른 방) ══
g.fill(16, 1, 29, 5).set(30, 3, "D").set(15, 3, "D");
g.put("u", [[18, 1], [19, 1], [20, 1], [22, 1], [23, 1], [24, 1]]).put("T", [[20, 4], [24, 4]]) // (북벽 컨베이어 줄 + 포장대).set(29, 1, "L").set(16, 5, "c"); // (문 하나뿐인 방에는 열쇠 상자를 두지 않는다)
g.fill(9, 1, 14, 5).put("J", [[10, 3]]).put("c", [[14, 5]]) // (검수 대기 팔레트).set(9, 5, "L"); // (막다른 방 안쪽에는 열쇠 상자를 두지 않는다)

// ══ 위 보관동 (y9~16) ══ A·B 샛문, B·C 샛문, 주 통로로 하역문(2칸 폭)
bay(1, 9, 8, 16, [11, 13, 15]); // A
bay(10, 9, 17, 16, [11, 13, 15]); // B
bay(19, 9, 29, 16, [11, 13, 15], { breaks: [24] }); // C
g.set(9, 12, "D").set(18, 14, "D");
for (const x of [3, 4, 12, 13, 21, 22, 27, 28]) g.set(x, 17, ".");
g.set(1, 9, "Z").set(8, 16, "L").set(17, 9, "Z").set(19, 16, "L").set(29, 16, "Z");

// ══ 냉동 창고·경비실 (x31~45, y1~16) ══
g.fill(31, 1, 37, 10).set(30, 9, "D").set(34, 11, "D"); // 냉장실: C 보관동 쪽 문 + 전실 문
for (const x of [32, 34, 36]) for (let y = 3; y <= 7; y++) g.set(x, y, "h");
g.set(37, 1, "Z").set(31, 1, "c").set(34, 1, "e"); // (천장 쪽 냉동기 증발기)
g.fill(39, 1, 45, 10).set(38, 5, "D").set(42, 11, "D"); // 냉동실: 냉장실 ↔ 경비실 사이로 지나는 방
for (const x of [40, 42, 44]) for (let y = 2; y <= 7; y++) g.set(x, y, "h");
g.set(39, 10, "Z").set(45, 1, "L").set(39, 1, "c").set(42, 1, "e");
g.fill(31, 12, 39, 16).set(33, 17, "D").set(37, 17, "D"); // 전실(작업장): 기둥, 주 통로로 문 2개
g.put("O", [[34, 14], [37, 14]]).set(31, 16, "Z").set(39, 12, "L").set(32, 12, "F"); // (출고 준비 지게차)
g.fill(41, 12, 45, 16).set(40, 14, "D").set(43, 17, "D"); // 경비실(시작): 전실·냉동실·주 통로로 문 3개
g.put("S", [[44, 15], [45, 15], [44, 16], [45, 16]]).put("T", [[43, 13]]).set(45, 12, "Z").set(41, 16, "L");

// ══ 지게차 주 통로 (y18~19) ══ B·C 보관동 사이가 쓰러진 선반으로 막혔다(보관동이나 메자닌으로 돌아간다)
g.fill(1, 18, 45, 19);
g.wall(18, 18, 18, 19).put("c", [[17, 18], [19, 19]]);
g.set(1, 18, "L").set(30, 19, "Z").set(45, 19, "c");
// 주 통로 → 아래 보관동은 서쪽 두 곳(A'·B')으로만 내려간다
for (const x of [3, 4, 7]) g.set(x, 20, ".");

// ══ 아래 보관동 (y21~28) ══ 이웃 보관동과 샛문 두 줄(y22·y27)로 이어진다
bay(1, 21, 8, 28, [23, 25]); // A'
bay(10, 21, 17, 28, [24, 26]); // B'
bay(19, 21, 27, 28, [23, 25]); // C'
bay(29, 21, 36, 28, [24, 26]); // D'
bay(38, 21, 45, 28, [23, 25]); // E'(출고 대기)
for (const x of [9, 37]) g.set(x, 22, "D").set(x, 27, "D");
g.set(18, 22, "D").set(18, 27, "D").set(28, 22, "D"); // (C·D 칸막이는 샛문 하나: 갈래를 너무 늘리지 않는다)
g.set(8, 21, "Z").set(10, 28, "L").set(27, 21, "Z").set(29, 28, "L").set(45, 28, "Z").set(1, 28, "L");
// 아래 띠로는 동쪽 E' 두 곳으로만 내려간다
g.set(39, 29, "D").set(44, 29, "D");

// ══ 사무동 (x30~45, y30~41) ══ 북쪽 방 둘 → 복도(y34~35) → 남쪽 방 둘, 복도 서쪽 끝은 충전실로 열림
g.fill(30, 30, 36, 32).set(33, 33, "D"); // 출고 사무실(막다른 방)
g.put("T", [[31, 31], [35, 31]]).set(36, 30, "L");
g.fill(38, 30, 45, 32).set(39, 33, "D").set(44, 33, "D"); // 휴게실(문 4개: 위 E', 아래 복도)
g.put("T", [[41, 31], [42, 31]]).set(38, 30, "L").set(45, 30, "c");
g.fill(29, 34, 45, 35); // 사무동 복도
g.set(45, 34, "L").set(31, 35, "Z"); // (복도 남쪽 벽 상자)
g.fill(30, 37, 37, 41).set(36, 36, "D").set(29, 39, "D"); // 사무실(부품 창고로 뒷문)
g.put("T", [[32, 39], [35, 39]]).set(37, 41, "Z").set(30, 37, "L");
g.fill(39, 37, 45, 41).set(42, 36, "D").set(38, 40, "D"); // 탈의실(사물함, 사무실로 샛문)
g.put("L", [[39, 41], [41, 41], [43, 41]]).set(45, 37, "Z");

// ══ 지게차 충전실 (x19~28, y30~35) · 부품 창고 (x19~28, y37~41) ══ 사이 문, 둘 다 하역장으로 문
g.fill(19, 30, 28, 35).set(18, 32, "D").set(24, 36, "D");
g.put("g", [[20, 30], [22, 30], [24, 30], [26, 30]]).put("F", [[23, 34]]).put("c", [[28, 30], [19, 35]]) // (북벽 충전기 넷 + 충전 중인 지게차).set(19, 33, "Z");
g.fill(19, 37, 28, 41).set(18, 39, "D");
g.put("c", [[19, 41], [20, 41], [28, 37]]).put("h", [[22, 38], [22, 39], [22, 40], [25, 38], [25, 39], [25, 40]]).set(28, 41, "Z").set(19, 37, "L");

// ══ 하역장 (x10~17, y30~41) ══ 서쪽 벽에 트럭 도크 두 곳(2칸 폭)으로 컨테이너 야적장
g.fill(10, 30, 17, 41);
g.put("K", [[12, 33], [13, 33], [12, 38], [13, 38]]).put("Q", [[16, 35], [16, 36]]).set(17, 41, "Z").set(10, 30, "L").put("J", [[14, 41], [11, 41]]); // (하역 대기 팔레트)
for (const y of [31, 32, 38, 39]) g.set(9, y, ".");

// ══ 컨테이너 야적장 (x2~8, y30~41) ══ 서쪽 철문(출구)
g.fill(2, 30, 8, 41);
g.put("K", [[4, 33], [5, 33], [4, 34], [5, 34]]).put("Q", [[6, 38], [6, 39], [3, 40]]);
g.set(1, 36, "E");
g.set(8, 30, "Z").set(2, 41, "L");

// ══════════════ 2층 (1층과 같은 크기) ══════════════
// 북쪽 메자닌 층(x1~29, y1~16): 사무실 줄(y1~4) 아래로 랙 보관 메자닌(y6~16)이 위 보관동 A·B·C 를 덮는다(계단 구멍 셋, 둘레 난간).
// 남쪽 2층 보관층(x1~45, y21~28): 가운데 띠 위를 서 → 동으로 가로지르는 셋째 길. 서쪽 끝 계단(주 통로 서쪽 끝에서 올라옴) →
//   보관 홀 셋(샛문) → 2층 사무동(x29~45, y30~41: 전산실·기록실·복도·회의실) → 계단으로 1층 사무동 복도에 내려선다.
// 야적장(바깥)·하역장(높은 천장) 위는 2층이 없다.
up.fill(1, 6, 29, 16); // 메자닌 바닥(캣워크 포함)
for (const y of [10, 12, 14]) for (const [a, b] of [[2, 7], [10, 13], [16, 21], [23, 28]]) for (let x = a; x <= b; x++) if (up.get(x, y) === ".") up.set(x, y, "H");
g.stairs(4, 8, 0, -1).stairs(14, 8, 0, -1).stairs(26, 8, 0, -1); // (A·B·C 보관동 북쪽 벽 계단 → 메자닌 바닥, 2층에는 구멍)
up.put("Z", [[29, 9], [1, 16]]).put("L", [[29, 16]]).put("c", [[9, 16], [10, 16], [20, 16]]);
// 남쪽 2층 보관층: 홀 셋(x1~14, x16~28, x30~45), 홀 사이 샛문 위·아래 두 곳
bay(1, 21, 14, 28, [23, 26], { on: up, breaks: [7, 8] });
bay(16, 21, 28, 28, [24], { on: up, breaks: [22] });
bay(30, 21, 45, 28, [23, 26], { on: up, breaks: [37, 38] });
up.set(15, 22, "D").set(29, 27, "D");
up.put("Z", [[14, 21], [28, 28], [45, 21]]).put("L", [[16, 21], [30, 28]]).put("c", [[1, 28], [2, 28], [45, 28]]);
// 2층 사무동: 전산실(서버 랙 m)·기록실(서류 c) / 복도 y34~35 / 회의실·자료실. 보관층과는 문 두 곳(y29)
up.fill(30, 30, 36, 32).fill(38, 30, 45, 32).fill(30, 34, 45, 35).fill(30, 37, 37, 41).fill(39, 37, 45, 41);
up.set(33, 29, "D").set(41, 29, "D").set(33, 33, "D").set(41, 33, "D").set(31, 36, "D").set(42, 36, "D").set(37, 31, "D");
up.put("R", [[30, 30], [31, 30], [33, 30], [34, 30]]).put("c", [[38, 30], [39, 30], [45, 32]]).set(36, 32, "Z").set(45, 30, "L");
up.put("T", [[32, 39], [35, 39], [41, 39], [43, 39]]).set(30, 41, "L").set(45, 41, "Z").set(45, 35, "c");
up.set(38, 39, "D"); // (회의실 ↔ 자료실)
// 계단: 주 통로 서쪽 끝(1층 A' 보관동 북서 구석으로 들어간 계단실) ↑ 2층 보관층, 1층 사무동 복도 ↓ 2층 사무실
g.set(2, 21, "#").set(2, 22, "#").stairs(1, 20, 0, 1); // (1층: 계단실 양옆 벽, 꼭대기 앞 벽)
g.set(33, 37, "#").set(35, 37, "#").stairs(34, 36, 0, 1);

const opts = { blocked: ["H", "h"] };
const r = report("물류 창고", g, opts);
if (process.argv.includes("--print")) for (const [name, gr] of [["1층", g], ["2층", up]]) console.log(name + "\n" + gr.rows().map((row, i) => String(i).padStart(2) + " " + row).join("\n"));
if (!process.argv.includes("--dry"))
	writeStage("Stage2.luau", g, [
		"STAGE 2 — 물류 창고 (47x43칸 2층 건물: Rows 1층 + 같은 크기 Rows2 2층, tools/places/warehouse.js 로 생성, 설계 문서 docs/levels/stage2.md)",
		"S자 세 띠, 띠마다 두세 갈래. 위 띠: 북동쪽 경비실(시작, 문 3개)에서 냉동 창고(냉장실·냉동실, 세로 선반 h) / 지게차 주 통로(2칸 폭) /",
		"위 보관동 A·B·C(가로 선반 H, 샛문·하역문) / 2층 메자닌 층(사무실 줄 + 랙 메자닌, 보관동 북벽 계단 셋) 중 골라 서쪽으로. 메자닌 아래 1층은 포장실(컨베이어)·검수실.",
		"주 통로는 B·C 사이가 쓰러진 선반으로 막혀 보관동이나 메자닌으로 돌아간다. 주 통로에서 A'·B' 두 곳으로 내려가",
		"가운데 띠: 아래 보관동 다섯 개(A'~E')를 샛문으로 동쪽으로(또는 주 통로 서쪽 끝 계단 → 2층 보관층 → 2층 사무동 → 계단으로 1층 사무동). D'·E' 두 곳으로 내려가",
		"아래 띠: 사무동(출고 사무실·휴게실 → 복도 → 사무실·탈의실) → 지게차 충전실 / 부품 창고 → 하역장(컨테이너) → 트럭 도크 두 곳 →",
		`남서쪽 컨테이너 야적장 서쪽 철문(출구). 괴물 하나가 어디 서도 돌아가는 길이 있다(목 0, tools/level-graph.js). 출구까지 최단 약 ${r.exit}칸.`,
		"장비(ChapterProps/Warehouse): 지게차 F·팔레트 J·컨베이어 u·충전기 g·증발기 e·서버 랙 R.",
	]);
