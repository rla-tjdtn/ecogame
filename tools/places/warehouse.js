// 챕터 2 물류 창고: 선반 보관동·지게차 주 통로·냉동 창고·하역장·컨테이너 야적장·사무동, 2층 메자닌 사무실·캣워크.
//   node tools/places/warehouse.js [--dry] [--print]
// 큰 흐름(S자 세 띠, 띠마다 두세 갈래):
//   위 띠(y1~19): 북동쪽 경비실(시작) → 냉동 창고 / 주 통로 / 위 보관동 / 2층 메자닌 중 골라 서쪽으로
//   가운데 띠(y21~28): 아래 보관동 다섯 개를 위·아래 샛문 두 줄로 동쪽으로
//   아래 띠(y30~41): 사무동 복도 / 사무실 → 충전실 / 부품 창고 → 하역장 → 컨테이너 야적장 출구(남서쪽)
const { Grid, report, writeStage } = require("./lib");

const g = new Grid(47, 43);
g.markUpper(1, 1, 29, 6);

// 보관동: x0..x1, y0..y1 에 가로 선반 줄(H)을 rows 에, 선반은 양 끝 한 칸씩 비워 통로를 남긴다
function bay(x0, y0, x1, y1, rows, { gapL = 1, gapR = 1, breaks = [] } = {}) {
	g.fill(x0, y0, x1, y1);
	for (const y of rows) for (let x = x0 + gapL; x <= x1 - gapR; x++) if (!breaks.includes(x)) g.set(x, y, "H");
}

// ══ 2층 메자닌 (x1~29, y1~6): 방(y1~4) + 캣워크(y6) ══ 계단 세 곳(A·B·C 보관동 북쪽 벽)
g.fill(1, 6, 29, 6);
g.fill(1, 1, 7, 4).set(4, 5, "D"); // 2층 관리 사무실
g.put("T", [[2, 2], [6, 2]]).set(1, 4, "Z").set(7, 1, "L");
g.fill(9, 1, 14, 4).set(11, 5, "D").set(8, 3, "D"); // 회의실(관리 사무실과 안쪽 문)
g.put("T", [[11, 2], [12, 2]]).set(14, 4, "Z");
g.fill(16, 1, 20, 4).set(18, 5, "D"); // 서류 창고
g.put("c", [[16, 1], [17, 1], [20, 4]]).set(20, 1, "Z");
g.fill(22, 1, 29, 4).set(23, 5, "D").set(28, 5, "D"); // 2층 휴게실(문 2개)
g.put("T", [[25, 2]]).set(29, 1, "L").set(22, 1, "Z");
g.stairs(4, 8, 0, -1).stairs(14, 8, 0, -1).stairs(26, 8, 0, -1);

// ══ 위 보관동 (y9~16) ══ A·B 샛문, B·C 샛문, 주 통로로 하역문(2칸 폭)
bay(1, 9, 8, 16, [11, 13, 15]); // A
bay(10, 9, 17, 16, [11, 13, 15]); // B
bay(19, 9, 29, 16, [11, 13, 15], { breaks: [24] }); // C
g.set(9, 12, "D").set(18, 14, "D");
for (const x of [3, 4, 12, 13, 21, 22, 27, 28]) g.set(x, 17, ".");
g.set(1, 9, "Z").set(8, 16, "L").set(17, 9, "Z").set(19, 16, "L").set(29, 16, "Z");

// ══ 냉동 창고·경비실 (x31~45, y1~16) ══
g.fill(31, 1, 37, 10).set(30, 9, "D").set(34, 11, "D"); // 냉장실: C 보관동 쪽 문 + 전실 문
for (const x of [32, 34, 36]) for (let y = 3; y <= 7; y++) g.set(x, y, "h");
g.set(37, 1, "Z").set(31, 1, "c");
g.fill(39, 1, 45, 10).set(38, 5, "D").set(42, 11, "D"); // 냉동실: 냉장실 ↔ 경비실 사이로 지나는 방
for (const x of [40, 42, 44]) for (let y = 2; y <= 7; y++) g.set(x, y, "h");
g.set(39, 10, "Z").set(45, 1, "L").set(39, 1, "c");
g.fill(31, 12, 39, 16).set(33, 17, "D").set(37, 17, "D"); // 전실(작업장): 기둥, 주 통로로 문 2개
g.put("O", [[34, 14], [37, 14]]).set(31, 16, "Z").set(39, 12, "L");
g.fill(41, 12, 45, 16).set(40, 14, "D").set(43, 17, "D"); // 경비실(시작): 전실·냉동실·주 통로로 문 3개
g.put("S", [[44, 15], [45, 15], [44, 16], [45, 16]]).put("T", [[43, 13]]).set(45, 12, "Z").set(41, 16, "L");

// ══ 지게차 주 통로 (y18~19) ══ B·C 보관동 사이가 쓰러진 선반으로 막혔다(보관동이나 메자닌으로 돌아간다)
g.fill(1, 18, 45, 19);
g.wall(18, 18, 18, 19).put("c", [[17, 18], [19, 19]]);
g.set(1, 18, "L").set(30, 19, "Z").set(45, 19, "c");
// 주 통로 → 아래 보관동은 서쪽 두 곳(A'·B')으로만 내려간다
for (const x of [3, 4, 7]) g.set(x, 20, ".");

// ══ 아래 보관동 (y21~28) ══ 이웃 보관동과 샛문 두 줄(y22·y27)로 이어진다
bay(1, 21, 8, 28, [23, 25]); // A'
bay(10, 21, 17, 28, [24, 26]); // B'
bay(19, 21, 27, 28, [23, 25]); // C'
bay(29, 21, 36, 28, [24, 26]); // D'
bay(38, 21, 45, 28, [23, 25]); // E'(출고 대기)
for (const x of [9, 18, 28, 37]) g.set(x, 22, "D").set(x, 27, "D");
g.set(8, 21, "Z").set(10, 28, "L").set(27, 21, "Z").set(29, 28, "L").set(45, 28, "Z").set(1, 28, "L");
// 아래 띠로는 동쪽 E' 두 곳으로만 내려간다
g.set(39, 29, "D").set(44, 29, "D");

// ══ 사무동 (x30~45, y30~41) ══ 북쪽 방 둘 → 복도(y34~35) → 남쪽 방 둘, 복도 서쪽 끝은 충전실로 열림
g.fill(30, 30, 36, 32).set(33, 33, "D"); // 출고 사무실(막다른 방)
g.put("T", [[31, 31], [35, 31]]).set(36, 30, "Z");
g.fill(38, 30, 45, 32).set(39, 33, "D").set(44, 33, "D"); // 휴게실(문 4개: 위 E', 아래 복도)
g.put("T", [[41, 31], [42, 31]]).set(38, 30, "L").set(45, 30, "c");
g.fill(29, 34, 45, 35); // 사무동 복도
g.set(45, 34, "L");
g.fill(30, 37, 37, 41).set(36, 36, "D").set(29, 39, "D"); // 사무실(부품 창고로 뒷문)
g.put("T", [[32, 39], [35, 39]]).set(37, 41, "Z").set(30, 37, "L");
g.fill(39, 37, 45, 41).set(42, 36, "D").set(38, 40, "D"); // 탈의실(사물함, 사무실로 샛문)
g.put("L", [[39, 41], [41, 41], [43, 41]]).set(45, 37, "Z");

// ══ 지게차 충전실 (x19~28, y30~35) · 부품 창고 (x19~28, y37~41) ══ 사이 문, 둘 다 하역장으로 문
g.fill(19, 30, 28, 35).set(18, 32, "D").set(24, 36, "D");
g.put("m", [[20, 30], [22, 30], [24, 30], [26, 30]]).put("c", [[28, 30], [19, 35]]).set(19, 33, "Z");
g.fill(19, 37, 28, 41).set(18, 39, "D");
g.put("c", [[19, 41], [20, 41], [28, 37]]).put("h", [[22, 38], [22, 39], [22, 40], [25, 38], [25, 39], [25, 40]]).set(28, 41, "Z").set(19, 37, "L");

// ══ 하역장 (x10~17, y30~41) ══ 서쪽 벽에 트럭 도크 두 곳(2칸 폭)으로 컨테이너 야적장
g.fill(10, 30, 17, 41);
g.put("K", [[12, 33], [13, 33], [12, 38], [13, 38]]).put("Q", [[16, 35], [16, 36]]).set(17, 41, "Z").set(10, 30, "L");
for (const y of [31, 32, 38, 39]) g.set(9, y, ".");

// ══ 컨테이너 야적장 (x2~8, y30~41) ══ 서쪽 철문(출구)
g.fill(2, 30, 8, 41);
g.put("K", [[4, 33], [5, 33], [4, 34], [5, 34]]).put("Q", [[6, 38], [6, 39], [3, 40]]);
g.set(1, 36, "E");
g.set(8, 30, "Z").set(2, 41, "L");

const opts = { blocked: ["H", "h"] };
const r = report("물류 창고", g, opts);
if (process.argv.includes("--print")) console.log(g.rows().map((row, i) => String(i).padStart(2) + " " + row).join("\n"));
if (!process.argv.includes("--dry"))
	writeStage("Stage2.luau", g, [
		"STAGE 2 — 물류 창고 (47x43칸, tools/places/warehouse.js 로 생성)",
		"S자 세 띠, 띠마다 두세 갈래. 위 띠: 북동쪽 경비실(시작, 문 3개)에서 냉동 창고(냉장실·냉동실, 세로 선반 h) / 지게차 주 통로(2칸 폭) /",
		"위 보관동 A·B·C(가로 선반 H, 샛문·하역문) / 2층 메자닌(UpperRects: 캣워크 + 관리 사무실·회의실·서류 창고·휴게실, 계단 세 곳) 중 골라 서쪽으로.",
		"주 통로는 B·C 사이가 쓰러진 선반으로 막혀 보관동이나 메자닌으로 돌아간다. 주 통로에서 A'·B' 두 곳으로 내려가",
		"가운데 띠: 아래 보관동 다섯 개(A'~E')를 위·아래 샛문 두 줄로 동쪽으로. D'·E' 두 곳으로 내려가",
		"아래 띠: 사무동(출고 사무실·휴게실 → 복도 → 사무실·탈의실) → 지게차 충전실 / 부품 창고 → 하역장(컨테이너) → 트럭 도크 두 곳 →",
		`남서쪽 컨테이너 야적장 서쪽 철문(출구). 어느 칸을 막아도 돌아가는 길이 있다(목 0). 출구까지 최단 약 ${r.exit}칸.`,
	]);
