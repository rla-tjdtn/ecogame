// 챕터 3 하수도: 나뭇가지 모양 하수망의 아래쪽 끝. 굵은 간선 차집관로(보행로 2 / 수로 / 보행로 2, 5칸 폭)가 상류 낙차 맨홀실(북동, 시작)에서
// 북 → 서 → 남 → 동으로 맵 가장자리를 돌아 내려가다가 동쪽 위에서 서쪽으로 꺾여 맵 한가운데 배수 펌프장 집수정으로 흘러든다.
// 안쪽에는 지선 관리용 점검 갤러리(2칸 폭)가 간선을 따라 한 바퀴 돌며 관리 사무실·맨홀 수직갱실·밸브실·침사지·월류 위어실을 잇는다.
// 출구: 펌프장 서쪽 우수 저류조(사각 저류실 + 둥근 집수 웅덩이)의 점검 수직갱 사다리. 시작과는 흙벽·갤러리를 사이에 두고 30칸 넘게 떨어져 있다.
//   node tools/places/sewer.js [--dry] [--print]
// 수로 w 는 6스터드 낮은 물길(PitTiles): 걸어서는 못 건너고 철제 다리 b(물길 줄 위에만)로 반대편 보행로로 건넌다.
// 지선 물은 간선 위 천장 유입관 Q 로 떨어진다 — 지선 수로가 보행로를 가로지르는 곳이 없다(보행로는 끊김 없는 바닥: Studio 길찾기가 다리 난간에 걸리지 않게).
// 서로 떨어진 세 갈래(간선 바깥 보행로 / 안쪽 보행로 / 점검 갤러리)가 끝까지 나란히 가서, 괴물 둘로는 맵을 가르지 못한다(tools/level-graph.js bigcut).
const fs = require("fs");
const os = require("os");
const path = require("path");
const { Grid, report, writeStage } = require("./lib");

const g = new Grid(47, 43);

// ══ 큰 뼈대(QA 2차 재작업) ══
// 상류 낙차 맨홀실(시작, 북동) → 굵은 간선 차집관로(보행로 2 / 수로 / 보행로 2)가 북 → 서 → 남 → 동으로 맵 가장자리를 돌아 내려가다가
// 동쪽 위에서 서쪽으로 꺾여 맵 한가운데 배수 펌프장으로 흘러든다. 펌프장 서쪽 우수 저류조의 점검 수직갱 사다리가 출구다(시작에서 흙벽 너머 약 30칸).
// 서로 떨어진 세 갈래가 끝까지 나란히 간다(괴물 둘로는 맵을 가르지 못한다):
//   ① 간선 바깥 보행로  ② 간선 안쪽 보행로(둘 사이는 물길 — 다리는 시작 맨홀실 하나뿐)  ③ 안쪽 점검 갤러리(지선 관리 통로: 관리 사무실 → 밸브실 → 침사지 → 월류 위어실)
// 지선 물은 간선 위 천장 유입관(Q)으로 떨어진다 — 지선 수로가 보행로를 가로지르지 않는다(보행로는 끊김 없는 바닥, 다리 b 는 간선 물길 위에만).

// ── 간선 차집관로(5칸 폭) ──
g.fill(1, 1, 45, 5); // 북쪽 간선
g.fill(1, 1, 5, 41); // 서쪽 간선
g.fill(1, 37, 45, 41); // 남쪽 간선
g.fill(41, 13, 45, 41); // 동쪽 간선(위로 거슬러 올라간다)
g.fill(36, 13, 45, 17); // 펌프장 유입 터널(동쪽 간선이 서쪽으로 꺾인다)
// 물길: 북 y3 → 서 x3 → 남 y39 → 동 x43 → 유입 터널 y15 → 펌프장 집수정
g.fill(3, 3, 44, 3, "w").fill(3, 3, 3, 39, "w").fill(3, 39, 43, 39, "w").fill(43, 15, 43, 39, "w").fill(26, 15, 43, 15, "w");
g.set(45, 3, "Q"); // (시작: 동쪽 벽 큰 유입관에서 오수가 떨어진다)
g.put("Q", [[20, 3], [3, 22], [30, 39]]); // (지선이 간선 천장 유입관으로 떨어진다)
g.put("K", [[3, 12], [24, 39]]); // (간선 위를 가로지르는 배관 다리 — 머리 위 높이)
g.put("P", [[12, 1], [12, 2], [44, 28], [45, 28]]);
g.put("b", [[9, 3], [30, 3], [3, 18], [3, 30], [14, 39], [43, 26]]); // (간선 물길을 건너는 철제 다리 여섯 — 바깥·안쪽 보행로를 잇는다. 다리는 물길 줄 위에만 놓는다) // (보행로 위 천장 압송관)
g.put("l", [[1, 18], [45, 33]]); // (벽 사다리: 지상 맨홀)

// ── 상류 낙차 맨홀실(시작, x40~45, y1~7): 지상 맨홀 사다리로 내려온 곳. 수로 위 철제 다리(바깥 보행로로) · 남쪽 점검 갤러리 문 ──
g.fill(40, 6, 45, 7).set(44, 3, "b").set(41, 8, "D");
g.put("S", [[44, 6], [45, 6], [44, 7], [45, 7]]);
g.set(40, 7, "c").set(45, 1, "L").set(40, 1, "l");

// ── 점검 갤러리(2칸 폭, 지선 관리 통로): 북(y9~10) → 서(x8~9) → 남(y33~34) → 동(x37~38) → 펌프장 동쪽 문 둘 ──
g.fill(8, 9, 41, 10).fill(8, 9, 9, 34).fill(8, 33, 38, 34).fill(37, 19, 38, 34).set(36, 20, "D").set(36, 25, "D");
// 관리 사무실(x22~29, y8~11): 갤러리가 가로지른다. 양 끝 문(갤러리 한 칸은 문, 한 칸은 문설주 벽)
g.fill(22, 8, 29, 11).set(21, 9, "D").set(21, 10, "#").set(30, 10, "D").set(30, 9, "#");
g.put("T", [[23, 8], [26, 8]]).put("C", [[28, 8], [22, 11]]).set(29, 8, "Y").set(25, 11, "Z").set(29, 11, "L");
// 맨홀 수직갱실(x13~17, y8~11): 갤러리 위 지상 맨홀로 통하는 둥근 수직갱
g.fill(13, 8, 17, 11).set(15, 8, "R").set(13, 11, "c");
// 밸브실(x7~9, y18~23): 서쪽 갤러리를 문 둘로 끊는다(엇갈린 문). 지선 수문 밸브·수문 조작기·계기반
g.fill(7, 18, 9, 23).set(8, 17, "D").set(9, 17, "#").set(9, 24, "D").set(8, 24, "#");
g.put("V", [[7, 18], [7, 21]]).set(7, 23, "G").set(7, 19, "Z").set(6, 20, "D"); // (서쪽 벽 점검문 → 간선 안쪽 보행로)
// 침사지(x14~23, y29~34): 모래를 가라앉히는 넓은 홈(y31 수로) + 스크린. 갤러리가 남쪽 보행로로 지난다
g.fill(14, 29, 23, 34).fill(15, 31, 22, 31, "w").set(18, 31, "H");
g.set(14, 29, "Z").put("I", [[23, 29]]);
// 월류 위어실(x28~35, y29~34): 비 오는 날 넘친 물을 가르는 둑(U) + 작업대
g.fill(28, 29, 35, 34).fill(29, 31, 34, 31, "w").set(31, 31, "U");
g.set(35, 34, "Z").put("J", [[28, 29]]).set(35, 29, "L");

// 갤러리 ↔ 간선 안쪽 보행로 점검문(두 겹 벽을 뚫은 짧은 문 통로): 서쪽 둘(밸브실 포함) · 남쪽 둘 · 동쪽 하나
g.set(6, 12, "D").set(7, 12, ".").set(25, 36, "D").set(25, 35, ".").set(31, 36, "D").set(31, 35, ".").set(40, 22, "D").set(39, 22, ".");

// ── 배수 펌프장(x24~35, y13~27): 유입 터널 물길이 집수정(서쪽 끝)으로. 북쪽 보행로 · 남쪽 펌프 바닥(펌프 셋, 밸브, 계기반, 머리 위 압송관) ──
g.fill(24, 13, 35, 27).set(30, 15, "H");
g.put("M", [[27, 20], [31, 20], [27, 24]]).put("V", [[33, 24]]).put("Y", [[24, 22]]).put("P", [[29, 22], [30, 22], [31, 22]]);
g.set(35, 26, "Z").set(24, 27, "Z").set(35, 13, "L");
// ── 우수 저류조(x12~23, y13~27): 사각 저류실 + 가운데 둥근 집수 웅덩이(지름 5) + 기둥. 펌프장과는 기둥 줄(x23)로만 나뉜다(벽 없음).
//    서쪽 벽 점검 수직갱 사다리 = 출구(지상) ──
g.fill(12, 13, 23, 27);
const CX = 17, CY = 20;
for (let y = CY - 3; y <= CY + 3; y++) for (let x = CX - 3; x <= CX + 3; x++) if ((x - CX) ** 2 + (y - CY) ** 2 <= 2.3 * 2.3) g.set(x, y, "w");
g.set(17, 20, "Q"); // (천장 빗물 유입관이 웅덩이 가운데로 떨어진다)
g.put("O", [[23, 14], [23, 18], [23, 22], [23, 26], [14, 16], [20, 16], [14, 24], [20, 24]]).set(17, 27, "Z").set(12, 13, "L");
g.set(11, 20, "E");

// ── 열쇠 상자·숨는 곳: 벽을 판 오목한 자리(보행로를 좁히지 않는다) ──
g.put("Z", [[15, 6], [33, 6], [36, 8], [6, 14], [6, 30], [7, 27], [20, 36], [34, 36], [11, 35], [40, 25], [39, 30], [45, 24], [1, 26], [30, 1]]);
g.put("L", [[28, 6], [7, 22], [20, 8], [40, 33], [13, 35], [1, 10], [45, 20]]);

if (process.argv.includes("--print")) console.log(g.rows().map((row, i) => String(i).padStart(2) + " " + row).join(String.fromCharCode(10)));
const PITS = ["w", "H", "Q", "U", "K"];
const WALK = ["P", "l"];
const opts = { id: 3, pits: PITS, walkable: WALK, blocked: ["M", "V", "Y", "G", "J", "I", "T", "C", "R"] };
const r = report("하수도", g, opts);
if (!process.argv.includes("--dry")) {
	// 스테이지 파일은 한 번에 쓴다(Rojo 가 Studio 로 바로 옮긴다): 임시 폴더에 만든 뒤 Props 줄·옛 수로 함수까지 바꿔 한 번에 덮어쓴다
	const outDir = process.env.STAGE_OUT_DIR; // (다른 폴더에 써서 시험할 때)
	const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "stage3-"));
	process.env.STAGE_OUT_DIR = tmp;
	writeStage("Stage3.luau", g, [
		"STAGE 3 — 하수도 (47x43칸, tools/places/sewer.js 로 생성, 설계 문서 docs/levels/stage3.md)",
		"굵은 간선 차집관로(보행로 2 / 수로 w / 보행로 2)가 상류 낙차 맨홀실(시작, 북동) → 북 → 서 → 남 → 동으로 가장자리를 돌아 맵 한가운데 배수 펌프장 집수정으로 흘러든다.",
		"안쪽 점검 갤러리(2칸, 지선 관리 통로)가 간선을 따라 돌며 관리 사무실·맨홀 수직갱실·밸브실·침사지·월류 위어실을 잇고 펌프장 동쪽 문 둘로 든다.",
		"수로는 6스터드 낮은 물길: 철제 다리(b, 물길 줄 위에만)로 반대편 보행로로 건넌다. 지선 물은 천장 유입관 Q 로 떨어진다(보행로를 가로지르는 지선 수로 없음).",
		"출구: 펌프장 서쪽 우수 저류조(사각 저류실 + 둥근 집수 웅덩이, 기둥)의 점검 수직갱 사다리(시작과 흙벽 너머 30칸 넘게 떨어짐).",
		"세 갈래(간선 바깥 보행로 / 안쪽 보행로 / 점검 갤러리)가 끝까지 따로 가서 괴물 둘로는 맵을 가르지 못한다. 갤러리 ↔ 안쪽 보행로 점검문 다섯, 다리 일곱.",
		`괴물 하나가 어디 서도 돌아가는 길이 있다(목 0, tools/level-graph.js). 출구까지 최단 약 ${r.exit}칸.`,
		"장비(ChapterProps/Sewer): 수로 w(물·아치 갈비)·낙차 유입관 Q·배관 다리 K(머리 위)·월류 위어 U·스크린 H·펌프 M·밸브 V·계기반 Y·수문 조작기 G·사다리 l·수직갱 R·압송관 P.",
	]);
	const real = outDir ? path.join(outDir, "Stage3.luau") : path.join(__dirname, "..", "..", "src", "server", "Stages", "Stage3.luau");
	let src = fs.readFileSync(path.join(tmp, "Stage3.luau"), "utf8");
	const nl = src.includes("\r\n") ? "\r\n" : "\n";
	// (예전 스테이지 파일 안의 수로 함수는 ChapterProps/Sewer.Channel 로 옮겼다: require 줄 다음부터 return 전까지 지운다)
	src = src.replace(/(local CP = require\([^\n]*\n)[\s\S]*?(\r?\nreturn \{)/, `$1$2`);
	src = src.replace(/\tProps = \{[^\n]*\n/, `\tProps = { w = CP.Channel, Q = CP.DropInlet, K = CP.PipeBridge, U = CP.Weir, H = CP.BarScreen, P = Props.BigPipe, l = CP.Ladder, M = CP.Pump, V = CP.ValveStand, Y = CP.GaugePanel, G = CP.SluiceGate, J = CP.Workbench, I = CP.PipeStack, R = CP.ManholeShaft, T = Props.Desk, C = Props.Cabinet },${nl}`);
	src = src.replace(/\tPitTiles = \{[^\n]*\n/, `\tPitTiles = { w = true, H = true, Q = true, U = true, K = true }, -- (물길 칸: 아래층 높이)${nl}`);
	src = src.replace(/\tWalkable = \{[^\n]*\n/, `\tWalkable = { P = true, l = true }, -- (머리 위 압송관·벽 사다리는 밑으로 지나간다. 수로는 괴물 배회 지점에서 뺀다: 보행로로만 다닌다)${nl}`);
	src = src.replace(/\tPipeChance = [^\n]*\n/, `\tPipeChance = 0.1, -- (벽 배관은 볼트까지 부품이 많다: 아치 갈비·수로 난간이 이미 선을 많이 그린다 — 부품 여유를 위해 0.2 → 0.1)${nl}`);
	fs.writeFileSync(real, src);
	fs.rmSync(tmp, { recursive: true, force: true });
}
