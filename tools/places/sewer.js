// 챕터 3 하수도: 나뭇가지 모양(수지상) 하수망. 굵은 간선 차집관로(보행로 2 / 수로 / 보행로 2, 5칸 폭)가 북 → 서 → 남 → 동으로 맵 가장자리를 따라 흐르고,
// 안쪽의 지선(3칸 폭: 보행로 / 수로 / 보행로)들이 간선으로 흘러든다. 지선이 모이는 원형 우수 저류조, 침사지, 월류 위어실, 끝의 배수 펌프장이 마디다.
//   node tools/places/sewer.js [--dry] [--print]
// 수로 w 는 6스터드 낮은 물길(PitTiles): 걸어서는 못 건너고 철제 다리 b 로만 반대편 보행로로 건넌다. 지선이 간선에 합류하는 곳은 보행로 아래로
// 물이 들어가는 철망 다리(b)다. 물 흐름(= 플레이어 길):
//   상류 낙차 맨홀실(시작, 북동쪽) → 북쪽 간선 / [지선 A → 원형 저류조 → 지선 B] → 북서 합류실 → 서쪽 간선 / [지선 D → 침사지 → 지선] →
//   남서 합류실 → 남쪽 간선 / [월류 지선 → 월류 위어실 → 펌프장 뒤 통로] → 남동 굽이 → 동쪽 간선 → 펌프장(스크린·집수정 / 펌프실) → 지상 계단(출구)
// 북동쪽 시작과 동쪽 펌프장 사이(맵 동쪽)는 흙 속이라 막혀 있다: 물길을 따라 한 바퀴 내려가야 한다(간선 끝이 이어지지 않은 반쪽 고리 + 안쪽 나뭇가지).
const fs = require("fs");
const os = require("os");
const path = require("path");
const { Grid, report, writeStage } = require("./lib");

const g = new Grid(47, 43);
// 간선(5칸 폭): 보행로 2칸 / 수로 1칸 / 보행로 2칸
const mainH = (x0, x1, y) => g.fill(x0, y, x1, y + 4).fill(x0, y + 2, x1, y + 2, "w");
const mainV = (x, y0, y1) => g.fill(x, y0, x + 4, y1).fill(x + 2, y0, x + 2, y1, "w");
// 지선(3칸 폭): 보행로 / 수로 / 보행로
const brH = (x0, x1, y) => g.fill(x0, y, x1, y + 2).fill(x0, y + 1, x1, y + 1, "w");
const brV = (x, y0, y1) => g.fill(x, y0, x + 2, y1).fill(x + 1, y0, x + 1, y1, "w");

// ══ 상류 낙차 맨홀실(시작, x40~45, y1~7): 지상 맨홀 사다리로 내려온 곳. 동쪽 벽 큰 유입관에서 오수가 떨어져(Q) 북쪽 간선 수로가 시작된다 ══
g.fill(40, 1, 45, 7).fill(40, 3, 44, 3, "w").set(45, 3, "Q");
g.put("S", [[44, 6], [45, 6], [44, 5], [45, 5]]).set(44, 3, "b"); // (수로 위 철제 다리: 북쪽 보행로로도 나간다)
g.set(41, 7, "l").set(45, 1, "L").set(40, 7, "c");

// ══ 북쪽 간선(x9~39, y1~5) ══ 북쪽 보행로 y1~2, 수로 y3, 남쪽 보행로 y4~5
mainH(9, 39, 1);
g.put("b", [[30, 3], [14, 3]]); // (건너는 다리)
g.put("Z", [[26, 6], [35, 6]]).put("P", [[24, 1], [24, 2]]); // (열쇠 상자는 벽을 판 오목한 자리에: 2칸 보행로를 좁히지 않는다) // (천장 밑 굵은 압송관이 간선을 가로지른다)
// 지선 G(x31~33, y6~8): 간선 남쪽 보행로 아래로 흘러드는 짧은 막다른 지선 — 끝에 지상 맨홀 사다리
brV(31, 6, 8).put("b", [[32, 4], [32, 5]]).set(33, 8, "l");

// ══ 북서 합류실(x1~8, y1~8): 북쪽 간선 수로가 남쪽으로 꺾여 서쪽 간선이 된다. 바깥 보행로(북·서)와 안쪽 보행로(남·동) ══
g.fill(1, 1, 8, 8).fill(3, 3, 8, 3, "w").fill(3, 3, 3, 8, "w");
g.put("b", [[6, 3], [3, 6]]).put("O", [[6, 6]]).set(1, 1, "Z").set(8, 8, "Z").set(8, 1, "L");
g.set(5, 5, "K"); // (안쪽 모서리: 꺾이는 수로 위를 지나는 배관 다리 — 랜드마크)

// ══ 서쪽 간선(x1~5, y9~32) ══ 서쪽 보행로 x1~2, 수로 x3, 동쪽 보행로 x4~5
mainV(1, 9, 32);
g.put("b", [[3, 13], [3, 23]]).put("Z", [[6, 12], [6, 24]]).set(6, 21, "L").set(4, 31, "G"); // (수문 승강기: 침사지로 물을 돌리던 수문)

// ══ 남서 합류실(x1~8, y33~41): 서쪽 간선이 동쪽으로 꺾여 남쪽 간선이 된다 ══
g.fill(1, 33, 8, 41).fill(3, 33, 3, 39, "w").fill(3, 39, 8, 39, "w");
g.put("b", [[3, 36], [6, 39]]).put("O", [[6, 35]]).set(1, 41, "Z").set(8, 33, "L").set(8, 41, "c");

// ══ 남쪽 간선(x9~37, y37~41) ══ 북쪽 보행로 y37~38, 수로 y39, 남쪽 보행로 y40~41
mainH(9, 37, 37);
g.put("b", [[18, 39], [33, 39]]).put("Z", [[11, 36], [31, 36]]).set(24, 36, "L").put("P", [[22, 40], [22, 41]]);
g.set(26, 39, "K"); // (남쪽 간선 위 배관 다리)

// ══ 남동 굽이(x38~45, y34~41): 남쪽 간선이 북쪽으로 꺾여 동쪽 간선이 된다(물은 펌프장 집수정으로 끌려 올라간다) ══
g.fill(38, 34, 45, 41).fill(38, 39, 43, 39, "w").fill(43, 34, 43, 39, "w");
g.put("b", [[40, 39], [43, 36]]).put("O", [[40, 36]]).set(45, 41, "Z").set(38, 34, "Z").set(45, 34, "L");

// ══ 동쪽 간선(x41~45, y24~33) ══ 서쪽 보행로 x41~42, 수로 x43, 동쪽 보행로 x44~45
mainV(41, 24, 33);
g.put("b", [[43, 28]]).set(40, 30, "Z").set(41, 26, "c");

// ══ 배수 펌프장(x32~45, y10~23): 스크린·집수정(x41~45) / 펌프실(x32~39) / 지상 계단실(출구, x41~45, y10~12) ══
// 집수정: 동쪽 간선 수로가 스크린(H)을 지나 막다른 집수정으로. 양쪽 보행로는 계단실 문 둘, 서쪽 보행로는 펌프실 문
g.fill(41, 14, 45, 23).fill(43, 14, 43, 23, "w").set(43, 20, "H").set(43, 16, "b");
g.set(41, 13, "D").set(45, 13, "D").set(40, 18, "D");
g.set(45, 22, "Z").set(41, 14, "L");
// 펌프실: 펌프 넷(M) 줄, 밸브(V), 계기반(Y), 머리 위 압송관(P). 서쪽 월류 통로 문, 계단실 문
g.fill(32, 10, 39, 23).set(40, 11, "D").set(31, 22, "D");
g.put("M", [[34, 15], [37, 15], [34, 19], [37, 19]]).put("V", [[33, 12], [38, 12]]).put("Y", [[32, 10], [35, 10]]);
g.put("P", [[34, 17], [35, 17], [36, 17], [37, 17]]).set(39, 23, "Z").set(32, 23, "L").set(39, 10, "c");
// 지상 계단실(출구): 펌프실·집수정 양쪽 보행로에서 들어온다(서로 다른 세 문) — 북동쪽 끝 계단(E)
g.fill(41, 10, 45, 12).set(45, 9, "E").set(41, 10, "Y");
// 발전기실(펌프실 남쪽, 막다른 방): 비상 발전기(m)
g.fill(33, 25, 39, 29).set(36, 24, "D").put("m", [[34, 26], [38, 26]]).set(39, 29, "L").set(33, 29, "c");

// ══ 안쪽 나뭇가지 ══
// 지선 A(x19~21, y6~11): 북쪽 간선 → 원형 저류조 북쪽
brV(19, 6, 11).put("b", [[20, 4], [20, 5]]);
// 원형 우수 저류조(가운데 (20,17), 지름 11): 둘레 보행로 고리, 가운데 물웅덩이, 기둥 넷. 지선 A(북)·B(서)가 철망 다리 밑으로 흘러든다
const CX = 20, CY = 17;
for (let y = CY - 6; y <= CY + 6; y++)
	for (let x = CX - 6; x <= CX + 6; x++) {
		const d = (x - CX) ** 2 + (y - CY) ** 2;
		if (d <= 5.6 * 5.6) g.set(x, y, d <= 2.3 * 2.3 ? "w" : ".");
	}
g.put("b", [[20, 12], [20, 13], [15, 17], [16, 17]]).put("w", [[20, 14], [17, 17]]);
g.put("O", [[17, 14], [23, 14], [17, 20], [23, 20]]).set(20, 22, "Z").set(25, 17, "Z");
g.set(20, 19, "Q"); // (저류조 가운데로 천장 유입관에서 빗물이 떨어진다)
// 지선 B(x6~14, y16~18): 저류조 서쪽 → 서쪽 간선(동쪽 보행로 아래로)
brH(6, 14, 16).put("b", [[4, 17], [5, 17]]);
// 관리 사무실(x9~17, y7~10): 북쪽 간선 · 지선 A 로 문 둘(이 장의 하나뿐인 사무실 — 책상·서류함·계기반)
g.fill(9, 7, 17, 10).set(12, 6, "D").set(18, 9, "D");
g.put("T", [[11, 9], [14, 9]]).put("C", [[9, 10], [17, 7]]).set(15, 7, "Y").set(9, 7, "Z").set(17, 10, "L");
// 밸브실(x8~13, y20~23, 막다른 방): 지선 B 남쪽 보행로에서. 밸브 둘
g.fill(8, 20, 13, 23).set(11, 19, "D").put("V", [[9, 22], [12, 22]]).set(13, 23, "L").set(8, 23, "c");
// 지선 D(x6~8, y27~29) + 침사지(x9~16, y25~31): 서쪽 간선에서 갈라져 모래를 가라앉히는 넓은 물길(침사 홈 v·스크린 H) → 지선으로 남쪽 간선에
brH(6, 8, 27).put("b", [[4, 28], [5, 28]]);
g.fill(9, 25, 16, 31).fill(9, 28, 14, 28, "w").fill(14, 28, 14, 31, "w");
g.set(11, 28, "b").set(12, 28, "H").set(9, 25, "Z").set(16, 31, "Z").set(16, 25, "L").put("I", [[11, 31]]);
brV(13, 32, 36).put("b", [[14, 37], [14, 38]]);
// 맨홀 수직갱실(x18~23, y31~35, 막다른 방): 남쪽 간선에서. 둥근 수직갱(R)과 사다리
g.fill(18, 31, 23, 35).set(20, 36, "D").set(20, 33, "R").set(23, 31, "l").set(18, 31, "L").set(23, 35, "c");
// 월류 지선(x27~29, y30~36) → 월류 위어실(x24~30, y24~29) → 펌프장 뒤 통로(x27~30, y22~23) → 펌프실 서쪽 문
brV(27, 30, 36).put("b", [[28, 37], [28, 38]]);
g.fill(24, 24, 30, 29).fill(28, 26, 28, 29, "w").set(28, 25, "U");
g.fill(27, 22, 30, 23);
g.set(24, 24, "Z").set(30, 29, "L").set(24, 29, "Y").put("J", [[30, 26]]);

if (process.argv.includes("--print")) console.log(g.rows().map((row, i) => String(i).padStart(2) + " " + row).join(String.fromCharCode(10)));
const PITS = ["w", "H", "Q", "U", "K"];
const WALK = ["P", "l"];
const opts = { id: 3, pits: PITS, walkable: WALK, blocked: ["M", "V", "Y", "G", "J", "I", "T", "C", "R"] };
const r = report("하수도", g, opts);
if (!process.argv.includes("--dry")) {
	// 스테이지 파일은 한 번에 쓴다(Rojo 가 Studio 로 바로 옮긴다): 임시 폴더에 만든 뒤 Props 줄·옛 수로 함수까지 바꿔 한 번에 덮어쓴다
	const outDir = process.env.STAGE_OUT_DIR; // (다른 폴더에 써서 시험할 때)
	const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "stage3-"));
	process.env.STAGE_OUT_DIR = tmp;
	writeStage("Stage3.luau", g, [
		"STAGE 3 — 하수도 (47x43칸, tools/places/sewer.js 로 생성, 설계 문서 docs/levels/stage3.md)",
		"나뭇가지 모양 하수망: 굵은 간선 차집관로(보행로 2 / 수로 w / 보행로 2)가 북 → 서 → 남 → 동으로 맵 가장자리를 따라 흐르고, 안쪽 지선(3칸 폭)이 간선으로 흘러든다.",
		"수로는 6스터드 낮은 물길: 철제 다리(b)로만 반대편 보행로로 건넌다. 지선이 간선에 합류하는 곳은 보행로 아래로 물이 드는 철망 다리.",
		"상류 낙차 맨홀실(시작, 북동) → 북쪽 간선 / 지선 A → 원형 우수 저류조 → 지선 B → 북서 합류실 → 서쪽 간선 / 지선 D → 침사지 → 남서 합류실 →",
		"남쪽 간선 / 월류 지선 → 월류 위어실 → 펌프장 뒤 통로 → 남동 굽이 → 동쪽 간선 → 배수 펌프장(스크린·집수정 / 펌프실) → 지상 계단실(출구, 세 문).",
		"맵 동쪽(시작과 펌프장 사이)은 흙 속이라 막혀 있다. 막다른 곳: 지선 G 끝 맨홀, 밸브실, 맨홀 수직갱실, 발전기실(숨는 곳만, 열쇠 상자 없음).",
		`괴물 하나가 어디 서도 돌아가는 길이 있다(목 0, tools/level-graph.js). 출구까지 최단 약 ${r.exit}칸.`,
		"장비(ChapterProps/Sewer): 수로 w(물·아치 갈비)·낙차 유입관 Q·배관 다리 K·월류 위어 U·스크린 H·펌프 M·밸브 V·계기반 Y·수문 G·사다리 l·수직갱 R·압송관 P.",
	]);
	const real = outDir ? path.join(outDir, "Stage3.luau") : path.join(__dirname, "..", "..", "src", "server", "Stages", "Stage3.luau");
	let src = fs.readFileSync(path.join(tmp, "Stage3.luau"), "utf8");
	const nl = src.includes("\r\n") ? "\r\n" : "\n";
	// (예전 스테이지 파일 안의 수로 함수는 ChapterProps/Sewer.Channel 로 옮겼다: require 줄 다음부터 return 전까지 지운다)
	src = src.replace(/(local CP = require\([^\n]*\n)[\s\S]*?(\r?\nreturn \{)/, `$1$2`);
	src = src.replace(/\tProps = \{[^\n]*\n/, `\tProps = { w = CP.Channel, Q = CP.DropInlet, K = CP.PipeBridge, U = CP.Weir, H = CP.BarScreen, P = Props.BigPipe, l = CP.Ladder, M = CP.Pump, V = CP.ValveStand, Y = CP.GaugePanel, G = CP.SluiceGate, J = CP.Workbench, I = CP.PipeStack, R = CP.ManholeShaft, T = Props.Desk, C = Props.Cabinet },${nl}`);
	src = src.replace(/\tPitTiles = \{[^\n]*\n/, `\tPitTiles = { w = true, H = true, Q = true, U = true, K = true }, -- (물길 칸: 아래층 높이)${nl}`);
	src = src.replace(/\tWalkable = \{[^\n]*\n/, `\tWalkable = { P = true, l = true }, -- (머리 위 압송관·벽 사다리는 밑으로 지나간다. 수로는 괴물 배회 지점에서 뺀다: 보행로로만 다닌다)${nl}`);
	fs.writeFileSync(real, src);
	fs.rmSync(tmp, { recursive: true, force: true });
}
