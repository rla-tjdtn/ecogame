// 챕터 3 하수도: 벽돌 아치 터널(보행로 / 수로 w / 보행로)이 맵 바깥을 크게 돌고, 가운데 원형 저수조가 갈림목이 된다.
//   node tools/places/sewer.js [--dry]
// 수로 w 는 6스터드 낮은 물길(PitTiles): 걸어서는 못 건너고 철제 다리 b 로만 반대편 보행로로 건넌다.
// 큰 흐름: 정비 출입구(왼쪽 위) → 위 터널(T1) → 가운데(저수조) 또는 동쪽 터널(V2) → 아래 터널(T3) → 서쪽 터널(V1S) → 배수구 출구.
// 살짝 뒤틀린 곳: 위 터널 가운데가 무너져 펌프실로 돌아가고, 서쪽 터널은 중간이 무너져 막혔다(정비 작업장 → 샛길로 저수조),
// 아래 터널도 무너져 오수 펌프장으로 돌아가며, 서쪽 터널 끝은 수문이 닫혀 수문실을 거쳐야 배수구에 닿는다.
const { Grid, report, writeStage } = require("./lib");

const W = 47, H = 43;
const g = new Grid(W, H);

// 터널: 수로(wx0..wx1, 줄 y)와 양쪽 보행로
const tunH = (wx0, wx1, y) => g.fill(wx0 - 1, y - 1, wx1 + 1, y + 1).fill(wx0, y, wx1, y, "w");
const tunV = (x, wy0, wy1) => g.fill(x - 1, wy0 - 1, x + 1, wy1 + 1).fill(x, wy0, x, wy1, "w");

// ══ 큰 터널 ══
tunH(3, 43, 8); // T1 위 터널 (보행로 y7, y9)
tunV(43, 8, 34); // V2 동쪽 터널 (보행로 x42, x44)
tunH(3, 43, 34); // T3 아래 터널 (보행로 y33, y35)
// V1 서쪽 터널 위쪽: 중간이 무너져 막다른 길(무너진 흙더미)
g.fill(2, 7, 4, 14).fill(3, 8, 3, 13, "w");
g.put("c", [[2, 14], [3, 14], [4, 14], [2, 13]]);
// V1S 서쪽 터널 아래쪽(배수구 쪽): 위 끝 y21, 중간 y27~28 에 닫힌 수문
tunV(3, 22, 34);
g.wall(2, 27, 4, 28);
g.put("c", [[2, 26], [4, 29]]);
g.set(1, 22, "E"); // 배수구(출구): 서쪽 벽의 철창

g.fill(3, 8, 43, 8, "w").fill(3, 34, 43, 34, "w"); // (모퉁이 물길 다시 잇기)
// 가운데 수직 터널 Vm: 위 터널 → 저수조
g.fill(21, 10, 23, 15).fill(22, 9, 22, 18, "w");
// T2 동쪽 터널: 저수조 → 동쪽 터널
g.fill(27, 20, 42, 22).fill(25, 21, 42, 21, "w");

// ══ 원형 저수조(가장 큰 공간): 가운데 물웅덩이, 둘레 보행로, 기둥 ══
const CX = 22, CY = 21;
for (let y = CY - 6; y <= CY + 6; y++)
	for (let x = CX - 6; x <= CX + 6; x++) {
		const d = (x - CX) ** 2 + (y - CY) ** 2;
		if (d <= 5.6 * 5.6) g.set(x, y, d <= 2.3 * 2.3 ? "w" : ".");
	}
g.fill(22, 16, 22, 18, "w").fill(25, 21, 27, 21, "w"); // 들어오는 물길
g.put("O", [[19, 18], [25, 18], [19, 24], [25, 24], [18, 21], [22, 25]]);

// ══ 다리 ══
g.put("b", [
	[10, 8], [28, 8], [37, 8], // 위 터널
	[22, 9], // Vm 합류(남쪽 보행로 잇기)
	[3, 11], // 서쪽 위
	[43, 15], [43, 28], [42, 21], // 동쪽 터널, T2 합류
	[35, 21], // T2
	[8, 34], [16, 34], [33, 34], [40, 34], // 아래 터널
	[3, 31], // 서쪽 아래
	[22, 17], [26, 21], // 저수조 둘레
]);

// ══ 무너진 곳 ══
g.wall(18, 7, 19, 9).put("c", [[17, 7], [20, 9]]); // 위 터널
g.wall(24, 33, 25, 35).put("c", [[23, 33], [26, 35]]); // 아래 터널

// ══ 위 띠(y1~5) ══
// 정비 출입구(시작): 사다리 수직갱 밑 작은 방
g.fill(1, 1, 5, 5).set(3, 6, "A");
g.put("S", [[1, 1], [2, 1], [1, 2], [2, 2]]).set(5, 1, "Z").set(5, 5, "L").set(1, 5, "c");
// 공구 창고(막다른 방)
g.fill(7, 1, 11, 5).set(9, 6, "D");
g.put("c", [[7, 1], [8, 1], [11, 5]]).set(11, 1, "Z").set(7, 5, "L");
// 펌프실(문 2개: 무너진 위 터널을 돌아가는 길) — 펌프 기계 줄, 머리 위 대형 배관
g.fill(13, 1, 25, 5).set(14, 6, "D").set(24, 6, "D");
g.put("m", [[15, 2], [16, 2], [19, 2], [20, 2], [23, 2]]).put("P", [[17, 4], [18, 4], [19, 4], [20, 4], [21, 4]]);
g.set(25, 1, "Z").set(13, 1, "L").put("v", [[13, 5], [25, 5]]).set(18, 3, "f");
// 밸브실(막다른 방): 밸브 바퀴 기계
g.fill(27, 1, 33, 5).set(30, 6, "D");
g.put("m", [[27, 1], [29, 1], [31, 1]]).put("v", [[33, 1], [33, 2]]).set(33, 5, "Z").set(27, 5, "L");
// 관리 사무실(문 2개)
g.fill(35, 1, 44, 5).set(36, 6, "D").set(43, 6, "D");
g.put("c", [[35, 1], [44, 1], [44, 2]]).set(39, 1, "Z").set(40, 3, "f").set(41, 1, "L");

// ══ 서쪽 가운데 ══
// 정비 작업장(문 2개: 서쪽 터널 → 샛길 → 저수조)
g.fill(6, 11, 13, 17).set(5, 13, "D").set(14, 13, "D").set(9, 18, "D");
g.put("m", [[7, 11], [8, 11], [12, 11]]).put("v", [[6, 17], [13, 17]]).set(10, 14, "f").set(13, 15, "Z").set(6, 15, "L");
// 정비 샛길(1칸): 작업장 → 저수조 서쪽 아치
g.fill(15, 13, 15, 21).set(16, 21, "A");
g.fill(16, 13, 18, 13).set(18, 12, "c").set(18, 13, "Z"); // (샛길 끝 막다른 틈)
// 약품 창고(작업장 안쪽 막다른 방)
g.fill(6, 19, 12, 21).put("c", [[6, 21], [12, 19]]).set(12, 21, "Z").set(6, 19, "L");
// 수문실(문 2개: 닫힌 수문 너머 배수구로 가는 유일한 길)
g.fill(6, 23, 12, 31).set(5, 25, "D").set(5, 30, "D");
g.put("m", [[6, 27], [7, 27], [6, 28]]).put("v", [[12, 23], [12, 24]]).set(12, 31, "Z").set(9, 26, "f").set(12, 28, "L").set(8, 31, "c");

// ══ 동쪽 가운데 ══
// 배수 제어실(문 2개: 위 터널 ↔ T2)
g.fill(28, 11, 34, 18).set(31, 10, "D").set(31, 19, "D");
g.put("m", [[28, 11], [29, 11], [34, 11]]).put("v", [[28, 18], [34, 18]]).set(34, 14, "Z").set(28, 15, "L").set(31, 14, "f");
// 작은 공구실(막다른 방)
g.fill(36, 11, 40, 17).set(38, 10, "D");
g.put("c", [[36, 17], [40, 17], [40, 16]]).set(40, 11, "Z").set(36, 11, "L");
// 침전조(문 2개: T2 ↔ 동쪽 터널) — 가운데 얕은 침전 물길과 기둥
g.fill(29, 24, 40, 31).set(31, 23, "D").set(41, 29, "D");
g.fill(31, 26, 38, 27, "w").put("O", [[30, 29], [34, 29], [38, 29]]);
g.set(40, 24, "Z").set(29, 31, "L").set(40, 31, "c");
// 침사지(저수조 남쪽 막다른 방)
g.fill(17, 28, 27, 31).set(22, 27, "D");
g.put("c", [[17, 31], [18, 31], [27, 28]]).put("v", [[17, 28], [27, 31]]).set(27, 30, "Z").set(17, 29, "L");

// ══ 아래 띠(y37~41) ══
// 공구 창고(막다른 방)
g.fill(6, 37, 12, 41).set(9, 36, "D");
g.put("c", [[6, 41], [7, 41], [12, 37]]).set(12, 41, "Z").set(6, 37, "L");
// 오수 펌프장(문 2개: 무너진 아래 터널을 돌아가는 길)
g.fill(19, 37, 30, 41).set(21, 36, "D").set(28, 36, "D");
g.put("m", [[19, 41], [20, 41], [24, 39], [25, 39], [30, 41]]).put("P", [[22, 38], [23, 38], [26, 38], [27, 38]]);
g.set(30, 37, "Z").set(19, 37, "L");
// 저장고(막다른 방)
g.fill(32, 37, 37, 41).set(34, 36, "D");
g.put("c", [[32, 41], [37, 41], [37, 40]]).set(32, 37, "Z").set(37, 37, "L");
// 배수 점검실(막다른 방)
g.fill(39, 37, 44, 41).set(41, 36, "D");
g.put("m", [[44, 41], [43, 41]]).set(44, 37, "Z").set(39, 41, "L");

// ══ 터널 벽 틈(숨는 곳·뒤지는 곳) ══
g.set(45, 16, "L").set(45, 30, "Z").set(1, 10, "L").set(1, 33, "Z").set(16, 32, "L");

if (process.argv.includes("--print")) console.log(g.rows().map((row, i) => String(i).padStart(2) + " " + row).join(String.fromCharCode(10)));
const opts = { pits: ["w"], walkable: ["P"] };
const r = report("하수도", g, opts);
if (!process.argv.includes("--dry"))
	writeStage("Stage3.luau", g, [
		"STAGE 3 — 하수도 (47x43칸, tools/places/sewer.js 로 생성)",
		"벽돌 아치 터널(보행로 / 수로 w / 보행로, 갈비 아치)이 맵 바깥을 크게 돌고, 가운데 원형 저수조(물웅덩이·기둥)가 갈림목이다.",
		"수로는 6스터드 낮은 물길: 철제 다리(b)로만 반대편 보행로로 건넌다.",
		"위 띠: 정비 출입구(시작)·공구 창고·펌프실(문 2개)·밸브실·관리 사무실(문 2개). 가운데: 정비 작업장 → 1칸 정비 샛길 → 저수조,",
		"배수 제어실(위 터널 ↔ 동쪽 터널)·침전조(문 2개)·침사지. 아래 띠: 공구 창고·오수 펌프장(문 2개)·저장고·배수 점검실.",
		"살짝 뒤틀린 곳: 위 터널과 아래 터널 가운데가 무너져 펌프실·오수 펌프장으로 돌아가고, 서쪽 터널은 중간이 무너져 막혔다.",
		"저수조로는 세 갈래(작업장 샛길, 가운데 터널, 배수 제어실), 동쪽은 터널 또는 침전조로 갈린다. 서쪽 터널 끝은 수문이 닫혀",
		`수문실을 지나야 배수구(출구)에 닿는다. 출구까지 최단 약 ${r.exit}칸.`,
	]);
