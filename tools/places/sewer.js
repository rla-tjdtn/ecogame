// 챕터 3 하수도: 벽돌 아치 터널(보행로 / 수로 w / 보행로) 세 줄이 S자로 이어지고, 가운데 띠 한복판에 원형 저수조(둘레 보행로 고리)가 있다.
//   node tools/places/sewer.js [--dry] [--print]
// 수로 w 는 6스터드 낮은 물길(PitTiles): 걸어서는 못 건너고 철제 다리 b 로만 반대편 보행로로 건넌다.
// 큰 흐름(띠마다 두세 갈래):
//   위 띠: 정비 출입구(시작, 북서쪽) → 위 터널 T1 / 방 줄(공구 창고·펌프실·밸브실·관리 사무실) 로 동쪽
//   동쪽 꺾임: 동쪽 터널 V2 / 배수 제어실
//   가운데 띠: 동쪽 가지 터널 T2E·제어실 줄·침전조 줄 → 저수조 고리(북·남 반원) → 서쪽 가지 터널 T2W·작업장·침사지 → 수문실로 서쪽
//   서쪽 꺾임: 서쪽 터널 V1 / 수문실 아래 문
//   아래 띠: 아래 터널 T3 / 방 줄(공구 창고·자재실·오수 펌프장·저장고·배수 점검실) 로 동쪽 → 동쪽 끝 배수구(출구)
const { Grid, report, writeStage } = require("./lib");

const W = 47, H = 43;
const g = new Grid(W, H);

// 터널: 수로(wx0..wx1, 줄 y)와 양쪽 보행로
const tunH = (wx0, wx1, y) => g.fill(wx0 - 1, y - 1, wx1 + 1, y + 1).fill(wx0, y, wx1, y, "w");
const tunV = (x, wy0, wy1) => g.fill(x - 1, wy0 - 1, x + 1, wy1 + 1).fill(x, wy0, x, wy1, "w");

// ══ 위 띠 ══
tunH(3, 43, 8); // T1 위 터널 (보행로 y7, y9)
g.wall(18, 7, 19, 9).put("c", [[17, 7], [20, 9]]); // 가운데가 무너짐(펌프실로 돌아간다)
// 서쪽 위 터널(V1 윗부분): 무너진 흙더미로 막힌 막다른 곳
g.fill(2, 10, 4, 13).fill(3, 9, 3, 12, "w");
g.put("c", [[2, 13], [3, 13], [4, 13]]);
// 정비 출입구(시작): 사다리 수직갱 밑 작은 방, 터널로 아치 + 공구 창고로 문
g.fill(1, 1, 5, 5).set(3, 6, "A").set(6, 3, "D");
g.put("S", [[1, 1], [2, 1], [1, 2], [2, 2]]).set(5, 1, "Z").set(5, 5, "L").set(1, 5, "c");
// 공구 창고
g.fill(7, 1, 11, 5).set(9, 6, "D").set(12, 3, "D");
g.put("c", [[7, 1], [8, 1], [11, 5]]).set(11, 1, "Z").set(7, 5, "L");
// 펌프실 — 펌프 기계 줄, 머리 위 대형 배관
g.fill(13, 1, 25, 5).set(16, 6, "D").set(24, 6, "D").set(26, 3, "D");
g.put("m", [[15, 2], [16, 2], [19, 2], [20, 2], [23, 2]]).put("P", [[17, 4], [18, 4], [19, 4], [20, 4], [21, 4]]);
g.set(25, 1, "Z").set(13, 1, "L").put("v", [[13, 5], [25, 5]]).set(18, 3, "f");
// 밸브실: 밸브 바퀴 기계
g.fill(27, 1, 33, 5).set(30, 6, "D").set(34, 3, "D");
g.put("m", [[27, 1], [29, 1], [31, 1]]).put("v", [[33, 1]]).set(33, 5, "Z").set(27, 5, "L");
// 관리 사무실(문 2개)
g.fill(35, 1, 44, 5).set(36, 6, "D").set(43, 6, "D");
g.put("c", [[35, 1], [44, 1], [44, 2]]).set(39, 1, "Z").set(40, 3, "f").set(41, 1, "L");

// ══ 동쪽 꺾임 ══
tunV(43, 8, 21); // V2 동쪽 터널 (보행로 x42, x44)
// 배수 제어실: 위 터널 남쪽 보행로 ↔ 가운데 띠 (안쪽 꺾임)
g.fill(36, 11, 40, 18).set(38, 10, "D").set(38, 19, "D").set(35, 15, "D");
g.put("m", [[36, 11], [40, 11]]).put("v", [[36, 18], [40, 18]]).set(40, 14, "Z").set(36, 13, "L").set(38, 14, "f");
g.set(45, 16, "L"); // (터널 벽 틈)

// ══ 가운데 띠 ══
// T2E 동쪽 가지 터널 (보행로 y20, y22) — 저수조로 흘러든다
g.fill(28, 20, 42, 22).fill(25, 21, 43, 21, "w");
// T2W 서쪽 가지 터널 (보행로 y20, y22) — 저수조에서 서쪽 터널로
g.fill(2, 20, 16, 22).fill(3, 21, 19, 21, "w");
// 원형 저수조(가장 큰 공간): 가운데 물웅덩이, 둘레 보행로 고리, 기둥
const CX = 22, CY = 21;
for (let y = CY - 6; y <= CY + 6; y++)
	for (let x = CX - 6; x <= CX + 6; x++) {
		const d = (x - CX) ** 2 + (y - CY) ** 2;
		if (d <= 5.6 * 5.6) g.set(x, y, d <= 2.3 * 2.3 ? "w" : ".");
	}
g.fill(17, 21, 19, 21, "w").fill(25, 21, 27, 21, "w"); // 들어오고 나가는 물길
g.put("O", [[19, 18], [25, 18], [19, 24], [25, 24]]);
// 펌프 제어실(제어실 줄): 배수 제어실 ↔ 저수조 북동 아치, 동쪽 가지 터널로도 문
g.fill(29, 12, 34, 18).set(31, 19, "D").fill(26, 17, 27, 17).set(28, 17, "D");
g.put("m", [[29, 12], [30, 12], [34, 12]]).put("v", [[34, 18]]).set(34, 13, "Z").set(29, 16, "L").set(32, 15, "f");
// 정비 작업장(서쪽 줄): 저수조 북서 아치 ↔ 서쪽 가지 터널
g.fill(6, 12, 13, 18).set(9, 19, "D").set(14, 17, "D").fill(15, 17, 18, 17);
g.put("m", [[6, 12], [7, 12], [12, 12]]).put("v", [[13, 12]]).set(10, 15, "f").set(13, 14, "Z").set(6, 15, "L");
g.set(15, 16, "c").fill(15, 13, 15, 16).set(15, 13, "Z"); // (작업장 옆 좁은 틈: 막다른 곳)
// 침전조(침전조 줄): 동쪽 가지 터널 남쪽 보행로 ↔ 저수조 남동 아치, 가운데 얕은 침전 물길과 기둥
g.fill(30, 24, 40, 30).set(32, 23, "D").set(39, 23, "D").fill(26, 25, 28, 25).set(29, 25, "D");
g.fill(32, 27, 38, 27, "w").put("O", [[31, 29], [35, 29], [39, 29]]);
g.set(40, 25, "Z").set(30, 30, "L").set(40, 30, "c");
// 침사지: 저수조 남쪽 아치 ↔ 수문실
g.fill(15, 28, 27, 30).set(22, 27, "D").set(14, 29, "D");
g.put("c", [[27, 28], [15, 28]]).put("v", [[17, 30], [27, 30]]).set(26, 28, "Z").set(19, 30, "L");
// 수문실: 서쪽 가지 터널·서쪽 터널·침사지·아래 터널로 문
g.fill(6, 24, 13, 31).set(9, 23, "D").set(5, 27, "D").set(9, 32, "D");
g.put("m", [[6, 24], [7, 24], [6, 25]]).put("v", [[13, 24], [13, 25]]).set(13, 31, "Z").set(10, 27, "f").set(13, 28, "L").set(6, 31, "c");

// ══ 서쪽 꺾임 ══
tunV(3, 21, 33); // V1 서쪽 터널 (보행로 x2, x4)
g.set(1, 26, "L");

// ══ 아래 띠 ══
tunH(3, 43, 34); // T3 아래 터널 (보행로 y33, y35)
g.wall(24, 33, 25, 35).put("c", [[23, 33], [26, 35]]); // 가운데가 무너짐(오수 펌프장·방 줄로 돌아간다)
g.set(45, 34, "E"); // 배수구(출구): 아래 터널 동쪽 끝 철창
// 방 줄(y37~41): 이웃 방끼리 문, 터널로 문
g.fill(6, 37, 11, 41).set(9, 36, "D").set(12, 39, "D"); // 공구 창고
g.put("c", [[6, 41], [7, 41], [11, 37]]).set(11, 41, "Z").set(6, 37, "L");
g.fill(13, 37, 17, 41).set(15, 36, "D").set(18, 39, "D"); // 배관 자재실
g.put("P", [[14, 40], [15, 40], [16, 40]]).set(17, 41, "Z").set(13, 37, "L");
g.fill(19, 37, 30, 41).set(21, 36, "D").set(28, 36, "D").set(31, 39, "D"); // 오수 펌프장
g.put("m", [[19, 41], [20, 41], [24, 39], [25, 39], [30, 41]]).put("P", [[22, 38], [23, 38], [26, 38], [27, 38]]);
g.set(30, 37, "Z").set(19, 37, "L");
g.fill(32, 37, 37, 41).set(34, 36, "D").set(38, 39, "D"); // 저장고
g.put("c", [[32, 41], [37, 41]]).set(32, 37, "Z").set(37, 37, "L");
g.fill(39, 37, 44, 41).set(41, 36, "D"); // 배수 점검실
g.put("m", [[44, 41], [43, 41]]).set(44, 37, "Z").set(39, 41, "L");

// ══ 다리 ══
g.put("b", [
	[10, 8], [28, 8], [37, 8], // 위 터널
	[43, 15], [42, 21], // 동쪽 터널, T2E 합류
	[35, 21], // T2E
	[10, 21], [18, 21], [26, 21], // T2W, 저수조 고리
	[3, 27], // 서쪽 터널
	[8, 34], [16, 34], [33, 34], [40, 34], // 아래 터널
]);
g.set(1, 33, "Z").set(16, 32, "L");

if (process.argv.includes("--print")) console.log(g.rows().map((row, i) => String(i).padStart(2) + " " + row).join(String.fromCharCode(10)));
const opts = { pits: ["w"], walkable: ["P"] };
const r = report("하수도", g, opts);
if (!process.argv.includes("--dry"))
	writeStage("Stage3.luau", g, [
		"STAGE 3 — 하수도 (47x43칸, tools/places/sewer.js 로 생성)",
		"벽돌 아치 터널(보행로 / 수로 w / 보행로, 갈비 아치) 세 줄이 S자로 이어지고, 가운데 띠 한복판에 원형 저수조(물웅덩이·기둥, 둘레 보행로 고리)가 있다.",
		"수로는 6스터드 낮은 물길: 철제 다리(b)로만 반대편 보행로로 건넌다. 띠마다 터널과 나란한 방 줄이 있어 두세 갈래로 갈린다.",
		"위 띠: 정비 출입구(시작)에서 위 터널(가운데 무너짐) 또는 공구 창고·펌프실·밸브실·관리 사무실 방 줄로 동쪽. 동쪽 터널 또는 배수 제어실로 꺾어",
		"가운데 띠: 동쪽 가지 터널 / 펌프 제어실 / 침전조 세 갈래가 저수조 고리(북·남 반원)로 모이고, 서쪽 가지 터널 / 정비 작업장 / 침사지로 갈려 수문실 쪽 서쪽으로.",
		"서쪽 터널 또는 수문실 아래 문으로 꺾어 아래 띠: 아래 터널(가운데 무너짐) 또는 공구 창고·자재실·오수 펌프장·저장고·배수 점검실 방 줄로 동쪽,",
		`아래 터널 동쪽 끝 배수구(출구). 어느 칸을 막아도 돌아가는 길이 있다(목 0). 출구까지 최단 약 ${r.exit}칸.`,
	]);
