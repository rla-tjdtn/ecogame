// 챕터 7 학교: 본관(1층·2층)과 별관(1층·2층)이 동쪽 끝에서 이어진 ㄷ자 학교. 실제 학교 구조 위에 막힌 복도·샛문을 살짝 섞었다.
//   node tools/places/school.js [--dry]
// 띠 배치(위→아래): 본관 1층(y1~9) | 계단 3곳 | 본관 2층(y12~20) | 벽 | 별관 2층(y22~30) | 계단 3곳 | 별관 1층(y33~41)
// 두 동은 동쪽에서만 만난다: 1층 동쪽 연결 복도(x44~45)와 2층 동쪽 연결 복도(x41~42). 별관 1층 당직실(남서쪽 시작)에서
// 동쪽으로 갔다가 본관 서쪽 현관(북서쪽 출구)으로 돌아온다. 길은 세 갈래가 나란히 달린다:
//   1층 복도 · 1층 샛문으로 이어진 방 줄(급식실·체육관 / 교무실·보건실) · 2층(별관 2층 → 2층 연결 복도 → 본관 2층),
// 그리고 각 동의 서쪽·가운데·동쪽 계단 3곳으로 1층과 2층을 언제든 갈아탄다.
const { Grid, report, writeStage } = require("./lib");

const g = new Grid(47, 43);
g.markUpper(1, 12, 42, 30);

// ══ 본관 1층 (A): 방 y1~6, 벽 y7, 복도 y8~9 ══
g.fill(1, 8, 45, 9);
// 서쪽 현관 로비(출구): 복도 쪽이 넓게 트였고 북쪽 벽에 현관문, 동쪽 행정실로 샛문
g.fill(1, 2, 6, 6).fill(4, 7, 6, 7).set(1, 1, "E").set(7, 5, "D");
g.put("L", [[6, 2], [3, 2]]).put("k", [[1, 6], [6, 6]]).set(3, 4, "O");
// 행정실
g.fill(8, 1, 12, 6).set(10, 7, "D").set(13, 2, "D");
g.put("T", [[9, 2], [11, 2]]).set(12, 1, "Z").set(8, 6, "k");
// 교무실(문 2개, 양옆 샛문)
g.fill(14, 1, 21, 6).set(15, 7, "D").set(20, 7, "D").set(22, 5, "D");
g.put("T", [[16, 2], [18, 2], [20, 2], [16, 6], [17, 6], [18, 6], [19, 6]]).set(14, 1, "Z").set(21, 1, "L").set(17, 4, "k");
// 교장실
g.fill(23, 1, 27, 6).set(25, 7, "D").set(28, 2, "D");
g.put("T", [[25, 2]]).set(27, 1, "Z").set(23, 6, "k");
// 보건실
g.fill(29, 1, 33, 6).set(29, 7, "D").set(33, 7, "D").set(34, 5, "D");
g.put("R", [[30, 6], [31, 6], [32, 6], [31, 2]]).set(33, 1, "Z").set(29, 1, "L");
g.wall(31, 8, 31, 9).set(30, 9, "c"); // (보건실 앞 복도: 쓰러진 침대 — 보건실을 가로지른다)
// 방송실
g.fill(35, 1, 38, 6).set(36, 7, "D").set(39, 2, "D");
g.put("m", [[35, 1], [36, 1]]).set(38, 1, "Z").set(38, 6, "c");
// 교직원 화장실
g.fill(40, 1, 45, 6).set(42, 7, "D");
g.put("L", [[41, 1], [43, 1], [45, 1]]).set(45, 6, "c");
// 복도에 쌓인 책상(교무실을 가로지르거나 비켜 간다)
g.wall(18, 8, 18, 9).put("c", [[17, 9], [19, 8]]);
g.set(27, 9, "L").set(41, 9, "c");

// ══ 계단: 본관 1층 ↔ 본관 2층 (서쪽·가운데·동쪽 계단실) ══
g.stairs(9, 10, 0, 1).stairs(24, 10, 0, 1).stairs(39, 10, 0, 1);

// ══ 본관 2층 (B, 2층): 복도 y12~13, 벽 y14, 교실 y15~20 ══
g.fill(1, 12, 42, 13);
const classroom = (x0, x1, y0, y1, doorY, front, back) => {
	g.fill(x0, y0, x1, y1).set(front, doorY, "D").set(back, doorY, "D");
	const inward = y0 > doorY ? 1 : -1;
	const far = inward > 0 ? y1 : y0; // 창가 줄
	for (let x = x0 + 1; x <= x1 - 1; x += 2) { g.set(x, far - inward * 1, "T"); g.set(x, far - inward * 3, "T"); }
	g.set(x0, far, "Z"); // 교탁 서랍
	g.set(x1, far, "L"); // 청소함
};
classroom(1, 6, 15, 20, 14, 2, 5); // 2-1
classroom(8, 13, 15, 20, 14, 9, 12); // 2-2
classroom(15, 20, 15, 20, 14, 16, 19); // 2-3
g.fill(22, 15, 26, 20).set(24, 14, "D").put("c", [[22, 20], [26, 20], [26, 19]]).set(22, 15, "Z"); // 교구 준비실(막다른 방)
classroom(28, 33, 15, 20, 14, 29, 32); // 2-4
g.fill(35, 15, 39, 20).set(37, 14, "D").put("L", [[35, 20], [37, 20], [39, 20]]).set(39, 15, "c"); // 화장실
// 2층 복도 막힌 곳: 2-2 앞(쓰러진 사물함 — 교실 앞문으로 들어가 뒷문으로 나온다)
g.wall(11, 12, 11, 13).set(10, 13, "c");
g.wall(30, 12, 30, 13).set(31, 12, "c"); // (2-4 앞)

// ══ 2층 동쪽 연결 복도 (x41~42, y14~28): 본관 2층 ↔ 별관 2층 ══
g.fill(41, 14, 42, 28);
g.set(42, 21, "L"); // (연결 복도 벽장)

// ══ 별관 2층 (C, 2층): 방 y22~27, 벽 y28, 복도 y29~30 ══
g.fill(1, 29, 42, 30);
// 과학실 ─ 준비실 ─ 음악실 이 샛문으로 이어진다
g.fill(1, 22, 7, 27).set(3, 28, "D").set(6, 28, "D").set(8, 24, "D");
g.put("T", [[3, 24], [5, 24], [3, 26], [5, 26]]).put("m", [[1, 22], [2, 22]]).set(7, 22, "k").set(1, 27, "Z");
g.fill(9, 22, 11, 27).set(10, 28, "D").set(12, 24, "D");
g.put("k", [[9, 22], [11, 22]]).set(9, 27, "c").set(11, 27, "Z");
g.fill(13, 22, 18, 27).set(14, 28, "D").set(17, 28, "D");
g.put("T", [[15, 27], [16, 27], [15, 23], [16, 23]]).set(18, 22, "L").set(13, 22, "k");
g.wall(16, 29, 16, 30).set(15, 30, "c"); // (음악실 앞 복도 막힘 — 음악실을 가로지른다)
// 화장실
g.fill(20, 22, 22, 27).set(21, 28, "D").put("L", [[20, 22], [22, 22]]);
// 도서관(서가 줄, 문 2개)
g.fill(24, 22, 32, 27).set(25, 28, "D").set(31, 28, "D");
for (const x of [26, 28, 30]) g.put("k", [[x, 23], [x, 24], [x, 26]]);
g.set(32, 22, "Z").set(24, 22, "L");
// 컴퓨터실
g.fill(34, 22, 39, 27).set(35, 28, "D").set(38, 28, "D");
g.put("T", [[35, 24], [37, 24], [35, 26], [37, 26]]).set(39, 22, "Z").set(34, 22, "L");
// 2층 복도 막힌 곳: 도서관 앞(도서관을 가로지른다)
g.wall(28, 29, 28, 30).set(27, 30, "c");

// ══ 계단: 별관 2층 ↔ 별관 1층 (서쪽·가운데·동쪽 계단실) ══
g.stairs(8, 32, 0, -1).stairs(23, 32, 0, -1).stairs(37, 32, 0, -1);

// ══ 별관 1층 (D): 복도 y33~34, 벽 y35, 방 y36~41 ══
g.fill(1, 33, 45, 34);
// 당직실(시작)
g.fill(1, 36, 5, 41).set(3, 35, "D").set(6, 37, "D");
g.put("S", [[1, 40], [2, 40], [1, 41], [2, 41]]).set(5, 41, "R").set(5, 36, "Z").set(1, 36, "L").set(3, 38, "T");
// 창고
g.fill(7, 36, 10, 41).set(8, 35, "D").set(11, 40, "D").put("c", [[7, 41], [10, 41], [10, 36]]).set(7, 36, "Z");
// 급식실(식탁 줄) ─ 조리실 샛문
g.fill(12, 36, 21, 41).set(13, 35, "D").set(20, 35, "D").set(22, 37, "D");
for (const x of [14, 16, 18]) g.put("T", [[x, 40]]);
for (let x = 14; x <= 19; x++) g.set(x, 36, "m"); // 배식대
g.set(21, 41, "Z").set(12, 41, "L");
g.fill(23, 36, 27, 41).set(25, 35, "D").set(28, 40, "D");
g.put("m", [[23, 41], [24, 41], [27, 41]]).put("k", [[27, 36]]).set(23, 36, "Z").set(25, 39, "T");
// 체육관(가장 큰 공간: 기둥 줄, 문 2개) ─ 체육 창고
g.fill(29, 36, 40, 41).set(30, 35, "D").set(39, 35, "D").set(41, 37, "D");
for (const [x, y] of [[32, 39], [35, 40], [38, 39]]) g.set(x, y, "O");
for (let x = 31; x <= 38; x++) g.set(x, 36, "m"); // 접이식 관람석
g.wall(34, 33, 34, 34).set(33, 33, "c"); // (체육관 앞 복도 막힘)
g.set(40, 41, "Z").put("c", [[29, 41], [30, 41]]);
g.fill(42, 36, 45, 41).set(44, 35, "D").put("c", [[45, 41], [44, 41]]).set(42, 41, "L").set(45, 36, "Z");
// 급식실 앞 복도: 무너진 천장(급식실로 돌아간다)
g.wall(17, 33, 17, 34).set(16, 34, "c");

// ══ 1층 동쪽 연결 복도 (x44~45, y10~32): 본관 1층 ↔ 별관 1층 ══
g.fill(44, 10, 45, 32);
g.put("c", [[44, 20], [45, 24]]).set(45, 15, "Z").set(44, 28, "L");

const opts = { blocked: ["R"] };
const r = report("학교", g, opts);
if (process.argv.includes("--print")) console.log(g.rows().join("\n"));
if (!process.argv.includes("--dry"))
	writeStage("Stage7.luau", g, [
		"STAGE 7 — 학교 (47x43칸, tools/places/school.js 로 생성)",
		"실제 학교 구조: 본관과 별관이 각각 1층·2층(2층 = UpperRects, 계단 1·2 로 오르내림)이고, 두 동은 동쪽 끝에서만 이어진다(ㄷ자).",
		"본관 1층: 서쪽 현관 로비(출구)─행정실─교무실─교장실─보건실─방송실이 샛문으로 줄줄이 이어지고, 앞에 긴 복도·교직원 화장실.",
		"본관 2층: 교실 줄(앞문·뒷문)·교구 준비실·화장실. 별관 2층: 과학실─준비실─음악실(샛문)·화장실·도서관 서가(문 2개)·컴퓨터실.",
		"별관 1층: 당직실(남서쪽 시작)─창고─급식실─조리실─체육관(기둥)─체육 창고가 샛문으로 이어지고, 앞에 긴 복도.",
		"동쪽 끝: 1층 연결 복도(x44~45)와 2층 연결 복도(x41~42). 각 동마다 서쪽·가운데·동쪽 계단실 3곳(1층 ↔ 2층).",
		"길은 세 갈래가 나란히: 1층 복도 / 샛문 방 줄 / 2층(별관 2층 → 2층 연결 복도 → 본관 2층), 계단·문마다 갈아탈 수 있다.",
		`쓰러진 책상·무너진 천장으로 막힌 복도 칸은 옆 교실·도서관·급식실로 비켜 간다. 출구까지 최단 약 ${r.exit}칸.`,
	]);
