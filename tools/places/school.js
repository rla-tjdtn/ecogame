// 챕터 7 학교: 한국 중학교 본관. 1층·2층이 같은 크기로 겹쳐 쌓인 진짜 2층 건물(Rows2)이고, 계단은 교실 동 양 끝 네 곳.
//   node tools/places/school.js [--dry] [--print]
// 큰 흐름(ㄷ자 한 바퀴): 남서쪽 당직실(시작) → 남쪽 교실 복도(1층·2층) / 체육관 → 급식실 → 조리실 → 동쪽 홈베이스(1층·2층) →
//   북쪽 본관 복도(교무실·행정실 줄) → 북서쪽 중앙 현관(신발장, 출구).
// 북쪽 동과 남쪽 동은 동쪽 끝 홈베이스(네 칸 폭 사물함 홀, 1층과 2층)에서만 만난다. 가운데는 서쪽에 체육관(2층 없음, 높은 천장),
// 동쪽에 북쪽 동 교실·도서관과 남쪽 동 급식실·조리실이 등을 맞댄다(사이 벽).
// 복도는 세 칸 폭, 홈베이스는 네 칸 폭: 괴물(3x3) 하나가 복도를 걸어가도 대개 벽 쪽으로 비켜 갈 수 있다.
// 같은 동 안에서는 1층 복도 · 앞문·뒷문이 있는 교실 · 2층 복도(양 끝 계단) 세 갈래로 괴물을 비켜 간다.
// 방 문: D = 문, "." = 문짝이 떨어져 나간 뒷문(뚫린 문틀). 교실은 늘 앞문·뒷문 두 개.
// 소품 글자(Stage7 Props 줄 → src/server/ChapterProps/School.luau):
//   T 학생 책상+의자, G 칠판+교탁(교실 앞 벽), N 게시판(복도·교실 뒤 벽, 지나감), k 캐비닛·사물함(벽, 지나감), L 청소함(숨는 곳)
//   W 신발장, U 화장실 칸(변기), I 세면대, J 실험대(개수대), Y 피아노, e 이젤, M 방송 콘솔, F 급식 식탁(긴 의자), V 배식대,
//   H 서가, g 농구대(벽), u 체육관 단상, R 보건실 침대, m 보일러·조리 설비, c 쓰러진 책상 더미(복도 막힘)
