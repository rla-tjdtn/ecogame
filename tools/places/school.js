// 교실: (x0..x1, y0..y1), 복도 쪽 벽 doorY 에 앞문(front)·뒷문(back). 칠판은 서쪽 앞 벽, 사물함·게시판은 동쪽 뒤 벽.
// 책상은 두 칸 간격 두 줄(교실마다 4~6개: 음파 선 잡음을 줄인다)
function classroom(on, x0, y0, x1, y1, doorY, front, back, { z = true, back: bk = "D", lock = true, desks = true } = {}) {
	on.fill(x0, y0, x1, y1).set(front, doorY, "D").set(back, doorY, bk);
	const inward = doorY < y0 ? 1 : -1;
	const near = inward > 0 ? y0 : y1; // 복도 쪽 줄(통로)
	const far = inward > 0 ? y1 : y0; // 창가 줄
	const midY = Math.round((y0 + y1) / 2);
	on.set(x0, midY, "G"); // 칠판 + 교탁(앞 벽)
	if (desks) for (let x = x0 + 2; x <= x1 - 2; x += 2) for (const d of [2, 4]) if (d <= y1 - y0 - 1) on.set(x, near + inward * d, "T");
	if (z) on.set(x0, far, "Z"); // 교탁 옆 교사용 서랍장(창가 앞 구석)
	if (lock) on.set(x1, far, "L"); // 뒤 벽 청소함
	on.set(x1, near + inward * 1, "N"); // 뒤 게시판
	on.set(x1, midY + inward, "k"); // 학생 사물함
}
// 화장실: 칸막이 줄(U)을 한쪽 벽에, 세면대(I)를 맞은편 벽에
function toilet(on, x0, y0, x1, y1, doorX, doorY, stallsX, sinkX) {
	on.fill(x0, y0, x1, y1).set(doorX, doorY, "D");
	for (let y = y0; y <= y1; y += 2) on.set(stallsX, y, "U");
	on.put("I", [[sinkX, y0], [sinkX, y0 + 2]]);
}
