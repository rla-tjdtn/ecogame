// 챕터 7 학교: 본관(1층·2층)과 별관(1층·2층), 계단실, 연결 복도. 실제 학교 구조 위에 막힌 복도·무너진 계단·샛문을 살짝 섞었다.
//   node tools/places/school.js [--dry]
// 띠 배치(위→아래): 본관 1층(y1~9) | 계단 | 본관 2층(y12~20) | 별관 2층(y22~30) | 계단 | 별관 1층(y33~41)
// 2층 두 동은 서쪽 2층 연결 복도로 이어지고, 1층 두 동은 동쪽 1층 연결 복도로 이어졌지만 그 가운데가 무너졌다.
const { Grid, report, writeStage } = require("./lib");

const g = new Grid(47, 43);
g.markUpper(1, 12, 42, 30);

// ══ 본관 1층 (A): 방 y1~6, 벽 y7, 복도 y8~9 ══
g.fill(1, 8, 45, 9);
// 행정실
g.fill(1, 1, 5, 6).set(3, 7, "D");
g.put("T", [[2, 3], [4, 3]]).set(1, 6, "Z").set(5, 1, "k");
// 교무실(문 2개, 행정실·교장실로 샛문)
g.fill(7, 1, 13, 6).set(8, 7, "D").set(12, 7, "D").set(6, 3, "D").set(14, 3, "D");
g.put("T", [[8, 3], [10, 3], [12, 3], [8, 5], [10, 5]]).set(13, 1, "Z").set(7, 1, "k").set(13, 6, "L");
// 교장실
g.fill(15, 1, 18, 6).set(16, 7, "D");
g.put("T", [[16, 2]]).set(18, 1, "Z").set(18, 6, "k");
// 중앙 현관 로비(출구): 복도 쪽이 넓게 트였고 북쪽 가운데가 현관문
g.fill(20, 2, 27, 6).fill(21, 7, 26, 7);
g.set(23, 1, "E");
g.put("O", [[21, 4], [26, 4]]).put("L", [[20, 2], [27, 2]]).set(20, 6, "k").set(27, 6, "k");
// 보건실
g.fill(29, 1, 33, 6).set(31, 7, "D");
g.put("R", [[29, 1], [31, 1]]).set(33, 1, "k").set(33, 4, "Z").set(29, 6, "L");
// 방송실
g.fill(35, 1, 38, 6).set(36, 7, "D");
g.put("m", [[35, 1], [36, 1]]).set(38, 1, "Z").set(38, 6, "c");
// 화장실(칸막이 = 숨는 곳)
g.fill(40, 1, 45, 6).set(41, 7, "D");
g.put("L", [[40, 1], [42, 1], [44, 1]]).set(45, 6, "c");
// 복도 사물함·막힌 곳: 교무실 앞 복도에 쌓인 책상(교무실을 거쳐 돌아간다)
g.wall(10, 8, 10, 9).put("c", [[9, 8], [11, 9]]);
g.set(18, 9, "L").set(34, 9, "L");

// ══ 본관 2층 (B, 2층): 복도 y12~13, 벽 y14, 교실 y15~20 ══
g.fill(1, 12, 42, 13);
const classroom = (x0, x1, y0, y1, doorY, front, back) => {
	g.fill(x0, y0, x1, y1).set(front, doorY, "D").set(back, doorY, "D");
	const inward = y0 > doorY ? 1 : -1;
	const far = inward > 0 ? y1 : y0; // 창가 줄
	for (let x = x0 + 1; x <= x1 - 1; x += 2) { g.set(x, far - inward * 1, "T"); g.set(x, far - inward * 3, "T"); }
	g.set(x0, far, "Z"); // 교탁 서랍
	g.set(x1, far, "L"); // 청소함
};
classroom(4, 9, 15, 20, 14, 5, 8); // 2-1
classroom(11, 16, 15, 20, 14, 12, 15); // 2-2
classroom(18, 23, 15, 20, 14, 19, 22); // 2-3
g.fill(25, 15, 27, 20).set(26, 14, "D").put("c", [[25, 20], [27, 20], [27, 19]]).set(25, 15, "Z"); // 교구 준비실(막다른 방)
classroom(29, 34, 15, 20, 14, 30, 33); // 2-4
g.fill(36, 15, 42, 20).set(37, 14, "D").put("L", [[37, 20], [39, 20], [41, 20]]).set(42, 15, "c"); // 화장실
// 2-2 앞 복도: 쓰러진 사물함(교실 앞문으로 들어가 뒷문으로 나온다)
g.wall(14, 12, 14, 13).set(13, 12, "c");

// ══ 2층 서쪽 연결 복도 (x1~2, y14~28) ══
g.fill(1, 14, 2, 28);
g.set(1, 21, "L"); // (연결 복도 가운데 벽장)

// ══ 별관 2층 (C, 2층): 방 y22~27, 벽 y28, 복도 y29~30 ══
g.fill(1, 29, 42, 30);
// 과학실 ─ 준비실 ─ 음악실 이 샛문으로 이어진다
g.fill(4, 22, 10, 27).set(5, 28, "D").set(9, 28, "D").set(11, 24, "D");
g.put("T", [[6, 24], [8, 24], [6, 26], [8, 26]]).put("m", [[4, 22], [5, 22]]).set(10, 22, "k").set(4, 27, "Z");
g.fill(12, 22, 14, 27).set(13, 28, "D").set(15, 24, "D");
g.put("k", [[12, 22], [14, 22]]).set(12, 27, "c").set(14, 27, "Z");
g.fill(16, 22, 21, 27).set(17, 28, "D").set(20, 28, "D");
g.put("T", [[18, 23], [19, 23]]).set(21, 22, "L").set(16, 22, "k");
// 화장실
g.fill(23, 22, 25, 27).set(24, 28, "D").put("L", [[23, 22], [25, 22]]);
// 도서관(서가 줄, 문 2개)
g.fill(27, 22, 36, 27).set(28, 28, "D").set(35, 28, "D");
for (const x of [29, 31, 33, 35]) g.put("k", [[x, 23], [x, 24], [x, 26]]);
g.set(36, 22, "Z").set(27, 22, "L");
// 컴퓨터실
g.fill(38, 22, 42, 27).set(39, 28, "D");
g.put("T", [[39, 24], [41, 24], [39, 26], [41, 26]]).set(42, 22, "Z").set(38, 22, "L");
// 복도가 막힌 두 곳: 음악실 앞(준비실 → 음악실로 돌아간다), 도서관 앞(도서관을 가로지른다)
g.wall(15, 29, 15, 30).wall(32, 29, 32, 30).set(31, 30, "c").set(16, 29, "c");

// ══ 계단 ══
// 본관 1층 ↔ 본관 2층: 서쪽·가운데·동쪽 계단실
g.stairs(6, 10, 0, 1).stairs(24, 10, 0, 1).stairs(38, 10, 0, 1);
// 별관 2층 ↔ 별관 1층: 동쪽 계단만 살아 있다(서쪽 계단실은 무너져 1층에서 막다른 곳)
g.stairs(40, 32, 0, -1);
g.set(6, 32, "c"); // (무너진 계단 입구: 잔해만 보인다)

// ══ 별관 1층 (D): 복도 y33~34, 벽 y35, 방 y36~41 ══
g.fill(1, 33, 45, 34);
// 당직실(시작)
g.fill(1, 36, 5, 41).set(3, 35, "D");
g.put("S", [[1, 36], [2, 36], [1, 37], [2, 37]]).set(5, 41, "R").set(5, 36, "Z").set(1, 41, "L").set(4, 39, "T");
// 창고
g.fill(7, 36, 9, 41).set(8, 35, "D").put("c", [[7, 41], [9, 41], [9, 40], [7, 36]]).set(9, 36, "Z");
// 급식실(식탁 줄) ─ 조리실 샛문
g.fill(11, 36, 20, 41).set(12, 35, "D").set(19, 35, "D").set(21, 39, "D");
for (const x of [13, 15, 17]) g.put("T", [[x, 38], [x, 40]]);
g.set(20, 41, "Z").set(11, 41, "L");
g.fill(22, 36, 27, 41).set(26, 35, "D");
g.put("m", [[22, 41], [23, 41], [24, 41], [27, 41]]).put("k", [[27, 37], [27, 38]]).set(22, 36, "Z").set(25, 39, "T");
// 체육관(가장 큰 공간: 기둥 줄, 문 2개) ─ 체육 창고
g.fill(29, 36, 40, 41).set(30, 35, "D").set(39, 35, "D").set(41, 38, "D");
for (const x of [31, 34, 37]) g.set(x, 38, "O");
g.set(40, 41, "Z").put("c", [[29, 41], [30, 41]]);
g.fill(42, 36, 45, 41).put("c", [[45, 41], [44, 41], [45, 40]]).set(42, 41, "L").set(45, 36, "Z");
// 급식실 앞 복도: 무너진 천장(급식실 → 조리실로 돌아간다)
g.wall(21, 33, 21, 34).set(20, 34, "c");

// ══ 1층 동쪽 연결 복도 (x44~45): 가운데가 무너져 양쪽 모두 막다른 길 ══
g.fill(44, 10, 45, 32).wall(44, 21, 45, 21);
g.put("c", [[44, 20], [45, 22]]).set(45, 15, "Z").set(44, 27, "L");

const opts = { blocked: ["R"] };
report("학교", g, opts);
if (!process.argv.includes("--dry"))
	writeStage("Stage7.luau", g, [
		"STAGE 7 — 학교 (47x43칸, tools/places/school.js 로 생성)",
		"실제 학교 구조: 본관과 별관이 각각 1층·2층(2층 = UpperRects, 계단 1·2 로 오르내림).",
		"본관 1층: 행정실·교무실·교장실(샛문으로 이어짐)·중앙 현관 로비(출구)·보건실·방송실·화장실, 복도 끝에 계단실 3곳.",
		"본관 2층: 교실 줄(앞문·뒷문)·교구 준비실·화장실. 서쪽 2층 연결 복도로 별관 2층(과학실─준비실─음악실 샛문, 화장실, 도서관 서가, 컴퓨터실).",
		"별관 1층: 당직실(시작)·창고·급식실─조리실·기둥이 선 체육관·체육 창고. 별관 계단은 동쪽만 살아 있다.",
		"살짝 뒤틀린 곳: 복도마다 쓰러진 사물함·책상으로 막힌 칸(교실·교무실·도서관을 가로질러 돌아감), 무너진 서쪽 계단실,",
		"가운데가 무너진 1층 동쪽 연결 복도(양쪽 막다른 길). 출구까지 최단 약 150칸.",
	]);
