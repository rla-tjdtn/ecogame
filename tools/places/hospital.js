// 챕터 4 폐병원: 외래·응급 1층(앞동) | 입원 병동 2층 | 수술·영안 1층(뒷동). 실제 병원 구조 위에 막힌 복도·무너진 계단·샛문을 살짝 섞었다.
//   node tools/places/hospital.js [--dry]
// 띠 배치(위→아래): 앞동 1층(y1~9) | 계단 | 병동 2층(y12~26: 북쪽 병실 · 복도 · 남쪽 병실) | 계단 | 뒷동 1층(y29~41)
// 뒷동에서 동쪽 계단으로 병동에 올라, 병동 복도를 서쪽으로 지나 엘리베이터 홀 계단(또는 서쪽 계단실)으로 앞동에 내려가 로비 출구로.
// 앞동과 뒷동을 잇던 동쪽 1층 연결 복도는 가운데가 무너졌다.
const { Grid, report, writeStage } = require("./lib");

const g = new Grid(47, 43);
g.markUpper(1, 12, 42, 26);

// ══ 앞동 1층 (외래·응급): 방 y1~6, 벽 y7, 복도 y8~9 ══
g.fill(1, 8, 45, 9);
// 원무과(수납 창구)
g.fill(1, 1, 5, 6).set(3, 7, "D");
g.put("T", [[2, 3], [4, 3]]).set(1, 1, "Z").set(5, 6, "k");
// 외래 진료실 1(원무과로 샛문)
g.fill(7, 1, 11, 6).set(9, 7, "D").set(6, 4, "D");
g.put("T", [[8, 2]]).set(11, 3, "R").set(11, 1, "Z").set(7, 6, "L");
// 외래 진료실 2
g.fill(13, 1, 16, 6).set(15, 7, "D");
g.put("T", [[14, 2]]).set(16, 4, "R").set(13, 1, "k").set(16, 6, "Z");
// 약제실(약장 줄, 문 2개)
g.fill(18, 1, 23, 6).set(19, 7, "D").set(22, 7, "D");
for (const x of [19, 21, 23]) g.put("k", [[x, 2], [x, 3]]);
g.set(18, 1, "Z").set(18, 6, "L");
// 응급실(침대 줄, 문 2개) — 앞 복도가 무너진 천장으로 막혀 응급실을 가로지른다
g.fill(25, 1, 33, 6).set(26, 7, "D").set(32, 7, "D");
for (const x of [25, 27, 29, 31, 33]) g.set(x, 1, "R");
g.put("k", [[29, 4]]).set(25, 6, "L").set(33, 6, "Z");
g.wall(29, 8, 29, 9).put("c", [[28, 8], [30, 9]]);
// 응급실·외래 로비(출구): 복도 쪽이 넓게 트였고 북쪽 가운데가 정문
g.fill(35, 2, 45, 6).fill(36, 7, 43, 7);
g.set(40, 1, "E");
g.put("O", [[37, 4], [40, 4], [43, 4]]).put("k", [[35, 6], [36, 6]]).put("L", [[35, 2], [45, 2]]).set(45, 6, "Z");

// ══ 계단: 앞동 1층 ↔ 병동 2층 (서쪽 계단실, 엘리베이터 홀 계단) ══
g.stairs(2, 10, 0, 1).stairs(15, 10, 0, 1);

// ══ 병동 2층: 북쪽 병실 y12~16, 벽 y17, 복도 y18~19, 벽 y20, 남쪽 병실 y21~25 ══
g.fill(1, 18, 42, 19);
const ward = (x0, x1, y0, y1, doorX, doorY) => {
	g.fill(x0, y0, x1, y1).set(doorX, doorY, "D");
	const win = doorY > y1 ? y0 : y1; // 창가 벽(문 반대쪽)
	for (let x = x0 + 2; x <= x1; x += 2) g.set(x, win, "R");
	g.set(x0, win, "Z"); // 협탁
	g.set(x1, win === y0 ? y1 : y0, "L"); // 옷장(문 쪽 구석)
};
// 북쪽
g.fill(1, 12, 4, 16).set(3, 17, "D").set(4, 12, "c"); // 서쪽 계단실
ward(6, 10, 12, 16, 8, 17); // 201
g.fill(12, 12, 18, 16).fill(15, 17, 16, 17); // 엘리베이터 홀(복도 쪽이 트임)
g.put("m", [[12, 12], [13, 12], [17, 12], [18, 12]]).set(18, 16, "k");
ward(20, 23, 12, 16, 21, 17); // 202
// 간호사실(복도로 트인 접수대) ─ 203 으로 샛문
g.fill(25, 13, 31, 16).fill(26, 17, 30, 17);
g.put("T", [[27, 14], [29, 14]]).put("k", [[25, 13], [31, 16]]).set(31, 13, "Z").set(25, 16, "L");
ward(33, 37, 12, 16, 35, 17); // 203
g.set(32, 14, "D");
ward(39, 42, 12, 16, 40, 17); // 204
// 남쪽
ward(1, 5, 21, 25, 3, 20); // 211
ward(7, 11, 21, 25, 9, 20); // 212
g.set(6, 23, "D"); // (211 ─ 212 벽이 뚫린 샛문)
g.fill(13, 21, 15, 25).set(14, 20, "D").put("c", [[13, 25], [15, 25], [15, 24]]).set(13, 21, "k").set(15, 21, "Z"); // 린넨·오물실(막다른 방)
ward(17, 21, 21, 25, 19, 20); // 213
// 처치실
g.fill(23, 21, 27, 25).set(25, 20, "D");
g.put("T", [[25, 23]]).put("k", [[23, 25], [27, 25]]).set(27, 21, "Z").set(23, 21, "L");
// 상담실(막다른 작은 방)
g.fill(29, 21, 32, 24).set(30, 20, "D").put("T", [[31, 22]]).set(29, 24, "Z");
ward(34, 37, 21, 25, 35, 20); // 214
// 동쪽 계단실(뒷동 1층으로)
g.fill(39, 21, 42, 25).set(40, 20, "D").set(40, 26, ".").set(42, 25, "c");
g.stairs(40, 28, 0, -1);
// 병동 복도가 막힌 두 곳: 간호사실 동쪽(쓰러진 침대: 203 → 샛문 → 간호사실로 돌아감),
// 엘리베이터 홀 서쪽(무너진 천장: 212 → 샛문 → 211 로 돌아가 서쪽 계단실)
g.wall(32, 18, 32, 19).put("c", [[33, 19], [31, 18]]);
g.wall(11, 18, 11, 19).put("c", [[10, 19], [12, 18]]);

// ══ 뒷동 1층 (수술·영안): 북쪽 작은 방 y29~31, 벽 y32, 복도 y33~34, 벽 y35, 남쪽 방 y36~41 ══
g.fill(1, 33, 45, 34);
// 북쪽 줄
g.fill(1, 29, 5, 31).set(3, 32, "D").put("c", [[1, 29], [5, 31]]).set(5, 29, "Z"); // 창고
g.fill(7, 29, 12, 31).set(9, 32, "D").put("L", [[7, 29], [12, 29]]).set(12, 31, "k"); // 탈의실
g.fill(14, 29, 17, 31).set(15, 32, "D").put("m", [[14, 29], [15, 29]]).set(17, 29, "c"); // 고장 난 엘리베이터 홀
g.fill(19, 29, 26, 31).set(20, 32, "D").set(25, 32, "D"); // 소독실(문 2개)
g.put("m", [[19, 29], [26, 29]]).put("k", [[22, 29], [23, 29]]).set(19, 31, "Z");
g.fill(28, 29, 32, 31).set(30, 32, "D").put("c", [[28, 29], [29, 29], [30, 29], [32, 31]]).set(32, 29, "L"); // 무너진 가운데 계단실(막다른 곳)
g.fill(34, 29, 36, 31).set(35, 32, "D").set(36, 29, "Z").set(34, 31, "c"); // 청소 도구실
g.fill(38, 29, 42, 31).set(39, 32, "D").set(42, 31, "k"); // 동쪽 계단실(위 계단 1 → 병동)
// 남쪽 줄
// 당직실(시작)
g.fill(1, 36, 5, 41).set(3, 35, "D");
g.put("S", [[1, 36], [2, 36], [1, 37], [2, 37]]).set(5, 41, "R").set(5, 36, "Z").set(1, 41, "L").set(4, 39, "T");
// 영안실(시신 냉장고 k 줄, 안치대 R, 문 2개) — 앞 복도가 막혀 영안실을 가로지른다
g.fill(7, 36, 14, 41).set(8, 35, "D").set(13, 35, "D");
for (const x of [7, 8, 9, 10, 11, 12, 13, 14]) g.set(x, 41, "k");
g.put("R", [[9, 38], [12, 38]]).set(14, 36, "Z").set(7, 36, "L");
g.wall(11, 33, 11, 34).put("c", [[10, 33], [12, 34]]);
// 수술실 ─ 수술 준비실 샛문
g.fill(16, 36, 22, 41).set(18, 35, "D").set(23, 38, "D");
g.set(19, 38, "X").put("m", [[16, 36], [22, 36], [16, 41]]).set(22, 41, "Z").set(18, 41, "k");
g.fill(24, 36, 27, 41).set(25, 35, "D");
g.put("k", [[27, 36], [27, 37]]).set(24, 41, "L").set(27, 41, "Z").set(25, 40, "T");
// 회복실(침대 줄, 문 2개) — 앞 복도에 쓰러진 침대
g.fill(29, 36, 36, 41).set(30, 35, "D").set(35, 35, "D");
for (const x of [31, 33, 35]) g.set(x, 41, "R");
g.set(29, 41, "Z").set(36, 36, "k");
g.wall(33, 33, 33, 34).put("c", [[32, 34], [34, 33]]);
// 중앙 공급실(막다른 방)
g.fill(38, 36, 42, 41).set(40, 35, "D");
g.put("k", [[38, 38], [38, 39], [42, 38], [42, 39]]).set(42, 41, "Z").set(38, 41, "c");
// 기계실
g.fill(44, 36, 45, 41).set(44, 35, "D").put("m", [[45, 36], [45, 37]]).set(44, 41, "Z");

// ══ 동쪽 1층 연결 복도 (x44~45): 가운데가 무너져 양쪽 모두 막다른 길 ══
g.fill(44, 10, 45, 32).wall(44, 21, 45, 21);
g.put("c", [[44, 20], [45, 22]]).set(45, 14, "Z").set(44, 28, "L");

const opts = { blocked: ["R"] };
const r = report("병원", g, opts);
if (process.argv.includes("--print")) console.log(g.rows().join("\n"));
if (!process.argv.includes("--dry")) {
	// (writeStage 는 주석 달린 UpperRects 줄을 못 지우므로 먼저 지운다)
	const sf = require("path").join(__dirname, "..", "..", "src", "server", "Stages", "Stage4.luau");
	const fs = require("fs");
	fs.writeFileSync(sf, fs.readFileSync(sf, "utf8").replace(/\r\n/g, "\n").replace(/\tUpperRects = \{[^\n]*\n/g, ""));
}
if (!process.argv.includes("--dry"))
	writeStage("Stage4.luau", g, [
		"STAGE 4 — 폐병원 (47x43칸, tools/places/hospital.js 로 생성)",
		"실제 병원 구조: 앞동(외래·응급) 1층, 입원 병동 2층, 뒷동(수술·영안) 1층(2층 = UpperRects, 계단 1·2 로 오르내림).",
		"앞동 1층: 원무과─외래 진료실(샛문)·진료실·약제실(약장 줄)·응급실(침대 줄)·기둥이 선 응급실·외래 로비(출구).",
		"병동 2층: 가운데 복도 양쪽으로 병실(창가 침대 R·협탁 Z·옷장 L), 복도로 트인 간호사실, 엘리베이터 홀, 린넨·오물실, 처치실, 상담실,",
		"서쪽·엘리베이터 홀·동쪽 계단. 뒷동 1층: 당직실(시작)·영안실(냉장고 줄)·수술실─준비실(샛문)·회복실·중앙 공급실·소독실·탈의실.",
		"살짝 뒤틀린 곳: 복도마다 쓰러진 침대·무너진 천장으로 막힌 칸(영안실·회복실·응급실을 가로지르거나 병실 샛문으로 돌아감),",
		"무너진 뒷동 가운데 계단실(막다른 곳), 가운데가 무너진 동쪽 1층 연결 복도. 병동에서 내려가는 계단은 두 곳(엘리베이터 홀·서쪽).",
		"출구까지 최단 약 PATHLEN칸.",
	].map((l) => l.replace("PATHLEN", String(r.exit))));
