function patchProps() {
	let s = fs.readFileSync(sf, "utf8");
	const crlf = s.includes("\r\n");
	s = s.replace(/\r\n/g, "\n");
	if (!s.includes("ChapterProps.Hospital")) s = s.replace(/(local Props = require\(script\.Parent\.Parent\.Props\)\n)/, "$1local HP = require(script.Parent.Parent.ChapterProps.Hospital)\n");
	s = s.replace(/\tProps = \{[^\n]*\n/, PROPS_LINE + "\n").replace(/\tWalkable = \{[^\n]*\n/, WALK_LINE + "\n");
	return crlf ? s.replace(/\n/g, "\r\n") : s;
}
