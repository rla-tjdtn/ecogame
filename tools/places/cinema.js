// 챕터 10 폐영화관: 멀티플렉스 1층(로비·상영관 4개·복도)과 2층(영사실 층). 실제 영화관 구조 위에 무너진 복도·막힌 계단·샛문을 살짝 섞었다.
//   node tools/places/cinema.js [--dry]
// 띠 배치(위→아래): 2층 영사실 층(y1~11) | 계단 | 1층 메인 복도(y14~15) | 상영관 4개(y17~27) | 비상구 복도(y29~30) | 로비 띠(y32~41)
// 서쪽 넓은 복도(x1~3)가 로비와 메인 복도를 잇는다. 상영관 사이 직원 통로 2개가 메인 복도와 비상구 복도를 잇는다(고리).
const { Grid, report, writeStage } = require("./lib");

const g = new Grid(47, 43);
g.markUpper(1, 1, 45, 11);

// ══ 1층: 서쪽 넓은 복도 (x1~3, y14~41) + 메인 복도 (y14~15) ══
g.fill(1, 14, 3, 41);
g.fill(1, 14, 37, 15);
g.put("F", [[1, 20], [1, 26], [1, 32]]).set(3, 41, "L").set(1, 41, "Z");
g.put("F", [[10, 14], [24, 14], [30, 14]]);
// 메인 복도 무너진 천장(1관 동쪽): 1관을 가로질러(뒷문 → 옆 통로 → 앞문) 비상구 복도로 돌아간다
g.wall(15, 14, 15, 15).put("c", [[14, 14], [16, 15]]);
// 무너진 계단(x32~33): 잔해만 쌓인 막다른 계단참
g.put("c", [[32, 13], [33, 13]]);
g.set(37, 14, "Z").set(35, 15, "c");

// ══ 상영관 (y17~26): 뒤쪽(북)이 메인 복도, 스크린(남)은 비상구 복도 쪽 ══
// x0..x1 (양 끝 열이 옆 통로). 뒷문 2개(y16), 앞문 2개(y27, 스크린 옆). u = 스크린이 남쪽인 좌석 줄(뒤로 갈수록 높은 단)
function hall(x0, x1, { frontDoors = [x0, x1], mid = null } = {}) {
	g.fill(x0, 17, x1, 26);
	for (let x = x0 + 2; x <= x1 - 2; x++) g.set(x, 26, "W");
	for (const y of [19, 20, 21, 23, 24]) for (let x = x0 + 1; x <= x1 - 1; x++) if (x !== mid) g.set(x, y, "u");
	g.set(x0, 16, "D").set(x1, 16, "D");
	for (const x of frontDoors) g.set(x, 27, "D");
	g.set(x1 - 1, 17, "L"); // 뒤 구석 사물함
}
hall(5, 14, { mid: 9 }); // 1관(큰): 가운데 통로
g.set(6, 26, "Z");
hall(18, 24); // 2관(작은)
g.set(23, 26, "Z");
hall(26, 35, { mid: 30 }); // 3관(큰)
g.put("c", [[27, 22], [26, 22]]).set(34, 26, "Z"); // 3관 옆 통로에 무너진 좌석
hall(39, 45, { frontDoors: [39, 44] }); // 4관(작은): 비상구 쪽
g.set(40, 17, "Z");
// 상영관 사이 직원 통로(1칸 폭): 메인 복도 ↔ 비상구 복도
g.fill(16, 17, 16, 26).set(16, 16, "D").set(16, 27, "D");
g.fill(37, 17, 37, 26).set(37, 16, "D").set(37, 27, "D");

// ══ 비상구 복도 (y28~29) ══ 서쪽 구간(1~3관 앞문)과 동쪽 구간(4관 앞문, 출구)은 벽으로 갈라졌다
g.fill(5, 28, 37, 29);
g.put("c", [[25, 28], [26, 29], [27, 29]]).set(5, 29, "L").set(20, 29, "Z").set(11, 28, "F");
g.fill(39, 28, 44, 29);
g.set(45, 28, "E"); // 비상구(출구)
g.set(39, 29, "L");

// ══ 1층 동쪽 비상계단 홀 (x39~45, y14~15): 2층에서 내려오는 계단, 4관 뒷문 ══
g.fill(39, 14, 45, 15);
g.set(45, 14, "c");

// ══ 로비 띠 ══
// 로비 홀 x5~38, y31~36 (검표대·기둥·매점·줄 세우기 기둥)
g.fill(5, 31, 38, 36);
g.set(4, 32, "A").set(4, 35, "A"); // 서쪽 넓은 복도로(검표구 안쪽)
g.put("g", [[10, 32], [10, 34], [10, 36]]); // 검표대 줄(사이로 지나간다)
g.put("O", [[15, 33], [15, 35], [34, 33]]);
// 매점: 카운터(y33) 뒤 직원 줄(y32), 벽 쪽 팝콘·음료 기계(y31)
for (let x = 20; x <= 30; x++) g.set(x, 33, "C");
g.put("M", [[21, 31], [24, 31], [28, 31]]).set(26, 31, "Z").set(30, 31, "L");
for (let x = 22; x <= 31; x++) g.set(x, 35, "r");
g.put("F", [[7, 31], [13, 31], [33, 31], [37, 31], [18, 36]]);
// 로비 아래 방들 (y38~41, 문 y37)
g.fill(5, 38, 10, 41).set(8, 37, "D").put("L", [[5, 41], [7, 41], [9, 41]]).put("V", [[5, 38]]).set(10, 38, "Z"); // 남자 화장실
g.fill(12, 38, 17, 41).set(15, 37, "D").put("L", [[12, 41], [14, 41], [16, 41]]).put("V", [[17, 38]]).set(12, 38, "Z"); // 여자 화장실
g.fill(19, 38, 20, 41).set(19, 37, "D").put("L", [[20, 41]]).set(20, 38, "c"); // 청소도구함
g.fill(22, 38, 28, 41).set(25, 37, "D").put("T", [[24, 40], [26, 40]]).set(28, 38, "Z").set(22, 41, "L"); // 직원 휴게실
g.fill(30, 38, 38, 41).set(34, 37, "D").put("c", [[30, 41], [31, 41], [30, 40], [36, 38]]).set(38, 41, "Z"); // 창고
// 매표소(시작) x40~45, y31~41: 로비로 문 하나, 창고로 샛문 하나
g.fill(40, 31, 45, 41).set(39, 33, "D").set(39, 40, "D");
g.put("S", [[41, 32], [42, 32], [41, 33], [42, 33]]);
g.put("C", [[41, 37], [42, 37], [43, 37]]).set(45, 41, "Z").set(45, 31, "L").set(44, 39, "T");

// ══ 계단 ══ 서쪽(관리실 쪽, 막다른 2층), 가운데(영사실 층), 동쪽(비상계단 → 4관·출구)
g.stairs(8, 13, 0, -1).stairs(17, 13, 0, -1).stairs(43, 13, 0, -1);

// ══ 2층 서쪽 (x1~13): 관리실·영사실 1·필름 창고. 영사 복도가 x14 에서 무너져 막다른 구역 ══
g.fill(1, 10, 13, 11);
g.fill(1, 1, 6, 8).set(3, 9, "D"); // 관리실
g.put("T", [[2, 3], [4, 3], [2, 6]]).set(6, 1, "Z").set(1, 8, "L");
g.fill(8, 5, 13, 8).set(11, 9, "D"); // 영사실 1
g.put("P", [[9, 8]]).set(13, 5, "Z");
g.fill(8, 1, 13, 3).set(10, 4, "D"); // 필름 창고
g.put("c", [[8, 1], [9, 1], [13, 3]]).set(13, 1, "Z");
g.set(13, 11, "c");

// ══ 2층 가운데·동쪽 (x15~45): 북쪽 직원 통로(y1~2)와 남쪽 영사 복도(y10~11) 사이에 방들(y4~8), 방마다 문 2개 ══
g.fill(15, 1, 45, 2);
g.fill(15, 10, 45, 11);
// 영사실 2
g.fill(15, 4, 20, 8).set(17, 9, "D").set(19, 3, "D");
g.put("P", [[16, 8]]).set(15, 4, "Z").put("m", [[20, 8]]);
// 필름 보관실(막다른 작은 방)
g.fill(22, 4, 24, 8).set(23, 9, "D");
g.put("c", [[22, 4], [24, 4], [22, 5]]).set(24, 6, "Z");
// 영사실 3(긴 영사실: 3관·4관 영사기 줄). 영사 복도가 바로 앞(x30)에서 무너져 이 방을 가로질러 간다
g.fill(26, 4, 34, 8).set(27, 9, "D").set(33, 9, "D").set(30, 3, "D");
g.put("P", [[29, 8], [31, 8]]).put("m", [[26, 4], [34, 4]]).set(28, 4, "L").set(32, 4, "Z");
g.wall(30, 10, 30, 11).put("c", [[29, 11], [31, 10]]);
// 직원 사무실(문 2개: 영사 복도 · 북쪽 직원 통로)
g.fill(36, 4, 41, 8).set(38, 9, "D").set(40, 3, "D");
g.put("T", [[37, 6], [39, 6]]).set(41, 4, "Z").set(36, 8, "L");
// 음향 기계실(막다른 방)
g.fill(43, 4, 45, 8).set(44, 9, "D");
g.put("m", [[43, 4], [45, 4]]).set(45, 7, "Z");
g.put("c", [[38, 1], [24, 2], [35, 2]]).set(15, 1, "L").set(45, 1, "Z");

const opts = { blocked: ["q", "u", "W", "C", "M", "P", "g", "V"], walkable: ["F", "r"] };
report("영화관", g, opts);
if (process.argv.includes("--print")) console.log(g.rows().join("\n"));
