// 챕터 8 폐유치원(1층 건물): ㄷ자 건물이 가운데 놀이 마당을 감싼다. 남서쪽 현관·신발장 홀에서 시작해
// 서쪽 반(위로) → 북쪽 원장실·교무실·강당(동쪽으로) → 동쪽 반(아래로) → 남쪽 식당 앞 복도(서쪽으로) → 울타리 문으로 마당에 들어가
// 마당 북쪽 끝 뒷문(E)으로 나간다. 구간마다 복도 + 옆문으로 이어진 방 사슬 두세 갈래가 나란히 간다.
//   node tools/places/kindergarten.js [--dry]
const { Grid, report, writeStage } = require("./lib");

const g = new Grid(47, 43);
// 반 교실 책걸상(작은 책상 t) 줄: 2칸 간격
const kidRoom = (x0, x1, y0, y1) => {
	for (let x = x0 + 1; x <= x1 - 1; x += 2) for (let y = y0 + 2; y <= y1 - 2; y += 2) g.set(x, y, "t");
};

// ══ 북쪽 날개 (y1~10) ══
// 교재 창고(막다른 방, 숨기 좋은 곳)
g.fill(1, 1, 5, 7).set(3, 8, "D");
g.put("c", [[1, 1], [2, 1], [1, 2], [4, 4], [5, 4]]).set(5, 1, "Z").set(1, 7, "L").set(5, 7, "y");
// 원장실: 교무실과 낮은 통로(q)로 이어진다
g.fill(7, 1, 12, 7).set(10, 8, "D").set(13, 4, "q");
g.put("t", [[9, 3], [10, 3]]).set(12, 1, "Z").set(7, 1, "L").set(7, 7, "c");
// 교무실(문 3: 복도 2, 강당 옆문)
g.fill(14, 1, 22, 7).set(16, 8, "D").set(21, 8, "D").set(23, 3, "D");
for (const x of [16, 19]) g.put("t", [[x, 3], [x + 1, 3], [x, 5], [x + 1, 5]]);
g.set(22, 1, "Z").set(14, 7, "L").set(14, 1, "c").set(22, 7, "c");
// 강당(유희실, 가장 큰 공간): 무대 단, 기둥 넷(문 4: 교무실 옆문 둘, 동쪽 복도·보건실)
g.fill(24, 1, 34, 10).set(23, 6, "D").set(35, 9, "D").set(35, 3, "D");
g.put("#", [[27, 5], [31, 5], [27, 8], [31, 8]]);
g.put("O", [[26, 1], [27, 1], [28, 1], [29, 1], [30, 1], [31, 1], [32, 1]]); // 무대 단
g.put("y", [[24, 10], [34, 1]]).set(34, 10, "Z").set(24, 1, "L").put("U", [[29, 7]]);
// 보건실(작은 침대 = 낮잠 매트, 교사 화장실로 옆문)
g.fill(36, 1, 40, 7).set(38, 8, "D").set(41, 4, "D");
g.put("N", [[37, 2], [37, 3], [39, 5], [39, 6]]).set(40, 1, "Z").set(36, 7, "L").set(40, 7, "j");
// 교사 화장실
g.fill(42, 1, 45, 7).set(43, 8, "D");
g.put("j", [[42, 1], [44, 1]]).set(45, 7, "L").set(45, 3, "Z");
// 복도 A: 서쪽(현관 쪽 날개 위) · 동쪽(강당 너머)
g.fill(1, 9, 22, 10).set(1, 9, "Z").put("c", [[13, 10]]);
g.fill(36, 9, 45, 10).set(45, 10, "L");

// ══ 서쪽 날개 (x1~15, y12~41): 가운데 복도 W(위로) + 양옆 반 교실 사슬 ══
g.fill(7, 11, 8, 33);
g.put("c", [[8, 20], [7, 27]]);
// 서쪽 사슬: 해님반 → 낮잠방 → 작은 화장실
g.fill(1, 12, 5, 18).set(6, 13, "D").set(6, 17, "D").set(3, 11, "D");
kidRoom(1, 5, 12, 18);
g.set(1, 12, "L").set(5, 18, "y").set(1, 18, "Z");
g.fill(1, 20, 5, 27).set(3, 19, "D").set(6, 24, "D");
for (const y of [21, 23, 25]) g.put("N", [[1, y], [2, y], [4, y], [5, y]]);
g.set(1, 27, "L").set(5, 27, "Z");
g.fill(1, 29, 5, 33).set(3, 28, "D").set(6, 31, "D").set(3, 34, "D");
g.put("j", [[1, 30], [1, 32], [5, 33]]).set(5, 29, "L");
// 동쪽 사슬: 달님반 → 별님반 → 꽃님반
g.fill(10, 12, 15, 18).set(9, 14, "D").set(15, 11, "D");
kidRoom(10, 15, 12, 18);
g.set(10, 12, "Z").set(10, 18, "y").set(15, 18, "L");
g.fill(10, 20, 15, 26).set(12, 19, "D").set(9, 23, "D");
kidRoom(10, 15, 20, 26);
g.set(15, 20, "L").set(10, 26, "y").set(15, 26, "Z");
g.fill(10, 28, 15, 33).set(13, 27, "D").set(9, 30, "D").set(11, 34, "D");
kidRoom(10, 15, 28, 33);
g.set(15, 33, "L").set(15, 28, "y");
// 현관·신발장 홀(시작, 문 3): 벽을 따라 어린이 신발장(L)
g.fill(1, 35, 12, 41).set(7, 34, "D");
g.put("S", [[1, 38], [2, 38], [1, 39], [2, 39]]);
g.put("L", [[1, 36], [1, 37], [1, 40], [4, 41], [5, 41], [6, 41]]).set(12, 36, "Z").set(12, 41, "y").set(9, 41, "c");

// ══ 동쪽 날개 (x31~45, y11~33): 가운데 복도 E(아래로) + 양옆 방 사슬 ══
g.fill(37, 11, 38, 33);
g.put("c", [[37, 16], [38, 29]]);
// 서쪽 사슬: 새싹반 → 볼풀방 → 실내 놀이터
g.fill(31, 12, 35, 18).set(36, 13, "D");
kidRoom(31, 35, 12, 18);
g.set(31, 12, "L").set(35, 18, "Z").set(31, 18, "y");
g.fill(31, 20, 35, 25).set(33, 19, "D").set(36, 23, "D");
g.fill(32, 21, 34, 24, "G");
g.set(31, 25, "Z").set(35, 20, "L").set(31, 20, "y");
g.fill(31, 27, 35, 32).set(32, 26, "D").set(36, 30, "D").set(34, 33, "D").set(31, 33, "D");
g.put("U", [[32, 29], [33, 29]]).set(35, 32, "L").set(31, 32, "y").set(35, 27, "Z");
// 동쪽 사슬: 무지개반 → 구름반 → 블록 놀이방
g.fill(40, 12, 45, 17).set(39, 16, "D").set(42, 11, "D");
kidRoom(40, 45, 12, 17);
g.set(45, 12, "Z").set(40, 17, "y").set(45, 17, "L");
g.fill(40, 19, 45, 25).set(43, 18, "D").set(39, 21, "D");
kidRoom(40, 45, 19, 25);
g.set(45, 25, "L").set(40, 25, "Z");
g.fill(40, 27, 45, 32).set(42, 26, "D").set(39, 31, "D").set(43, 33, "D");
g.put("O", [[42, 29], [43, 29]]).set(45, 27, "Z").set(40, 32, "y").set(45, 32, "L");

// ══ 남쪽: 식당 앞 복도 C (y34~35, 서쪽으로) + 식당·조리실·교구실 ══
g.fill(17, 34, 45, 35).put("c", [[30, 34], [24, 35]]).set(45, 35, "Z");
// 식당(문 2 + 조리실 옆문)
g.fill(17, 37, 29, 41).set(19, 36, "D").set(27, 36, "D").set(30, 39, "D");
for (const x of [19, 23]) g.put("t", [[x, 38], [x + 1, 38], [x, 40], [x + 1, 40]]);
g.set(17, 41, "Z").set(29, 41, "L").set(17, 37, "y");
// 조리실(문 2)
g.fill(31, 37, 38, 41).set(37, 36, "D");
g.put("m", [[31, 41], [32, 41], [34, 41], [35, 41], [37, 41], [38, 41], [38, 37], [38, 38]]).set(31, 37, "Z").set(34, 39, "c");
// 교구실(막다른 방)
g.fill(40, 37, 45, 41).set(42, 36, "D");
g.put("c", [[45, 41], [44, 41], [45, 40]]).put("y", [[40, 41], [43, 39]]).set(45, 37, "Z").set(40, 37, "L");

// ══ 가운데 놀이 마당(x17~29, y12~32): 울타리로 둘러싸여 남쪽 문 두 곳으로만 들어간다 ══
g.fill(17, 13, 29, 32);
g.set(18, 33, "A").set(22, 33, "A");
// 울타리 두 줄(줄마다 양 끝 틈) — 남쪽 놀이기구 마당 / 가운데 그네 마당 / 북쪽 모래 마당
g.wall(20, 22, 26, 22);
g.wall(21, 17, 27, 17);
// 남쪽: 미끄럼틀·정글짐·장난감 더미
g.put("U", [[20, 26], [21, 26], [26, 28], [26, 29]]).put("O", [[23, 30], [24, 30], [18, 29]]).put("y", [[29, 32], [17, 24]]);
g.set(17, 32, "L").set(29, 25, "Z").set(23, 23, "Z");
// 북쪽: 모래밭(G = 발이 빠지는 바닥, 지나갈 수 있다), 그네 기둥
g.fill(18, 14, 21, 16, "G");
g.put("O", [[26, 15], [28, 15]]).put("y", [[29, 20], [17, 13]]).set(17, 20, "L").set(29, 13, "Z");
// 마당 북동쪽 끝 뒷문(비상구)
g.set(28, 12, "E");

const opts = { walkable: ["G", "N", "q"] };
const r = report("유치원", g, opts);
if (!process.argv.includes("--dry"))
	writeStage("Stage8.luau", g, [
		"STAGE 8 — 폐유치원 (47x43칸, tools/places/kindergarten.js 로 생성)",
		"ㄷ자 건물이 가운데 놀이 마당을 감싼다: 남서쪽 현관·신발장 홀(시작) → 서쪽 날개(위로) → 북쪽 날개(동쪽으로) → 동쪽 날개(아래로) →",
		"식당 앞 복도(서쪽으로) → 울타리 문(두 곳)으로 마당에 들어가 마당 북쪽 끝 뒷문 비상구(E)로 나간다.",
		"서쪽 날개: 가운데 복도 + 해님반·낮잠방(N)·작은 화장실 사슬 + 달님반·별님반·꽃님반 사슬(방끼리 옆문) | 현관은 문 3개.",
		"북쪽 날개: 교재 창고(막다른 방)·원장실(교무실로 낮은 통로 q)·교무실·강당(유희실, 무대·기둥, 가장 큰 공간)·보건실·교사 화장실, 복도 A.",
		"동쪽 날개: 가운데 복도 + 새싹반·볼풀방(G)·실내 놀이터(U 미끄럼틀) 사슬 + 무지개반·구름반·블록 놀이방 사슬.",
		"남쪽: 식당 앞 복도 C, 식당(문 2 + 조리실 옆문)·조리실·교구실(막다른 방). 마당은 울타리로 둘러싸여 건물 쪽 문이 없다(모래밭 G, 놀이기구).",
		`숨는 곳(L)은 어린이 사물함·신발장, 뒤지는 곳(Z)은 장난감 상자. 출구까지 최단 약 ${r.exit}칸.`,
	]);
