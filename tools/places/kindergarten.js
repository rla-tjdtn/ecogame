// 챕터 8 폐유치원(1층 건물): 남쪽 현관·신발장 홀에서 시작해 긴 복도 세 줄(C → B → A)을 갈지자로 거슬러 올라가
// 북동쪽 후문(비상구)으로 나간다. 복도 사이에는 반별 교실·놀이 공간이 줄지어 있고, 두 복도를 잇는 방은 몇 곳뿐이다.
//   node tools/places/kindergarten.js [--dry]
// 띠 배치(위→아래): 북쪽 방(y1~7) | 복도 A(y9~10) | 교실 줄(y12~18) | 복도 B(y20~21) | 놀이 공간(y23~30) | 복도 C(y32~33) | 남쪽 방(y35~41)
const { Grid, report, writeStage } = require("./lib");

const g = new Grid(47, 43);

// ══ 북쪽 방 (y1~7), 문은 복도 A 쪽(y8) ══
// 교재 창고(막다른 방)
g.fill(1, 1, 6, 7).set(3, 8, "D");
g.put("c", [[1, 1], [2, 1], [1, 2], [4, 4], [5, 4]]).set(6, 1, "Z").set(1, 7, "L").set(6, 7, "y");
// 원장실: 교무실과 낮은 통로(q)로 이어진다
g.fill(8, 1, 13, 7).set(10, 8, "D").set(14, 5, "q");
g.put("t", [[10, 3], [11, 3]]).set(13, 1, "Z").set(8, 1, "L").set(8, 7, "c");
// 교무실: 복도 A 가 이 앞에서 막혀 있어 문 두 개로 가로질러야 한다
g.fill(15, 1, 26, 7).set(16, 8, "D").set(25, 8, "D");
for (const x of [18, 20, 22]) g.put("t", [[x, 3], [x + 1, 3], [x, 5], [x + 1, 5]]);
g.set(26, 1, "Z").set(15, 7, "L").set(15, 1, "c").set(26, 7, "c");
// 보건실(작은 침대 = 낮잠 매트)
g.fill(28, 1, 33, 7).set(30, 8, "D");
g.put("N", [[28, 2], [28, 3], [28, 5], [28, 6]]).set(33, 4, "Z").set(33, 1, "j").set(33, 7, "L");
// 교사 화장실
g.fill(35, 1, 38, 7).set(36, 8, "D");
g.put("j", [[35, 1], [37, 1]]).set(38, 7, "L").set(38, 3, "Z");
// 후문 홀 → 비상구(E)
g.fill(40, 1, 44, 7).set(41, 8, "D").set(45, 4, "E");
g.set(40, 1, "L").set(44, 1, "c").set(44, 7, "y");

// ══ 복도 A (y9~10): 교무실 앞이 무너진 천장으로 막혔다 ══
g.fill(1, 9, 45, 10);
g.wall(21, 9, 21, 10).put("c", [[20, 9], [22, 10]]);
g.set(45, 9, "L").set(1, 9, "Z");

// ══ 교실 줄 (y12~18): 반별 교실, 복도 A 또는 B 한쪽으로만 열린다(해님반만 둘 다) ══
const kidRoom = (x0, x1, y0, y1) => {
	for (let x = x0 + 1; x <= x1 - 1; x += 2) for (let y = y0 + 2; y <= y1 - 2; y += 2) g.set(x, y, "t");
};
// 해님반: 복도 A·B 를 잇는 문 두 개
g.fill(1, 12, 7, 18).set(5, 11, "D").set(3, 19, "D");
kidRoom(1, 7, 12, 18);
g.set(1, 12, "L").set(7, 18, "y").set(7, 12, "U");
// 달님반: 복도 B 로만 열리지만 사물함 뒤 낮은 통로(q)로 해님반에 기어 들어간다
g.fill(9, 12, 15, 18).set(13, 19, "D").set(8, 15, "q");
kidRoom(9, 15, 12, 18);
g.set(15, 12, "Z").set(9, 18, "y").set(9, 12, "L");
// 별님반
g.fill(17, 12, 23, 18).set(19, 19, "D");
kidRoom(17, 23, 12, 18);
g.set(17, 12, "Z").set(23, 18, "L").set(23, 12, "U");
// 새싹반(복도 A 쪽)
g.fill(25, 12, 31, 18).set(27, 11, "D");
kidRoom(25, 31, 12, 18);
g.set(31, 18, "Z").set(25, 18, "y").set(31, 12, "L");
// 무지개반
g.fill(33, 12, 38, 18).set(35, 19, "D");
kidRoom(33, 38, 12, 18);
g.set(38, 12, "L").set(33, 12, "U").set(38, 18, "Z");
// 작은 화장실(복도 A 쪽)
g.fill(40, 12, 45, 18).set(42, 11, "D");
g.put("j", [[40, 18], [42, 18], [44, 18], [45, 14]]).set(45, 16, "Z").set(40, 12, "L");

// ══ 복도 B (y20~21) ══
g.fill(1, 20, 45, 21);
g.put("c", [[16, 20], [29, 21]]).set(45, 20, "L");

// ══ 놀이 공간 (y23~30) ══
// 낮잠방(복도 C 쪽)
g.fill(1, 23, 7, 30).set(4, 31, "D");
for (const y of [24, 26, 28]) g.put("N", [[2, y], [3, y], [5, y], [6, y]]);
g.set(1, 30, "L").set(7, 23, "Z").set(7, 30, "y");
// 꽃님반(복도 B 쪽)
g.fill(9, 23, 15, 30).set(12, 22, "D");
kidRoom(9, 15, 23, 30);
g.set(9, 30, "Z").set(15, 30, "y").set(15, 23, "L");
// 실내 놀이터(큰 공간): 복도 C 로 문 두 개, 가운데 정글짐 칸막이, 미끄럼틀, 볼풀방으로 기어가는 터널(q)
g.fill(17, 23, 30, 30).set(18, 31, "D").set(29, 31, "D");
g.wall(24, 23, 24, 27);
g.put("U", [[19, 25], [20, 25], [27, 25], [28, 25]]).put("O", [[21, 28], [27, 28]]);
g.put("y", [[17, 30], [30, 30]]).set(30, 23, "Z").set(17, 23, "L").set(31, 27, "q");
// 볼풀방: 복도 C·B 를 잇는다
g.fill(32, 23, 38, 30).set(34, 31, "D").set(36, 22, "D");
g.fill(33, 25, 37, 28, "G");
g.set(38, 30, "Z").set(32, 23, "y").set(38, 23, "L");
// 구름반: 복도 C·B 를 잇는다
g.fill(40, 23, 45, 30).set(42, 31, "D").set(43, 22, "D");
kidRoom(40, 45, 23, 30);
g.set(45, 26, "L").set(40, 30, "y").set(45, 30, "Z");

// ══ 복도 C (y32~33): 가운데가 쓰러진 사물함으로 막혔다(놀이터나 식당으로 돌아간다) ══
g.fill(1, 32, 45, 33);
g.wall(24, 32, 24, 33).put("c", [[23, 32], [25, 33]]);
g.set(45, 32, "Z").set(1, 33, "L");

// ══ 남쪽 방 (y35~41), 문은 복도 C 쪽(y34) ══
// 현관·신발장 홀(시작): 벽을 따라 어린이 신발장(L)
g.fill(1, 35, 9, 41).set(7, 34, "D");
g.put("S", [[3, 38], [4, 38], [3, 39], [4, 39]]);
g.put("L", [[1, 36], [1, 37], [1, 39], [4, 41], [5, 41], [6, 41]]).set(9, 35, "Z").set(9, 41, "y");
// 작은 화장실
g.fill(11, 35, 15, 41).set(13, 34, "D");
g.put("j", [[11, 41], [13, 41], [15, 41]]).set(15, 35, "Z").set(11, 35, "L");
// 식당: 복도 C 로 문 두 개, 조리실로 옆문
g.fill(17, 35, 30, 41).set(18, 34, "D").set(29, 34, "D").set(31, 38, "D");
for (const x of [19, 22, 25]) g.put("t", [[x, 37], [x + 1, 37], [x, 39], [x + 1, 39]]);
g.set(17, 41, "Z").set(30, 41, "L");
// 조리실(식당으로만 들어간다)
g.fill(32, 35, 38, 41);
g.put("m", [[32, 41], [33, 41], [35, 41], [36, 41], [38, 41], [32, 35], [33, 35]]).set(38, 35, "Z").set(35, 38, "c");
// 교구실
g.fill(40, 35, 45, 41).set(42, 34, "D");
g.put("c", [[45, 41], [44, 41], [45, 40]]).put("y", [[40, 41], [43, 38]]).set(45, 35, "Z");

const opts = { walkable: ["G", "N", "q"] };
report("유치원", g, opts);
if (!process.argv.includes("--dry"))
	writeStage("Stage8.luau", g, [
		"STAGE 8 — 폐유치원 (47x43칸, tools/places/kindergarten.js 로 생성)",
		"진짜 유치원 1층 구조: 남쪽 현관·신발장 홀(시작)에서 긴 복도 세 줄(C → B → A)을 갈지자로 올라가 북동쪽 후문 비상구(E)로 나간다.",
		"남쪽: 현관·작은 화장실·식당(문 2)·조리실·교구실 | 놀이 공간: 낮잠방(N)·꽃님반·실내 놀이터(U 미끄럼틀, 정글짐 칸막이)·볼풀방(G)·구름반",
		"교실 줄: 해님반·달님반·별님반·새싹반·무지개반(작은 책걸상 t)·작은 화장실(j) | 북쪽: 교재 창고·원장실·교무실·보건실·교사 화장실·후문 홀.",
		"복도를 잇는 방은 몇 곳뿐: C→B 는 볼풀방·구름반(놀이터에서 볼풀방으로 기어가는 터널 q 도), B→A 는 해님반(달님반에서 낮은 통로 q 로도).",
		"살짝 미로: 복도 C 가운데가 쓰러진 사물함으로 막혀 놀이터나 식당을 가로지르고, 복도 A 는 교무실 앞이 무너져 교무실(문 2)·원장실 터널로 돌아간다.",
		"숨는 곳(L)은 어린이 사물함·신발장, 뒤지는 곳(Z)은 장난감 상자. 출구까지 최단 약 150칸.",
	]);
