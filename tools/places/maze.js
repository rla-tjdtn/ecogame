// 챕터 5 심층 미로 — 버려진 지하 채석장 납골당(카타콤)
//   node tools/places/maze.js [--dry] [--print] [--runs N]   (--runs: 배회 흉내까지 전부 재서 level-graph 요약 한 줄을 찍는다)
// 실제 카타콤은 석회암을 캐낸 옛 채석 갱도에 유골을 옮겨 쌓은 곳이다. 갱도는 지층을 따라 비스듬히 뻗고, 휘고, 갈라지고,
//   무너진 곳(붕락)을 돌아가며, 캐낸 자리마다 크고 작은 빈 방(채굴장)이 생긴다. 반듯한 띠나 나선이 아니다.
// 큰 뼈대(갈지자 번개 모양 — 지층이 기울어 갱도층이 세 단으로 비스듬히 내려간다):
//   1단 입구층(북동 → 서): 입구 나선 계단 바닥(시작) → 두 갈래 갱도(북쪽 접근 갱도·작업실 / 우물 갱도·채석공 우물실)
//     → 방주식 채석장(북서, 가장 큰 방: 캐다 남긴 바위 기둥 사이)
//   2단 납골층(서 → 동): 납골당 문 둘(명문 문틀 H) → 두 갈래(납골 회랑 / 지하 예배당 갱) → 해골 원형실(동쪽, 해골 원통 Q·무덤 등불 l)
//   3단 아래 채석층(동 → 남서): 두 갈래(석관 회랑·조각실·석관실 / 붕괴 갱·석재 하치장·운반 갱도) → 수직갱 바닥(남서 끝, 출구)
// 출구 방(수직갱 바닥)은 서로 다른 두 갈래(북쪽 석관실 갱도, 동쪽 운반 갱도)에서 들어온다 — 한 복도에 문 둘이 몰린 깔때기가 아니다.
// 큰 방 사이 갈래 사이는 통짜 바위라 지름길이 없고, 막다른 굴(무너진 옛 갱도·유골 정리 굴·환기 수직갱)에는 숨는 곳만 둔다.
const { Grid, report, writeStage } = require("./lib");

const g = new Grid(47, 43);

// 갱도 파기: 점 사이를 한 칸씩(가로 또는 세로로만) 따라가며 w×w 를 판다. 대각선은 계단처럼 꺾여 비스듬한 갱도가 된다.
//   점에 셋째 값을 주면 그 점부터 폭이 바뀐다(갱도 폭이 1~3칸으로 바뀐다)
function drift(pts, w = 2) {
	let [x, y] = pts[0];
	g.fill(x, y, x + w - 1, y + w - 1);
	for (const [tx, ty, nw] of pts.slice(1)) {
		while (x !== tx || y !== ty) {
			const dx = tx - x, dy = ty - y;
			if (Math.abs(dx) >= Math.abs(dy)) x += Math.sign(dx);
			else y += Math.sign(dy);
			g.fill(x, y, x + w - 1, y + w - 1);
		}
		if (nw) w = nw;
	}
}
// 캐낸 방(채굴장): 네모로 판 뒤 모서리를 k 칸씩 비스듬히 남겨 둥글고 울퉁불퉁하게
//   (이미 판 갱도 칸은 모서리로 다시 막지 않는다 — 갱도가 방 모서리로 들어올 수 있게)
function cave(x0, y0, x1, y1, k = 1) {
	const was = (x, y) => g.get(x, y) !== "#";
	const keep = [];
	for (let d = 0; d < k; d++)
		for (let e = 0; e < k - d; e++) for (const [x, y] of [[x0 + e, y0 + d], [x1 - e, y0 + d], [x0 + e, y1 - d], [x1 - e, y1 - d]]) if (!was(x, y)) keep.push([x, y]);
	g.fill(x0, y0, x1, y1);
	for (const [x, y] of keep) g.set(x, y, "#");
}

// ══════════ 1단 입구층 ══════════
// 입구 나선 계단 바닥(시작): 지상에서 감겨 내려온 나선 계단(I)이 북서 구석. 갈래 둘(서쪽 접근 갱도, 남서쪽 우물 갱도)
g.fill(39, 1, 45, 5).set(45, 5, "#");
g.put("S", [[43, 1], [44, 1], [43, 2], [44, 2]]).set(40, 1, "I").set(45, 4, "L");

// 북쪽 접근 갱도: 지층을 따라 꺾이며 서쪽으로. 갱도 이름 명판(N)
drift([[38, 2], [34, 2], [33, 4], [30, 4], [29, 3]], 2);
g.set(36, 1, "N").set(31, 5, "Z");
// 채석공 작업실(x22~28): 캐낸 석재를 다듬던 곳 — 석재 블록(K) 둘, 손 권양기(W). 갱도가 동·서로 지나간다
cave(22, 1, 28, 5, 1);
g.put("K", [[24, 2], [26, 4]]).set(27, 1, "W").set(23, 5, "Z");
// 작업실 서쪽: 고양이 구멍(1칸 폭 짧은 틈, 카타콤의 좁은 통로) 지나 다시 2칸 갱도로 서쪽 끝까지 → 채석장 북서 입구
drift([[21, 3], [18, 3], [14, 3, 2], [11, 3], [8, 4], [5, 6]], 1);
g.fill(18, 2, 20, 2, "#"); // (고양이 구멍 x18~21, 높이 1칸)
g.set(12, 2, "Z").set(15, 4, "N");
// 무너진 옛 갱도(막다른 굴): 서쪽 끝에서 북쪽으로 들어가다 돌무더기(F)로 막혔다 — 숨는 곳만
g.fill(2, 3, 5, 4).set(2, 3, "F").set(2, 4, "L");

// 우물 갱도: 시작에서 남서로 내려가 채석공 우물실로
drift([[40, 6], [38, 8], [35, 9]], 2);
// 채석공 우물실(x28~34): 채석공이 발을 씻고 물을 긷던 돌계단 우물(Y). 문은 갱도 둘(동·서)
cave(28, 8, 34, 12, 1);
g.put("Y", [[31, 10]]).set(34, 9, "."); g.set(29, 8, "Z").set(33, 12, "L");
// 우물실 서쪽 곧은 옛 갱도는 무너졌다(돌무더기 F 가 막은 짧은 굴) — 갱도는 남쪽으로 휘어 돌아간다
g.fill(25, 9, 27, 9).set(25, 9, "F");
drift([[27, 11], [24, 12], [21, 12], [19, 10], [16, 8], [13, 7]], 2);
g.set(22, 13, "Z").set(19, 9, "N");
// 샛길(갈래 사이 사다리): 우물실 북쪽 천장 틈으로 접근 갱도와 이어진 좁은 오르막
g.fill(30, 6, 30, 7);
// 둘째 샛길: 명판 아래 옛 시추 굴 — 접근 갱도 서쪽과 우물 갱도를 잇는다
g.fill(17, 4, 18, 7);

// ══════════ 방주식 채석장(북서, 가장 큰 방) ══════════
// 돌을 캐다 천장을 받치라고 남겨 둔 바위 기둥(#)이 불규칙하게 서 있고, 쌓은 석조 보강 기둥(B), 석재 블록(K),
// 반출 레일(r)과 광차(R), 손 권양기(W). 입구 넷: 북서(접근 갱도)·북동(우물 갱도)·남동(납골 회랑)·남(예배당 갱)
cave(2, 8, 14, 19, 2);
g.wall(5, 10, 6, 11).wall(10, 11, 11, 12).wall(5, 15, 6, 16).wall(9, 15, 9, 16);
g.put("B", [[8, 13], [12, 16]]).put("K", [[3, 12], [13, 10]]).set(7, 9, "W");
g.fill(3, 18, 8, 18, "r").set(5, 18, "R"); // (반출 레일 끝에 버려진 광차)
g.set(2, 14, "Z").set(14, 14, "Z").set(11, 19, "Z").set(2, 17, "L");

// ══════════ 2단 납골층 ══════════
// 납골당 문(H): 채석장에서 납골층으로 드는 두 입구에 돌 문틀 + "멈춰라, 여기부터 죽음의 제국" 명문 판(밟고 지나간다)
// 납골 회랑: 양쪽 벽에 정강이뼈·해골을 쌓은 뼈 벽면(u). 중간에 넓어진 납골 십자로(뼈 더미 섬 U 둘레로 돈다)
drift([[15, 17], [20, 16], [25, 18], [30, 17], [34, 16], [37, 16], [38, 17]], 2);
g.set(14, 18, ".").put("H", [[15, 17], [15, 18]]);
cave(22, 15, 27, 20, 1); // 납골 십자로
g.put("U", [[24, 17], [25, 17], [24, 18]]);
for (const [x, y] of [[16, 16], [17, 16], [18, 16], [19, 15], [20, 18], [21, 18], [30, 17], [31, 17], [34, 15], [35, 15], [36, 15], [32, 19]]) g.soft(x, y, "u");
g.set(22, 19, "Z").set(27, 16, "Z").set(33, 18, "L");
// 납골 샛길: 십자로 남쪽 뼈 벽 사이로 예배당 갱도까지 내려가는 짧은 굴
g.fill(25, 21, 26, 22);

// 지하 예배당 갱: 채석장 남쪽 문 → 짧은 갱 → 지하 예배당(x12~20, y22~27): 신도석(P) 두 줄 사이 가운데 통로, 동쪽 벽 제단(J)
drift([[9, 20], [10, 22]], 2);
g.put("H", [[9, 20], [10, 20]]);
cave(12, 22, 20, 27, 1);
g.put("P", [[14, 23], [15, 23], [17, 23], [18, 23], [14, 25], [15, 25], [17, 25], [18, 25]]).set(20, 24, "J");
g.set(20, 26, "Z").set(16, 27, "Z").set(19, 22, "L");
// 유골 정리 굴(막다른 굴): 옮겨 온 뼈를 가려 쌓던 곳 — 뼈 더미(U), 숨는 곳
g.fill(3, 22, 8, 23).put("U", [[5, 22], [7, 23]]).set(3, 22, "L");
// 예배당 동쪽 갱도 → 해골 원형실 서쪽
drift([[21, 23], [25, 23], [28, 22], [32, 23], [35, 23]], 2);
g.set(27, 22, "Z").set(30, 24, "N");

// 해골 원형실(동쪽, x36~44): 납골당 한가운데 둥근 방 — 가운데 해골 원통(Q)과 무덤 등불(l, 공기를 돌리던 불 그릇), 둘레 뼈 더미(U)
cave(36, 18, 44, 27, 2);
g.put("Q", [[40, 21]]).set(40, 24, "l").put("U", [[38, 20], [42, 20], [38, 25], [42, 25]]);
for (const [x, y] of [[39, 18], [41, 18], [36, 23], [36, 25], [44, 24], [39, 27]]) g.soft(x, y, "u"); // (둘레 벽 뼈 벽면)
g.set(44, 22, "Z").set(36, 21, "Z").set(43, 26, "Z");
// 환기 수직갱(막다른 굴): 원형실 북쪽에서 좁게 올라가다 끝에 숨는 곳
g.fill(43, 13, 43, 18).set(43, 13, "L");

// ══════════ 3단 아래 채석층 ══════════
// 석관 회랑: 원형실 남서에서 서쪽으로 → 채석공 조각실(옛 채석공이 벽에 새긴 요새 부조 M) → 석관실 → 수직갱 바닥 북쪽
drift([[38, 27], [36, 28], [31, 29], [26, 30], [21, 31], [19, 31]], 2);
cave(24, 28, 29, 32, 1);
g.set(26, 28, "M").set(29, 31, "Z").set(24, 32, "L");
// 석재 내림 굴: 조각실 남쪽에서 석재 하치장으로 돌을 굴려 내리던 경사 굴(갈래 사이 샛길)
g.fill(26, 33, 27, 35);
// 석관실(x13~19, y30~33): 돌 석관(V) 둘
g.fill(13, 30, 19, 33).put("V", [[15, 31], [17, 31]]).set(13, 33, "Z").set(19, 30, "Z");
drift([[12, 32], [8, 33], [6, 34]], 2);

// 붕괴 갱(x31~44, y31~37): 바닥이 꺼져 아래 채석층(구덩이 p)이 드러났다. 둘레 턱, 가운데 나무 다리(b), 구석 돌계단(s)
drift([[41, 28], [41, 29]], 2);
g.fill(31, 31, 44, 37).fill(33, 32, 42, 36, "p").fill(33, 34, 42, 34, "b");
g.put("s", [[36, 32], [40, 32], [36, 36], [40, 36]]); // (턱 벽에 붙여 북쪽 구덩이 둘·남쪽 구덩이 둘)
g.set(44, 31, "Z").set(31, 37, "Z");
// 배수 굴(막다른 굴): 붕괴 갱 남동 구석에서 내려가는 물 빠짐 굴 — 끝에 숨는 곳
g.fill(43, 38, 44, 40).set(44, 40, "L");
// 석재 하치장(x17~26, y36~41): 반출을 기다리는 석재 더미(K)와 광차(R), 운반 레일(r)이 서쪽 수직갱으로
drift([[30, 35], [27, 37]], 2);
g.fill(17, 36, 26, 41);
g.put("K", [[19, 37], [20, 37], [24, 37]]).set(26, 41, "Z").set(17, 36, "Z");
drift([[16, 39], [11, 39]], 2); // 운반 갱도
g.fill(11, 40, 25, 40, "r").set(22, 40, "R");

// 수직갱 바닥(남서 끝, 출구): 옛 수직갱의 권양탑 다리(G), 손 권양기(W), 고인 물을 퍼내던 양수 펌프(m)·배관(v).
// 서쪽 벽 오목한 곳에 케이지 승강기(출구 E). 입구 둘: 북쪽(석관실 갱도)·동쪽(운반 갱도)
cave(2, 35, 10, 41, 1);
g.fill(4, 40, 10, 40, "r");
g.set(1, 38, "E").put("G", [[2, 36], [2, 40]]).set(9, 36, "m").set(10, 37, "v").set(6, 41, "W");
g.set(10, 41, "Z").set(6, 35, "#").set(3, 41, "L");

// 납골 갱도 벽 뼈 벽면(u): 납골 회랑·예배당 동쪽 갱도의 벽 쪽 칸에 한 칸 걸러 — 갱도가 납골당으로 읽히게(다른 층에는 없다)
for (const [x0, y0, x1, y1] of [[16, 15, 37, 19], [21, 22, 35, 24]])
	for (let y = y0; y <= y1; y++)
		for (let x = x0; x <= x1; x++)
			if ((x + y) % 2 === 0 && g.get(x, y) === "." && (g.get(x, y - 1) === "#" || g.get(x, y + 1) === "#") && !(x >= 22 && x <= 27 && y <= 20)) g.set(x, y, "u");

const opts = { blocked: ["B", "U", "Q", "K", "W", "R", "Y", "P", "J", "G", "I", "V", "F", "l", "M"], walkable: ["r", "u", "N", "H"] };
const r = report("심층 미로(카타콤)", g, opts);
if (process.argv.includes("--print")) console.log(g.rows().map((row, i) => String(i).padStart(2) + " " + row).join("\n"));
// 머리 주석의 길이는 그래프 검사기(level-graph)와 같은 규칙으로 잰다
const { analyzeStage, summary } = require("../level-graph");
const runsArg = process.argv.indexOf("--runs");
const full = runsArg >= 0;
const LG = analyzeStage(5, { st: { rows: g.rows(), rows2: null, upper: [], pits: new Set(["p", "b", "s", "n"]), walk: opts.walkable }, quick: !full, runs: full ? +process.argv[runsArg + 1] : 200 });
if (full) { console.log(summary(LG)); for (const f of LG.fails) console.log("   ✗ " + f); for (const w of LG.warn) console.log("   · " + w); }
if (!process.argv.includes("--dry"))
	writeStage("Stage5.luau", g, [
		"STAGE 5 — 심층 미로 (47x43칸, tools/places/maze.js 로 생성, 소품은 ChapterProps/Maze.luau)",
		"버려진 지하 채석장 납골당(카타콤). 지층을 따라 비스듬히 뻗고 휘고 갈라지는 갱도 — 세 단이 갈지자로 내려간다.",
		"1단 입구층: 나선 계단(I) 바닥(시작) → 북쪽 접근 갱도·채석공 작업실·고양이 구멍 / 우물 갱도·채석공 우물실(Y)·붕락(F) 우회 → 방주식 채석장(바위 기둥, B·K·W·광차).",
		"2단 납골층: 납골당 문틀 H 둘 → 납골 회랑(뼈 벽면 u, 납골 십자로 U·Q) / 지하 예배당(신도석 P, 제단 J) → 해골 원형실(해골 원통 Q, 무덤 등불 l).",
		"3단 아래 채석층: 석관 회랑·채석공 조각실(M)·석관실(V) / 붕괴 갱(구덩이 p, 나무 다리 b, 돌계단 s)·석재 하치장·운반 갱도(레일 r) → 수직갱 바닥(권양탑 G, 펌프 m).",
		"출구(케이지 승강기)는 남서 끝 수직갱 바닥 서쪽 벽. 출구 방 입구는 서로 다른 갈래 둘(북쪽 석관실 갱도, 동쪽 운반 갱도).",
		"막다른 굴(무너진 옛 갱도·유골 정리 굴·환기 수직갱)에는 숨는 곳(L)만, 뒤지는 곳(Z)은 갈래 벽과 입구 둘 이상인 방에만.",
		`출구까지 최단 약 ${LG.exitLen}칸, 뒤지는 곳 ${LG.searchSpots}곳.`,
	]);
module.exports = { g };
