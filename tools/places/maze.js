// 챕터 5 심층 미로 — 버려진 지하 채석장 납골당(카타콤): 석회암을 캐낸 옛 채석 갱도에 도시의 유골을 옮겨 쌓은 곳.
//   node tools/places/maze.js [--dry] [--print]
// 실제 카타콤의 동선: 지상에서 나선 계단으로 내려온 입구 계단실 → 검표소 → 채석 작업장·갱부 대기실·채석공 우물(위 갱도층) →
//   납골 회랑(뼈 더미 벽, 해골 원통) → 아래 채석층(주 운반 갱도·붕괴 갱·석재 하치장·양수 펌프실) →
//   서쪽 배수 갱·유골 정리실·석관실 → 미로의 심장(지하 예배당) → 옛 수직갱 승강장(출구, 케이지 승강기).
// 큰 흐름은 안쪽으로 감기는 나선(시계 방향 3/4 바퀴): 위 띠 동쪽으로 → 동쪽 띠 남쪽으로 → 아래 띠 서쪽으로 → 서쪽 띠에서 심장으로.
// 띠마다 길이 두 갈래(갱도 + 문 2개 이상인 방 사슬)이고 가로 샛길이 자주 있어 한 곳이 막혀도 돌아간다(목 0).
// 심장(x10~35, y11~29)은 서쪽 띠에서만 들어간다: 시작 계단실 바로 아래에 있지만 미로를 한 바퀴 돌아야 닿는다.
const { Grid, report, writeStage } = require("./lib");

const g = new Grid(47, 43);

// ══════════ 위 띠(y1~9): 입구층 ══════════
// 입구 계단실(시작): 지상에서 내려오는 나선 계단(I)이 북동 구석, 갱도·검표소로 문 둘
g.fill(1, 1, 5, 5).put("S", [[1, 1], [2, 1], [1, 2], [2, 2]]).set(5, 1, "I");
g.set(6, 2, "D").set(6, 5, "D"); // (두 문은 세 칸 떨어뜨려 괴물 하나가 둘 다 막지 못하게)
g.set(1, 5, "L"); // (계단실 구석 벽장)

// 위 갱도(2칸 폭): 세 토막이 한 칸씩 어긋나며 동쪽으로(채석 갱도의 꺾임)
g.fill(7, 1, 18, 2).fill(17, 2, 30, 3).fill(29, 1, 43, 2);
g.put("B", [[24, 3]]); // (갱도 천장을 받치는 석조 보강 기둥 — 벽 쪽 반 칸에 붙여 세운다)
g.set(12, 1, "Z"); // (갱도 북쪽 벽 궤짝)

// 검표소(x7~11, y4~8): 매표 책상·서류장, 문 셋(계단실·갱도·작업장)
g.fill(7, 4, 11, 8).set(9, 3, "D").set(12, 6, "D");
g.put("T", [[9, 6]]).put("k", [[11, 4]]).set(7, 8, "Z").set(11, 8, "L");

// 채석 작업장(x13~26, y5~9): 잘라 낸 석재 블록(K), 손 권양기(W), 레일 위 광차(R). 문: 검표소·갱도(아치)·대기실
g.fill(13, 5, 26, 9).set(21, 4, "A").set(27, 7, "D");
g.put("K", [[15, 8], [16, 8], [19, 6], [24, 9]]).put("W", [[25, 5]]).put("R", [[18, 9]]);
g.set(13, 9, "Z").set(26, 9, "Z");

// 갱부 대기실(x28~34, y5~9): 나무 탁자·사물함. 문: 작업장·갱도(아치)·우물실
g.fill(28, 5, 34, 9).set(30, 4, "A").set(35, 7, "D");
g.put("T", [[31, 7]]).put("L", [[34, 5], [28, 9]]).put("c", [[34, 9]]);

// 채석공 우물실(x36~42, y4~9): 돌계단으로 물까지 내려가는 우물(Y), 문: 대기실·갱도·동쪽 갱도·납골 회랑(아치)
g.fill(36, 4, 42, 9).set(40, 3, "D").set(43, 7, "D").set(39, 10, "A");
g.put("Y", [[38, 6], [39, 6]]).set(42, 4, "Z");

// ══════════ 동쪽 띠(x37~45, y10~33): 납골당 ══════════
// 동쪽 갱도(x44~45): 위 갱도에서 아래 채석층까지 내려가는 2칸 폭 갱도, 군데군데 벽감(숨는 벽장)
g.fill(44, 1, 45, 41); // (붕괴 갱 동쪽 턱까지 그대로 내려간다)
g.set(45, 18, "L").set(44, 29, "Z").set(45, 10, "Z");

// 납골 회랑(x37~42, y11~29): 가운데 뼈 더미 벽(U) 두 섬이 통로를 둘로 가르고, 그 사이 해골 원통(Q)이 랜드마크
g.fill(37, 11, 42, 29);
for (let y = 13; y <= 17; y++) g.put("U", [[39, y], [40, y]]);
for (let y = 22; y <= 27; y++) g.put("U", [[39, y], [40, y]]);
g.put("Q", [[39, 19]]);
for (const y of [12, 13, 14, 16, 17, 18, 21, 22, 23, 26, 27, 28]) g.soft(37, y, "u").soft(42, y, "u"); // (양쪽 벽에 붙여 쌓은 얇은 뼈 벽면 — 밟을 수 있는 벽 장식)
g.set(43, 14, "D").set(43, 25, "D").set(39, 30, "A");
g.set(37, 11, "Z").set(42, 29, "Z").set(37, 24, "L");

// ══════════ 아래 띠(y31~41): 아래 채석층 ══════════
// 주 운반 갱도(x3~43, y31~33, 3칸 폭): 가운데 줄에 광차 레일(r, 밟고 지나간다), 벽에 붙여 세운 석조 보강 기둥(B)이 남·북으로 번갈아
g.fill(3, 31, 43, 33);
for (let x = 4; x <= 43; x++) g.set(x, 32, "r");
for (const [x, y] of [[11, 31], [18, 33], [25, 31], [32, 33], [40, 31]]) g.set(x, y, "B");
g.put("N", [[4, 33], [45, 3], [17, 1]]); // (갱도 이름을 새긴 벽 명판 — 벽에 붙은 얇은 판이라 밟고 지나간다)
g.set(22, 31, "Z").set(36, 33, "Z");

// 붕괴 갱(x29~43, y35~41): 바닥이 꺼져 아래 채석층(구덩이)이 드러났다. 북쪽 턱·남쪽 턱, 가운데 나무 다리(b),
//   다리 북쪽·남쪽 구덩이 바닥으로는 양 끝 돌계단(s)으로 내려간다(구덩이 바닥도 동서로 건너는 길)
g.fill(29, 35, 43, 41);
g.fill(30, 36, 42, 40, "p");
for (let x = 30; x <= 42; x++) g.set(x, 38, "b");
g.put("s", [[31, 36], [41, 36], [31, 40], [41, 40]]); // (다리 북쪽·남쪽 구덩이마다 양 끝 돌계단 두 곳)
g.set(31, 34, "A").set(41, 34, "A").set(28, 38, "D");
g.set(45, 41, "Z").set(29, 35, "L");

// 석재 하치장(x15~27, y35~41): 반출을 기다리는 석재 더미(K)와 광차(R)
g.fill(15, 35, 27, 41).set(21, 34, "A").set(14, 38, "D");
g.put("K", [[17, 37], [18, 37], [17, 40], [24, 37], [25, 37], [24, 40]]).put("R", [[21, 39]]);
g.set(27, 41, "Z").set(15, 35, "c");

// 양수 펌프실(x1~13, y35~41): 고인 물을 퍼 올리는 펌프(m)·배관(v), 서쪽 배수 갱과 이어진다
g.fill(1, 35, 13, 41).set(8, 34, "A");
g.put("m", [[5, 38], [9, 38]]).put("v", [[13, 41]]).set(1, 41, "Z").set(13, 35, "L");

// ══════════ 서쪽 띠(x1~8, y11~34): 배수 갱·유골 정리실·석관실 ══════════
g.fill(1, 11, 2, 34); // 서쪽 배수 갱(2칸 폭)
g.set(1, 11, "L");
// 유골 정리실(x4~8, y12~19): 옮겨 온 뼈를 가려 쌓던 작업대(T)
g.fill(4, 12, 8, 19).set(3, 15, "D").set(9, 14, "D");
g.put("T", [[6, 16]]).put("U", [[4, 19], [5, 19]]).set(8, 12, "Z");
// 석관실(x4~8, y21~29): 석관(V) 두 기, 문: 배수 갱·예배당·운반 갱도
g.fill(4, 21, 8, 29).set(3, 26, "D").set(9, 25, "D").set(6, 30, "A");
g.put("V", [[5, 23], [7, 23], [5, 27]]).set(8, 29, "Z");

// ══════════ 심장(x10~35, y11~29): 지하 예배당 · 수직갱 승강장 ══════════
// 지하 예배당(x10~22, y12~28): 신도석(P) 두 줄 사이 가운데 통로, 동쪽 끝 제단(J)
g.fill(10, 12, 22, 28);
for (const y of [15, 17, 19, 23, 25]) for (const x of [12, 13, 14, 17, 18, 19]) g.set(x, y, "P");
g.put("J", [[22, 20]]).set(10, 28, "Z").set(22, 12, "L");
g.set(23, 15, "D").set(23, 25, "D");
g.set(14, 29, ".").set(14, 30, "A"); // (예배당 남쪽 벽이 무너져 운반 갱도와 이어진 틈 — 심장으로 드는 셋째 입구)
// 수직갱 승강장(x24~34, y12~28): 옛 권양탑(G)과 권양기(W), 동쪽 벽 오목한 곳에 케이지 승강기(출구)
g.fill(24, 12, 34, 28);
g.put("G", [[28, 19], [28, 21]]).put("W", [[25, 13]]).put("K", [[33, 27]]);
g.set(35, 20, "E");
g.set(34, 12, "Z");

const opts = { blocked: ["B", "U", "Q", "K", "W", "R", "Y", "P", "J", "G", "I", "V", "T", "k"], walkable: ["r", "u", "N"] };
const r = report("심층 미로(카타콤)", g, opts);
if (process.argv.includes("--print")) console.log(g.rows().map((row, i) => String(i).padStart(2) + " " + row).join("\n"));
// 머리 주석의 길이는 그래프 검사기(level-graph)와 같은 규칙으로 잰다(벽 상자 c·배관 v 는 지나갈 수 있는 것으로)
const { analyzeStage } = require("../level-graph");
const LG = analyzeStage(5, { st: { rows: g.rows(), rows2: null, upper: [], pits: new Set(["p", "b", "s", "n"]), walk: opts.walkable }, quick: true });
if (!process.argv.includes("--dry"))
	writeStage("Stage5.luau", g, [
		"STAGE 5 — 심층 미로 (47x43칸, tools/places/maze.js 로 생성, 소품은 ChapterProps/Maze.luau)",
		"버려진 지하 채석장 납골당(카타콤): 석회암을 캐낸 옛 갱도에 유골을 옮겨 쌓은 곳. 안쪽으로 감기는 나선(시계 방향 3/4 바퀴)으로 깊어진다.",
		"위 띠(입구층): 나선 계단(I)이 내려오는 입구 계단실(시작) → 2칸 폭 위 갱도 / 검표소·채석 작업장(석재 K·권양기 W·광차 R)·갱부 대기실·채석공 우물실(Y).",
		"동쪽 띠(납골당): 2칸 폭 동쪽 갱도 / 납골 회랑(뼈 더미 벽 U 두 섬, 벽면 뼈 u, 가운데 해골 원통 Q).",
		"아래 띠(아래 채석층): 3칸 폭 주 운반 갱도(광차 레일 r, 벽에 붙은 석조 보강 기둥 B) / 붕괴 갱(구덩이 p, 나무 다리 b, 돌계단 s)·석재 하치장·양수 펌프실(m).",
		"서쪽 띠: 2칸 폭 배수 갱 / 유골 정리실·석관실(V). 심장(가운데): 지하 예배당(신도석 P, 제단 J) → 수직갱 승강장(권양탑 G, 동쪽 벽 케이지 승강기 = 출구).",
		"심장은 서쪽 띠의 두 문과 예배당 남쪽 무너진 틈(운반 갱도)으로만 들어간다. 시작 계단실 바로 아래지만 미로를 돌아야 닿는다.",
		`띠마다 갱도 + 문 2개 이상인 방 사슬 두 갈래라 괴물 하나로 끊기는 목이 없다. 출구까지 최단 약 ${LG.exitLen}칸, 뒤지는 곳 ${LG.searchSpots}곳.`,
	]);
