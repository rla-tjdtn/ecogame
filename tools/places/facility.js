// 챕터 1 지하 시설: 경비 초소·출입 통제 구역에서 시작해 시설을 시계 방향으로 한 바퀴 감아 돌고(동 → 남 → 서 → 북),
// 마지막에 봉인된 가운데 기계 구역의 화물 엘리베이터(출구)로 들어간다.  node tools/places/facility.js [--dry] [--print]
// 왼쪽 위(경비 초소 3x3, 문 하나 너머 기둥 2개가 선 검문 홀, 아래 탈의실, y9 출입 복도, 장비 정비실의 y15 줄)는
// 자동 테스트(TestHarness)가 타일 좌표로 쓰는 자리라 모양을 그대로 둔다.
// 구간마다 길이 두세 갈래(복도 + 문 2개 이상인 방 사슬)라 한 곳이 막혀도 돌아갈 수 있다(목 0).
const { Grid, report, writeStage } = require("./lib");

const g = new Grid(47, 43);

// ══ 출입 통제 구역(왼쪽 위, 테스트 자리) ══
// 경비 초소(시작, 3x3 안전 구역)
g.fill(1, 1, 3, 3).put("S", [[1, 1], [2, 1], [1, 2], [2, 2]]).set(4, 2, "D").set(2, 4, "A");
// 검문 홀(차단 기둥 2개) → 동쪽 아치로 통제실, 남쪽 아치로 보안 사무실
g.fill(5, 1, 11, 3).put("O", [[7, 2], [9, 2]]).set(12, 2, "A").set(6, 4, "A");
// 탈의실(사물함) → 출입 복도
g.fill(1, 5, 3, 7).set(2, 8, "D").put("L", [[3, 5], [3, 7]]);
// 보안 사무실(책상) → 출입 복도
g.fill(5, 5, 11, 7).set(9, 8, "D");
g.put("T", [[7, 6], [9, 6]]).set(11, 5, "Z").set(5, 7, "L").set(11, 7, "c");
// 출입 복도(1칸, 곧게) → 본 복도
g.fill(1, 9, 8, 9);

// ══ 1구간(위, 동쪽으로): 통제실·기록 보관실·장비실·환기 설비실이 옆문으로 이어진 방 사슬 + 본 복도 ══
// 통제실(문 3곳: 검문 홀 아치, 본 복도, 기록 보관실 옆문): 북쪽 벽 상황판(W, 대형 화면) 을 향해 통제 콘솔(k) 두 줄.
// 콘솔 사이(짝수 열)는 비워 두어 줄 사이로 걸어 다닌다. (본 복도 쪽 둘째 문은 뺐다 — 길이 너무 많았다)
g.fill(13, 1, 22, 7).set(15, 8, "D").set(23, 2, "D");
g.put("W", [[16, 1], [18, 1], [20, 1]]);
g.put("k", [[15, 3], [17, 3], [19, 3], [21, 3], [15, 5], [17, 5], [19, 5], [21, 5]]);
g.set(13, 7, "L").set(22, 7, "Z").set(18, 6, "f");
// 기록 보관실(문 4곳): 양면 서류 캐비닛(F) 두 줄이 남북으로 선 서고
g.fill(24, 1, 30, 7).set(25, 8, "D").set(29, 8, "D").set(31, 2, "D");
g.put("F", [[26, 2], [26, 3], [26, 4], [28, 2], [28, 3], [28, 4], [26, 6], [28, 6]]).set(30, 7, "Z").set(24, 1, "L").set(27, 5, "f");
// 전기실(문 3곳: 기록 보관실 옆문, 본 복도, 공조실 옆문): 북쪽 벽에 고압 배전반(P) 넷
g.fill(32, 1, 38, 7).set(33, 8, "D").set(39, 6, "D");
g.put("P", [[33, 1], [34, 1], [37, 1], [38, 1]]).set(38, 3, "Z").set(32, 7, "L").set(35, 4, "c");
// 공조실(문 2곳: 전기실 옆문, 본 복도 끝): 천장 큰 환풍기 + 북쪽 벽 공조기(Y, 둥근 송풍기 둘 + 덕트)
g.fill(40, 1, 45, 7).set(43, 8, "D");
g.put("f", [[42, 3]]).set(44, 1, "Y").set(45, 1, "y").put("v", [[40, 1], [40, 2]]).set(45, 7, "Z").set(40, 7, "L");

// ══ 본 복도 C1 (y9~10): 기록 보관실 앞 천장이 무너져 방으로 돌아간다 ══
g.fill(9, 9, 44, 10);
g.wall(26, 9, 27, 10).put("c", [[25, 10], [28, 9]]);

// ══ 2구간(동쪽, 남쪽으로): 발전기 홀 → 냉각 배관 구역, 나란히 동쪽 비상 복도 C3 ══
// 동쪽 비상 복도 C3 (x42~43): 본 복도 끝에서 아래 복도까지 곧게, 옆에 대피 칸
g.fill(42, 11, 43, 37);
g.fill(44, 17, 45, 19).set(45, 17, "L").set(45, 19, "c"); // 대피 칸
g.fill(44, 29, 45, 31).set(45, 31, "Z").set(45, 29, "c");
g.set(43, 24, "c").set(42, 33, "v");
// 발전기 홀(가장 큰 공간): 비상 발전기(G, 2x2) 넷, 콘크리트 기둥, 배관(문 3곳: 본 복도, C3, 냉각 구역)
g.fill(30, 12, 40, 24).set(32, 11, "D").set(41, 21, "D");
g.put("#", [[33, 16], [37, 16], [33, 21], [37, 21]]);
for (const [x, y] of [[31, 13], [35, 13], [31, 18], [38, 18]]) g.put("g", [[x + 1, y], [x, y + 1], [x + 1, y + 1]]).set(x, y, "G");
g.put("v", [[30, 24], [40, 12], [40, 13], [30, 12]]).put("f", [[35, 19]]).set(40, 24, "Z").set(30, 16, "Z").set(36, 24, "L"); // (서쪽 벽 공구 서랍장)
g.set(32, 25, "D").set(32, 26, ".");
// 냉각 배관 구역: 냉각수 배관 선반(U)이 줄지어 선 좁은 통로(살짝 미로) — 문 4곳
g.fill(30, 27, 40, 36).set(41, 31, "D").set(36, 37, "D").set(28, 35, "D").set(29, 35, ".");
g.fill(32, 29, 38, 29, "U").set(35, 29, "v"); // 배관 선반(가운데 틈)
g.fill(30, 32, 33, 32, "U").fill(35, 32, 40, 32, "U"); // 배관 선반(틈 x34)
g.fill(32, 34, 38, 34, "U").set(33, 34, "v"); // 배관 선반(틈 x33)
g.put("v", [[30, 27], [40, 27], [30, 30], [40, 33], [30, 36], [36, 31]]);
g.set(40, 28, "Z").set(30, 33, "L").set(38, 36, "Z").set(40, 36, "c");

// ══ 3구간(아래, 서쪽으로): 구덩이 작업장·창고, 나란히 아래 복도 C4 ══
// 아래 복도 C4 (y38~39): 동쪽 C3 에서 서쪽 정비 통로까지
g.fill(2, 38, 43, 39);
g.put("c", [[16, 38], [33, 38]]).set(25, 40, "L").set(30, 40, "Z").set(1, 39, "c");
// 구덩이 작업장(두 번째 큰 공간): 가운데 정비 구덩이 위로 다리, 구덩이 계단, 크레인 기둥(문 4곳)
g.fill(15, 24, 27, 36).set(19, 37, "D").set(25, 37, "D").set(24, 23, "D");
g.fill(18, 27, 24, 32, "p");
g.fill(18, 29, 24, 29, "b"); // 다리(가로)
g.set(18, 32, "s").set(21, 27, "s"); // 구덩이 계단(다리 남쪽·북쪽 하나씩)
g.put("#", [[17, 26], [25, 26], [17, 34], [25, 34], [21, 25]]);
g.put("m", [[15, 24], [16, 24]]).put("j", [[26, 36], [27, 36]]).put("v", [[27, 24], [15, 36]]).set(27, 32, "L").set(15, 31, "Z").set(27, 28, "Z").set(22, 35, "c");
// 작업장 남쪽은 벽으로 갈라 자재 복도(y34~36): 아래 복도·냉각 구역·창고를 잇는 두 번째 길
g.wall(15, 33, 27, 33);
// 창고(선반 줄, 문 5곳: 서쪽 정비 통로, 작업장 2, 아래 복도, 북쪽 정비 통로)
g.fill(5, 25, 12, 36).set(4, 30, "D").set(13, 29, "D").set(14, 29, ".").set(13, 35, "D").set(14, 35, ".").set(8, 37, "D").set(6, 24, "D");
for (const y of [28, 31, 34]) g.fill(7, y, 10, y, "R"); // 철제 선반 줄
g.put("c", [[5, 25], [12, 25], [12, 36], [5, 35]]).set(12, 30, "Z").set(5, 29, "L").set(5, 36, "Z").set(11, 26, "c");

// ══ 4구간(서쪽, 북쪽으로): 서쪽 정비 통로 W1 과 정비 통로 C2, 장비 정비실 ══
// 서쪽 정비 통로 W1(1칸, 아치): 위쪽은 무너져 막혔고(출입 복도에서 바로 못 내려간다) 아래 복도까지
g.fill(3, 11, 3, 38).set(3, 10, "A").set(2, 13, "Z");
g.put("A", [[3, 14], [3, 28], [3, 34]]).set(3, 21, "#"); // (y21 에서 무너져 위·아래가 끊겼다)
g.fill(1, 24, 2, 26).set(1, 24, "L").set(1, 26, "c"); // (통로 옆 대피 칸)
// 정비 통로 C2(1칸): W1 → 창고 북문 → 기계실 남문, 중간에 장비 정비실 남문으로 올라가는 가지
g.fill(4, 22, 27, 22).fill(6, 23, 6, 23);
g.set(17, 22, "A").set(8, 22, "A");
g.fill(13, 19, 15, 20).set(14, 21, "A"); // (통로 옆 배전함 칸: 막다른 곳 — 열쇠 상자는 두지 않는다)
g.put("P", [[13, 19], [14, 19], [15, 19]]);
// 장비 정비실(문 3개): y15 줄은 비워 둔다(테스트: 괴물이 걸어가는 줄)
g.fill(5, 12, 15, 17).set(4, 15, "D").set(12, 11, "D");
g.put("j", [[7, 12], [9, 12], [11, 12]]).put("m", [[5, 17], [6, 17], [14, 17]]).set(15, 12, "Z").set(5, 12, "L").set(12, 17, "c");

// ══ 마지막: 봉인된 가운데 기계실 → 화물 엘리베이터(출구) ══
// 기계실: 기계 줄, 콘크리트 기둥(문 3곳: 장비 정비실, 정비 통로 C2 둘). 북쪽 본 복도·동쪽 발전기 홀과는 벽으로 막혔다
g.fill(17, 12, 27, 20).set(20, 21, "D").set(26, 21, "D");
g.put("#", [[20, 16], [24, 16]]);
g.put("m", [[18, 14], [19, 14], [23, 13], [24, 13], [18, 19], [19, 19], [25, 19]]).put("v", [[27, 20], [17, 20]]);
g.set(17, 17, "L").set(22, 17, "f");
// 화물 엘리베이터 홀(기계실 동북 구석) → 출구
g.put("v", [[27, 15], [26, 16]]);
g.put("h", [[26, 13], [27, 13], [27, 14]]).set(28, 13, "E").set(27, 12, "Z").set(25, 14, "v");

if (process.argv.includes("--print")) console.log(g.rows().map((row, i) => String(i).padStart(2) + " " + row).join(String.fromCharCode(10)));
const opts = { blocked: ["T", "k", "F", "G", "g", "P", "U", "j", "Y", "y", "R"] };
const r = report("지하 시설", g, opts);
