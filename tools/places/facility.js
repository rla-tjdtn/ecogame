// 챕터 1 지하 시설: 경비 초소·출입 통제 구역에서 시작해 통제실 → 본 복도 → 발전기 홀·기계실 → 서쪽 정비 통로 →
// 창고·구덩이 작업장·냉각 배관 구역 → 화물 엘리베이터(출구).  node tools/places/facility.js [--dry] [--print]
// 왼쪽 위(경비 초소 3x3, 문 하나 너머 기둥 2개가 선 검문 홀, 아래 탈의실, y9 출입 복도, 장비 정비실의 y15 줄)는
// 자동 테스트(TestHarness)가 타일 좌표로 쓰는 자리라 모양을 그대로 둔다.
// 띠 세 줄: 위 띠(동쪽으로) → 가운데 띠(서쪽으로) → 아래 띠(동쪽으로). 띠마다 갈래 길이 둘 이상이다.
const { Grid, report, writeStage } = require("./lib");

const g = new Grid(47, 43);

// ══ 출입 통제 구역(왼쪽 위, 테스트 자리) ══
// 경비 초소(시작, 3x3 안전 구역)
g.fill(1, 1, 3, 3).put("S", [[1, 1], [2, 1], [1, 2], [2, 2]]).set(4, 2, "D").set(2, 4, "A");
// 검문 홀(차단 기둥 2개) → 동쪽 아치로 통제실, 남쪽 아치로 보안 사무실
g.fill(5, 1, 11, 3).put("O", [[7, 2], [9, 2]]).set(12, 2, "A").set(6, 4, "A");
// 탈의실(사물함) → 출입 복도
g.fill(1, 5, 3, 7).set(2, 8, "D").put("L", [[3, 5], [3, 7]]);
// 보안 사무실(책상) → 출입 복도
g.fill(5, 5, 11, 7).set(9, 8, "D");
g.put("T", [[7, 6], [9, 6]]).set(11, 5, "Z").set(5, 7, "L").set(11, 7, "c");
// 출입 복도(1칸, 곧게) → 본 복도
g.fill(1, 9, 8, 9);

// ══ 위 띠: 통제실·기록 보관실·장비실·환기 설비실 ══
// 통제실: 모니터 책상 두 줄(문 3곳: 검문 홀 아치, 본 복도 2곳)
g.fill(13, 1, 22, 7).set(15, 8, "D").set(20, 8, "D");
g.put("T", [[14, 1], [16, 1], [18, 1], [20, 1], [22, 1], [15, 4], [17, 4], [19, 4], [21, 4]]);
g.set(13, 7, "L").set(22, 7, "Z").set(18, 6, "f");
// 기록 보관실(문 2개: 무너진 본 복도를 돌아가는 길): 서류 캐비닛 줄
g.fill(24, 1, 30, 7).set(25, 8, "D").set(29, 8, "D");
g.put("c", [[26, 2], [26, 3], [26, 5], [28, 2], [28, 3], [28, 5]]).set(30, 1, "Z").set(24, 1, "L").set(27, 4, "f");
// 장비실(문 2개)
g.fill(32, 1, 38, 7).set(33, 8, "D").set(37, 8, "D");
g.put("m", [[32, 1], [33, 1], [37, 1], [38, 1]]).set(38, 4, "Z").set(32, 4, "L").set(35, 3, "c");
// 환기 설비실(막다른 방): 큰 환풍기
g.fill(40, 1, 45, 7).set(42, 8, "D");
g.put("f", [[42, 3]]).put("m", [[45, 1], [44, 1]]).put("v", [[40, 1], [40, 2]]).set(45, 7, "Z").set(40, 7, "L");

// ══ 본 복도 C1 (y9~10) ══
g.fill(9, 9, 43, 10);
g.wall(26, 9, 27, 10).put("c", [[25, 10], [28, 9]]); // 무너진 천장(기록 보관실로 돌아간다)

// ══ 가운데 띠 ══
// 동쪽 비상 복도 C3 (x42~43): 본 복도 → 발전기 홀 동쪽 문, 아래는 막혔다
g.fill(42, 11, 43, 24);
g.set(44, 15, "L").set(42, 23, "c").set(42, 24, "Z");
// 발전기 홀(가장 큰 공간): 발전기 2x2 넷, 콘크리트 기둥, 배관(문 5곳)
g.fill(29, 12, 40, 24).set(31, 11, "D").set(38, 11, "D").set(41, 20, "D").set(28, 17, "D").set(28, 22, "D");
g.put("#", [[32, 16], [37, 16], [32, 21], [37, 21]]);
for (const [x, y] of [[30, 13], [35, 13], [30, 18], [38, 18]]) g.put("m", [[x, y], [x + 1, y], [x, y + 1], [x + 1, y + 1]]);
g.put("v", [[29, 24], [40, 12], [40, 13], [29, 12]]).put("f", [[34, 18]]).set(40, 24, "Z").set(35, 24, "L");
// 기계실: 기계 줄, 콘크리트 기둥(문 3곳)
g.fill(17, 12, 27, 20).set(16, 14, "D").set(22, 21, "D");
g.put("#", [[20, 16], [24, 16]]);
g.put("m", [[18, 13], [19, 13], [23, 13], [24, 13], [18, 19], [19, 19], [25, 19], [26, 19]]).put("v", [[27, 12], [27, 13], [17, 20]]);
g.set(27, 20, "Z").set(17, 16, "L").set(22, 17, "f");
// 정비 통로 C2(1칸, 아치): 발전기 홀 남서 문 → 기계실 아래 → 장비 정비실 남쪽 문
g.fill(10, 22, 27, 22).fill(10, 19, 10, 21).set(10, 18, "D");
g.set(20, 22, "A").set(17, 22, "A").set(10, 20, "A");
g.fill(13, 19, 15, 20).set(14, 21, "A"); // (통로 옆 배전함 칸: 막다른 곳)
g.put("m", [[13, 19], [15, 19]]).set(14, 19, "Z");
// 장비 정비실(문 2개): y15 줄은 비워 둔다(테스트: 괴물이 걸어가는 줄)
g.fill(5, 12, 15, 17).set(4, 15, "D");
g.put("T", [[7, 12], [9, 12], [11, 12]]).put("m", [[5, 17], [6, 17], [14, 17]]).set(15, 12, "Z").set(5, 12, "L").set(12, 17, "c");
// 서쪽 정비 통로 W1(1칸, 아치): 위쪽은 무너져 막혔고 아래로 창고·아래 복도까지
g.fill(3, 11, 3, 37).put("c", [[3, 11], [3, 12]]).set(2, 13, "Z");
g.put("A", [[3, 14], [3, 20], [3, 26], [3, 33]]);
g.fill(1, 22, 2, 24).set(1, 22, "L").set(1, 24, "c"); // (통로 옆 대피 칸)

// ══ 아래 띠 ══
// 창고(선반 줄, 문 3곳)
g.fill(5, 25, 12, 36).set(4, 28, "D").set(13, 28, "D").set(8, 37, "D");
for (const y of [27, 30, 33]) g.wall(7, y, 10, y);
g.put("c", [[5, 25], [12, 25], [12, 36], [5, 34]]).set(12, 31, "Z").set(5, 30, "L").set(5, 36, "Z").set(11, 26, "c");
g.set(14, 28, "."); // 창고 ↔ 작업장 짧은 통로
// 구덩이 작업장(두 번째 큰 공간): 가운데 정비 구덩이 위로 다리, 구덩이 계단, 크레인 기둥
g.fill(15, 24, 27, 36).set(21, 37, "D").set(28, 30, "D");
g.fill(18, 27, 24, 32, "p");
g.fill(18, 29, 24, 29, "b"); // 다리(가로)
g.set(21, 32, "s").set(21, 27, "s"); // 구덩이 계단(다리 남쪽·북쪽 하나씩)
g.put("#", [[17, 26], [25, 26], [17, 34], [25, 34], [21, 25]]);
g.put("m", [[15, 24], [16, 24], [26, 36], [27, 36]]).put("v", [[27, 24], [15, 36]]).set(27, 32, "L").set(15, 31, "Z").set(27, 28, "Z").set(19, 35, "c");
// 냉각 배관 구역: 배관 벽이 줄지어 선 좁은 통로(살짝 미로) — 문 3곳
g.fill(30, 27, 40, 36).set(29, 30, ".").set(41, 31, "D").set(36, 37, "D");
g.wall(32, 29, 38, 29).set(35, 29, "v"); // 배관 벽(가운데 틈)
g.wall(30, 32, 33, 32).wall(35, 32, 40, 32); // 배관 벽(틈 x34)
g.wall(32, 34, 38, 34).set(33, 34, "v"); // 배관 벽(틈 x33)
g.put("v", [[30, 27], [40, 27], [30, 30], [40, 33], [30, 36], [36, 31], [37, 35]]);
g.set(40, 28, "Z").set(30, 33, "L").set(38, 36, "Z").set(40, 36, "c");
// 화물 엘리베이터 홀 → 출구
g.fill(42, 28, 44, 36).set(43, 37, "D");
g.set(45, 32, "E").put("c", [[42, 28], [44, 36]]).set(44, 28, "Z").set(42, 36, "L");
// 아래 복도 C4 (y38~39)
g.fill(2, 38, 43, 39);
g.wall(16, 38, 17, 39).put("c", [[15, 38], [18, 39]]); // 무너진 곳: 창고 → 작업장으로 돌아간다
g.set(25, 40, "L").set(33, 40, "Z").set(1, 39, "c");

if (process.argv.includes("--print")) console.log(g.rows().map((row, i) => String(i).padStart(2) + " " + row).join(String.fromCharCode(10)));
const opts = { blocked: [] };
const r = report("지하 시설", g, opts);
if (!process.argv.includes("--dry"))
	writeStage("Stage1.luau", g, [
		"STAGE 1 — 지하 시설 (47x43칸, tools/places/facility.js 로 생성)",
		"출입 통제 구역(왼쪽 위): 경비 초소(시작)·검문 홀·탈의실·보안 사무실·출입 복도 — 자동 테스트가 쓰는 칸이라 모양을 지킨다.",
		"위 띠(동쪽으로): 통제실(모니터 책상 줄)·기록 보관실(문 2개)·장비실(문 2개)·환기 설비실, 그 아래 본 복도.",
		"가운데 띠(서쪽으로): 발전기 홀(발전기 넷, 콘크리트 기둥, 가장 큰 공간) → 기계실(기계 줄) 또는 1칸 정비 통로 → 장비 정비실.",
		"서쪽 정비 통로(아치)로 내려가 아래 띠(동쪽으로): 창고(선반 줄)·구덩이 작업장(정비 구덩이 위 다리, 구덩이 계단)·",
		"냉각 배관 구역(배관 벽 사이 좁은 통로) 또는 아래 복도 → 화물 엘리베이터(출구).",
		"살짝 뒤틀린 곳: 본 복도 천장이 무너져 기록 보관실로 돌아가고, 서쪽 정비 통로 위쪽은 무너져 막혔으며(출입 복도에서 바로 못 내려감),",
		"아래 복도도 무너져 창고 → 작업장으로 돌아간다. 막다른 방: 환기 설비실·배전함 칸·동쪽 비상 복도 끝·구덩이 바닥.",
		`출구까지 최단 약 ${r.exit}칸.`,
	]);
